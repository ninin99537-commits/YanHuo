// ---------------------------------------------------------------------------
// 去信封: 剥掉上游注入的「工具调用信封」与「响应元信息前缀」, 让解析层看到原本的载荷文本。
//
// 2026-10-16 真机(烟火): 模型吐出来的不是裸 JSON, 而是
//     emit_complete_response_ff5b24e854bfad63f26efccd{content:{"世界":{…}}}
// 上游中转为了"逼模型把话说完"塞了一个工具, 模型就把这次调用**当文本**吐了出来 —— 那串十六进制
// 是每次请求现生成的 nonce。真载荷因此从"顶层对象"降级成"别人的一个值":
//   · 最外那个 `{` 没闭合时, 括号配平切分一个候选都切不出来 → 报"AI 没有返回 JSON 对象";
//   · 最外那个 `{` 闭合时, 收下的就是信封本身(顶层键只剩 content) → 校验层再说结构不符。
// 三个插件的解析器都会被打中(各自的扫描器不同、报错不同, 但都救不回真载荷)。
//
// 2026-10-21 真机(剧情导演): 上游换了另一种污染形状 —— 把响应元信息当正文前置:
//     finishReason: STOP
//     finishMessage: Model generated function call(s).
//     {"章回":{…}}
// 这两行本身不会让括号配平失败(第一个 `{` 在它们后面), 但它们说明模型走的是**函数调用**,
// arguments 被上游当文本塞进了 content。留着这两行只会让报错里的"原始内容"更难读, 而且
// "载荷从 `{` 开始"这个契约对所有上游形状都该成立 —— 所以在这里一并剥掉。
//
// 这一层只做两件事: 剥元信息前缀 + 把信封连前缀一起切掉。剩下的文本就是原本的载荷,
// 后面的括号配平、载荷识别、双解析器择优一个字都不用改。
//
// 注意: **不要**为此放宽各解析器里"值位置的 `{` 不算新候选"那条规则 —— 它是承重的
// (防"截断被从内层 { 切出半截对象、误判成解析成功", 见 烟火/解析.ts 的说明与用例 [10])。
// 去信封加在它**之前**, 是两件不同的事。
// ---------------------------------------------------------------------------

/** 信封 = 标识符 + `{` + 键 `content`(可带引号) + `:`。键名是上游定的, 就这一个。
 *  不锚定行首: 模型常在信封前面先说一句("好的, 结果如下: …"), 那截散文一起丢掉即可。
 *  也不怕误伤合法载荷 —— 判据要求 `{` 前面有个标识符, 而 `{"content": …}` 这种合法载荷没有。 */
const 信封 = /[A-Za-z_$][\w$.-]*\s*\{\s*["']?content["']?\s*:\s*/;

/** 元信息行 = `键: 值`, 键是 ASCII 标识符, 值里**不含 `{`**(否则可能是 `content: {…}` 这类正文)。
 *  行首缩进可有可无; 只在前缀区、且后面紧接 `{` 时才认(见 剥元信息前缀 的守卫)。 */
const 元信息行 = /^[ \t]*[A-Za-z][A-Za-z0-9_.-]{0,40}[ \t]*:[^\r\n{]*$/;

/**
 * 剥掉开头的「响应元信息」行(`finishReason: STOP` / `finishMessage: …` 这类)。
 *
 * 守卫: 整段前缀行之后**必须紧接一个 `{`** 才动手。散文("注意: 别改动"之后的正文)与
 * 合法 JSON(`{"content":…}` 首字符就是 `{`, 不匹配)都不会被误伤。
 * 没命中就**原样返回**(一个字节都不改, 连首尾空白也不动)。
 */
export function 剥元信息前缀(文本: string): string {
  const 首 = 文本.search(/\S/);
  if (首 < 0) return 文本;
  const 行们 = 文本.slice(首).split(/\r?\n/);
  let 用掉 = 0;
  while (用掉 < 行们.length && 元信息行.test(行们[用掉])) 用掉++;
  if (用掉 === 0) return 文本;
  const 余下 = 行们.slice(用掉).join('\n').trimStart();
  // 前缀后面不是 JSON 开头 → 这是散文, 不是元信息, 不动
  if (!余下.startsWith('{')) return 文本;
  return 余下;
}

/**
 * 有信封就剥掉, 没有就**原样返回**(一个字节都不改, 连首尾空白也不动)。
 *
 * 两种形状都收:
 *  1. 载荷**内联**在信封里(`{content:{"世界":…}}`) —— 真机见到的就是这个;
 *  2. 载荷被当成**字符串**传(`{content:"{\"世界\":…}"}`) —— 真工具调用(arguments 是 JSON 串)的样子。
 *
 * 元信息前缀(见 剥元信息前缀)先剥, 再找信封 —— 两层污染可以叠在一起。
 */
export function 去信封(文本: string): string {
  const 去元 = 剥元信息前缀(文本);
  let 命中 = 信封.exec(去元);
  if (!命中) return 去元;
  let 余下 = 去元.slice(命中.index + 命中[0].length);
  // 套了两层信封的也认(上游偶尔会再包一次)
  while ((命中 = 信封.exec(余下))) 余下 = 余下.slice(命中.index + 命中[0].length);
  余下 = 余下.trim();
  if (!余下.startsWith('"')) return 余下;
  // 形状 2: 值是字符串 —— 取出字符串本体再交回去(末尾可能还挂着信封自己的 `}`)
  for (const 候选 of [余下, 余下.replace(/\}\s*$/, '')]) {
    try {
      const 值 = JSON.parse(候选);
      if (typeof 值 === 'string') return 值;
    } catch {
      // 不是"载荷当字符串"的形状, 交给后面的解析层按原文处理
    }
  }
  return 余下;
}

import { klona } from 'klona';
import type { WorldData, WorldEvent, WorldFaction } from './schema';
import type { 世界数据环境, 变更返回 } from './世界数据变更';
import { 保存世界概述, 保存世界条目, 保存事件, 保存势力 } from './世界数据变更';
import type { 世界条目层 } from './世界字段表';
import { 全部字段, 取层 } from './世界字段表';

/**
 * 「世界编辑会话」(候选 5): 面板上四类手动编辑(五层条目 / 事件 / 势力 / 世界概述)的唯一会话。
 *
 * 以前面板里是四份各写一遍的镜像草稿(worldDraft / editDraft / eventDraft / factionDraft),
 * 每份都自己"打开时拷进去、保存时拷出来", 于是同一件事有两份表示(比如 worldEditing 与
 * worldDraft.layer), 靠三处手动同步; 更要紧的是没有"打开时那一条还在不在"的判断, 于是
 * 并发下有三种不报错的失败:
 *   ① 事件保存按**对象引用**定位: AI 推进一次会整棵换掉数据树, 引用当场失效 → 保存静默什么都没发生;
 *   ② 数组层(伏笔/节令)改名后按旧名字找不到就 push → 造出一条重复条目;
 *   ③ 势力保存整对象覆盖 → 把编辑期间刚到的推进结果一起回退掉。
 *
 * 现在只有这一个会话, 四类编辑共用同一套动作:
 *   - 打开: 按「层 + 名字」/ id / 势力名 从**数据仓**取当前那一条作基准(新增时基准为空);
 *   - 比较基准: 基准随会话带着走, 提交时交给那道门只写用户真正改过的字段(不覆盖 AI 的推进);
 *   - 冲突判定: 打开时那一条已经不在数据仓里(被 AI 删了/改名了)就明确报冲突, 不再假装保存成功;
 *   - 提交: 一律回到 世界数据变更.ts 那道门(上限/同名/id 签发/落快照/同步世界书都归它), 它返回
 *     的 说明/拒绝 面板照原样告诉用户——"点了保存什么都没发生"从接口上就不存在;
 *   - 取消: 会话丢掉就是取消(草稿不在数据仓里, 数据与快照一个字都不用动)。
 *
 * 这个 module 不碰平台、不读设置: 存储与世界书同步都走那道门的 世界数据环境。
 */

// ---------------------------------------------------------------------------
// 会话的形状
// ---------------------------------------------------------------------------

/** 在编的是什么: 提交时也按它去数据仓里**重新定位**(绝不按对象引用) */
export type 编辑目标 =
  | { 种类: '条目'; 层: 世界条目层; 键: string }
  | { 种类: '事件'; id: string }
  | { 种类: '势力'; 名: string }
  | { 种类: '概述' };

/** 每一种会话都有的四样: 目标(定位) / 基准(合并基准) / 原稿(打开时的草稿) / 草稿(在编的) */
export interface 会话骨架<草稿, 基准> {
  目标: 编辑目标;
  /** 打开时数据仓里那一条的原值(新增为 null): 提交时"以数据仓为准"跟它比较, 只写真正改过的字段 */
  基准: 基准;
  /** 打开时草稿的样子(深拷贝): 只用来算 会话改过() */
  原稿: 草稿;
  /** 草稿(面板 v-model 直接绑它) */
  草稿: 草稿;
}

/** 五层条目的草稿形状 = 世界编辑表单.vue 的 props, 也是那道门收的 草稿/基准 */
export interface 条目草稿 {
  layer: 世界条目层;
  /** 打开时那一条的名字('' = 新增) */
  key: string;
  fields: Record<string, string>;
}

export interface 条目编辑会话 extends 会话骨架<条目草稿, Record<string, string> | null> {
  目标: { 种类: '条目'; 层: 世界条目层; 键: string };
}

export interface 事件编辑会话 extends 会话骨架<WorldEvent, WorldEvent | null> {
  目标: { 种类: '事件'; id: string };
}

export interface 势力编辑会话 extends 会话骨架<WorldFaction, WorldFaction | null> {
  目标: { 种类: '势力'; 名: string };
}

/** 世界概述(时间/氛围/总览) */
export interface 世界概述 {
  时间: string;
  氛围: string;
  总览: string;
}

export interface 概述编辑会话 extends 会话骨架<世界概述, 世界概述 | null> {
  目标: { 种类: '概述' };
}

export type 任意编辑会话 = 条目编辑会话 | 事件编辑会话 | 势力编辑会话 | 概述编辑会话;

function 文本(值: unknown): string {
  return String(值 ?? '').trim();
}

/** 数据仓里那一条: 映射层按名字取, 数组层按名称键找(与那道门同一口径) */
export function 数据里那一条(数据: WorldData, 层: 世界条目层, 键: string): Record<string, any> | undefined {
  const 定义 = 取层(层);
  if (定义.形态 === '映射') return (数据[层] as Record<string, any> | undefined)?.[键];
  return ((数据[层] as unknown as Record<string, any>[]) ?? []).find(条目 => 条目?.[定义.名称键] === 键);
}

// ---------------------------------------------------------------------------
// 打开草稿
// ---------------------------------------------------------------------------

/** 打开五层里的一条: 键='' 就是新增。字段初值照 世界字段表.ts(枚举字段给第一项), 名字字段回落到点开的名字。 */
export function 打开条目会话(数据: WorldData, 层: 世界条目层, 键 = ''): 条目编辑会话 {
  const 定义 = 取层(层);
  const 名 = 文本(键);
  const 原条目 = 名 ? 数据里那一条(数据, 层, 名) : undefined;
  const fields: Record<string, string> = {};
  for (const f of 全部字段(定义)) {
    const 初始 = 定义.名称键 && f.键 === 定义.名称键 ? 名 : (f.枚举 ? String(f.枚举[0]) : '');
    fields[f.键] = String(原条目?.[f.键] ?? 初始);
  }
  const 草稿: 条目草稿 = { layer: 层, key: 名, fields };
  return {
    目标: { 种类: '条目', 层, 键: 名 },
    基准: 原条目 ? { ...原条目 } : null,
    原稿: klona(草稿),
    草稿,
  };
}

/** 打开一条事件: 基准是点开那一刻的原值, 提交时按 id 回到数据仓里认(老快照没 id 时由那道门按标题兜底) */
export function 打开事件会话(事件: WorldEvent): 事件编辑会话 {
  return {
    目标: { 种类: '事件', id: 文本(事件.id) },
    基准: klona(事件),
    原稿: klona(事件),
    草稿: klona(事件),
  };
}

/** 打开一个势力(名字不在数据仓里时返回 null: 面板那一行多半已经被推进换掉了) */
export function 打开势力会话(数据: WorldData, 名: string): 势力编辑会话 | null {
  const 目标名 = 文本(名);
  const 原势力 = 数据.势力?.[目标名];
  if (!原势力) return null;
  return {
    目标: { 种类: '势力', 名: 目标名 },
    基准: klona(原势力),
    原稿: klona(原势力),
    草稿: klona(原势力),
  };
}

/** 打开世界概述(时间/氛围/总览) */
export function 打开概述会话(数据: WorldData): 概述编辑会话 {
  const 原: 世界概述 = {
    时间: 数据.世界.时间,
    氛围: 数据.世界.氛围,
    总览: 数据.世界.总览,
  };
  return {
    目标: { 种类: '概述' },
    基准: klona(原),
    原稿: klona(原),
    草稿: klona(原),
  };
}

// ---------------------------------------------------------------------------
// 比较基准 / 冲突判定 / 提交 / 取消
// ---------------------------------------------------------------------------

/** 草稿与打开时相比动过没有(没动过也可以保存: 那道门照样落一次快照并给说明, 与以前一致) */
export function 会话改过(会话: 任意编辑会话): boolean {
  return JSON.stringify(会话.草稿) !== JSON.stringify(会话.原稿);
}

/**
 * 打开的那一条还在数据仓里吗? 不在就返回要说给用户的话(没有冲突返回 null)。
 * 新增(基准为空)与老快照里没有 id 的事件不算冲突——前者本来就还没有那一条, 后者交给那道门按标题认。
 */
export function 会话冲突(会话: 任意编辑会话, 数据: WorldData): string | null {
  if (!会话.基准) return null;
  const 目标 = 会话.目标;
  if (目标.种类 === '条目') {
    if (!目标.键) return null;
    return 数据里那一条(数据, 目标.层, 目标.键) ? null : `${目标.层}「${目标.键}」已经不在清单里了, 请重新打开再改`;
  }
  if (目标.种类 === '事件') {
    if (!目标.id) return null;
    return (数据.事件 ?? []).some(事件 => 事件.id === 目标.id) ? null : '这条事件已经不在清单里了, 请重新打开再改';
  }
  if (目标.种类 === '势力') {
    // 与那道门(保存势力/移除势力)同一句文案, 一字不改
    return 数据.势力?.[目标.名] ? null : '这条势力已经不在清单里了';
  }
  return null;
}

/**
 * 提交: 先看冲突(打开时那一条已经不在数据仓里就明确报冲突), 否则交给那道门写。
 * 返回 null 只在"根本没有会话"时出现——面板的保存按钮只在有会话时渲染, 所以按钮按下去必有回音:
 * 要么是 说明(成功), 要么是 拒绝(有话说)。
 */
export function 提交会话(会话: 任意编辑会话 | null, 数据: WorldData, 环境: 世界数据环境): 变更返回 | null {
  if (!会话) return null;
  const 冲突 = 会话冲突(会话, 数据);
  if (冲突) return { 数据, 说明: '', 拒绝: 冲突 };
  const 目标 = 会话.目标;
  if (目标.种类 === '条目') return 保存世界条目(数据, 目标.层, 目标.键, 会话.草稿.fields, 环境, 会话.基准 ?? undefined);
  if (目标.种类 === '事件') return 保存事件(数据, 会话.草稿, 环境, 会话.基准 ?? undefined);
  if (目标.种类 === '势力') return 保存势力(数据, 目标.名, 会话.草稿, 环境, 会话.基准 ?? undefined);
  return 保存世界概述(数据, 会话.草稿, 环境, 会话.基准 ?? undefined);
}

/** 取消: 会话丢掉就是取消(草稿只活在会话里, 数据仓与快照一个字都不用动) */
export function 取消会话(): null {
  return null;
}

/** 解析数字字符串为数值, 非法/缺省按 0 */
function 取数值(value: unknown): number {
    const n = Number(value);
    return Number.isFinite(n) ? n : 0;
}
/** 数值 → 1 位小数字符串("3" / "56.3"), 存进卡片 */
function 格式数值(value: number): string {
    return (Math.round(value * 10) / 10).toFixed(1).replace(/\.0$/, '');
}
/** 舍入到 1 位小数(阶段判定前先归一, 防浮点尾差) */
function 舍入1位(value: number): number {
    return Math.round(value * 10) / 10;
}
/** 舍入到 2 位小数: 系数相乘会留下 4.800000000000001 这类二进制尾差,
 *  收一下让"变化量"与词表里的数值对得上(落库前还会再按 1 位小数格式化) */
function 舍入2位(value: number): number {
    return Math.round(value * 100) / 100;
}
/** 找数值所属的档(表已按区间升序, 不重不漏) */
function 落档阶段(表: { 名: string; 下界: number; 上界: number }[], 值: number): string {
    for (const 档 of 表) {
        if (值 >= 档.下界 && 值 <= 档.上界)
            return 档.名;
    }
    return 值 < 0 ? 表[0].名 : 表[表.length - 1].名;
}
/**
 * 推算一条轴的阶段(±2 滞回, 可跳档)。
 * 保持当前阶段, 除非数值越过当前档边界 2 点(含)以上: 升档 值≥上界+2 / 降档 值≤下界−2;
 * 换档时直接落到数值所属的档。当前阶段无效/缺失时按区间直接落档。
 */
function 推算阶段(轴: string, 值: number, 当前阶段?: string): string {
    const 表 = 轴 === '情欲' ? 情欲阶段表 : 好感阶段表;
    const 数值 = Math.max(0, Math.min(100, 值));
    const 当前档 = 表.find(档 => 档.名 === (当前阶段 ?? '').trim());
    if (!当前档)
        return 落档阶段(表, 数值);
    if (数值 < 当前档.上界 + 阶段滞回 && 数值 > 当前档.下界 - 阶段滞回)
        return 当前档.名;
    return 落档阶段(表, 数值);
}
/** 事件类型的规范名(别名只做兼容) */
function 规范事件类型(类型: string): string {
    const 名 = String(类型 ?? '').trim();
    return 事件类型别名表[名] ?? 名;
}
/**
 * 折算一条数值事件: (事件, 情感倾向枚举名) → { 轴, 变化量 }。
 * 只处理 好感/情欲 两条轴; 名分事件、类型/强度不合法的事件返回 null(丢弃)。
 * 系数怎么乘(策划案 §3.3 v4 定稿): 好感涨/落 × 敏感度; 情欲涨 × 敏感度;
 * 情欲落(满足回落) × 粘性, **不乘敏感度**——否则"外放(1.4)"会变成"性爱之后冷却得更快"。
 */
function 折算事件(事件: any, 情感倾向名: string): { 轴: string; 变化量: number } | null {
    const 轴 = String(事件?.['轴'] ?? '').trim();
    const 类型 = 规范事件类型(String(事件?.['类型'] ?? ''));
    const 强度 = String(事件?.['强度'] ?? '').trim();
    if (轴 !== '好感' && 轴 !== '情欲')
        return null;
    const 系数 = 情感倾向表[情感倾向名] ?? 情感倾向表.常规;
    if (轴 === '好感') {
        const 基础 = 强度表.好感[强度];
        if (基础 === undefined)
            return null;
        if (好感涨事件类型.includes(类型))
            return { 轴, 变化量: 舍入2位(基础 * 系数.敏感度) };
        if (好感落事件类型.includes(类型))
            return { 轴, 变化量: 舍入2位(-基础 * 系数.敏感度) }; // 好感的落事件不乘粘性
        return null;
    }
    if (情欲落事件表[类型]) {
        const 基础 = 情欲落事件表[类型][强度];
        if (基础 === undefined)
            return null;
        return { 轴, 变化量: 舍入2位(基础 * 系数.粘性) };
    }
    if (情欲涨事件类型.includes(类型)) {
        const 基础 = 强度表.情欲[强度];
        if (基础 === undefined)
            return null;
        return { 轴, 变化量: 舍入2位(基础 * 系数.敏感度) };
    }
    return null;
}
/** 应用一条名分事件: (卡, 事件) → 新名分。类型不合法时原样返回当前名分。 */
function 应用名分事件(卡: any, 事件: any): string {
    const 类型 = 规范事件类型(String(事件?.['类型'] ?? ''));
    return 名分事件表[类型] ?? String(卡?.['名分'] ?? '').trim();
}
/** 恋爱标签归一化: 按词表过滤 → 去重(保持顺序) → 截断到上限, 逗号连接返回 */
function 校验标签(原始: string): string {
    const 词 = String(原始 ?? '')
        .split(/[,，、;；]/)
        .map(词 => 词.trim())
        .filter(词 => 词 && 标签词表.includes(词));
    return [...new Set(词)].slice(0, 标签上限).join(',');
}
type 开局结果 = { 好感值?: number; 情欲值?: number; 名分?: string; 依据: string };

/** 从事件数组里挑出开局并校验(§3.9 第 1、2 条)。不接受时返回 null。
 *
 *  依据是入场券, 与名分事件同档: 缺 / 空串 / 全空白 → 整条拒绝。
 *  依据的**来源**与名分事件不同: 名分要求正文原文(两人"说定"了什么只有正文能证明),
 *  开局是回溯**已经存在**的关系, 人设本身就是权威来源——它不需要正文"发生"过。
 *
 *  三个数据键**各自独立**校验: 命中不了的该键作废, 不是整条作废; 三个全作废才整条忽略。 */
function 解析开局(事件列表: any[]): 开局结果 | null {
    const 元素 = (事件列表 ?? []).find(事件 => String(事件?.['轴'] ?? '').trim() === '开局');
    if (!元素)
        return null;
    const 依据 = String(元素?.['依据'] ?? '').trim();
    if (!依据)
        return null;
    const 好感值 = 开局好感值表[String(元素?.['好感'] ?? '').trim()];
    const 情欲值 = 开局情欲值表[String(元素?.['情欲'] ?? '').trim()];
    const 名分原始 = String(元素?.['名分'] ?? '').trim();
    const 名分 = 名分词表.includes(名分原始) ? 名分原始 : undefined;
    if (好感值 === undefined && 情欲值 === undefined && 名分 === undefined)
        return null;
    return { 好感值, 情欲值, 名分, 依据 };
}

/**
 * 恋爱回合结算(整个恋爱数值流水线, 策划案 §3.5): 逐条折算事件 → **按方向分桶** →
 * 只夹涨桶 → 时间回落并入落桶 → 涨后(夹 0–100) → 情欲按地板**截断回落**(不抬升) →
 * 重算阶段 → 写恋爱动向。
 *
 * 纯函数: 不修改入参, 返回**要写回卡的字段补丁**; 调用方(mergeCard)负责 Object.assign。
 * 惰性补齐: 卡上没有 情感倾向 按常规, 没有 恋爱基准日期 按本轮剧情日期(首次不回落)。
 * 本轮剧情时间缺失/非法时跳过时间回落, 且不更新基准日期("没有依据就不动手")。
 *
 * 分桶顺序(§3.5 v5): 先分桶、只夹涨桶、再让落桶相抵——若先净额相抵再夹, 同轮的落事件会
 * 掩盖超上限的涨(涨 +24 与落 −10 → 净额 +14 没超上限, 于是 +24 逃掉了上限)。
 * 地板(§3.6 v4): 实际回落量 = min(|落桶|, max(0, 涨后情欲 − 地板)), 地板按**结算后**的
 * 好感阶段取。地板是"冷却后的稳态"而不是磁铁——情欲低于地板时回落不生效, 但也不会被抬到地板。
 */
function 应用恋爱回合(卡: Record<string, any>, 事件列表: any, storyTimeText: string): Record<string, any> {
    const 补丁: Record<string, any> = {};
    // 惰性补齐: 情感倾向
    const 倾向名 = 情感倾向表[String(卡?.['情感倾向'] ?? '').trim()] ? String(卡['情感倾向']).trim() : '常规';
    if (!String(卡?.['情感倾向'] ?? '').trim())
        补丁['情感倾向'] = '常规';
    const 名分未落 = !String(卡?.['名分'] ?? '').trim();
    const 事件数组 = Array.isArray(事件列表) ? 事件列表 : [];
    // 开局(§3.9 第 1 条): 两道闸同时成立才接受。
    // 第二道「恋爱动向为空」是防迟到乱开——已经跑了几十轮、有变化记录的 NPC,
    // 不会被一个错报的开局直接跳到恋人档。
    const 开局窗口 = String(卡?.['恋爱开局'] ?? '').trim() !== '是'
        && String(卡?.['恋爱动向'] ?? '').trim() === '';
    const 开局 = 开局窗口 ? 解析开局(事件数组) : null;
    // 惰性补齐(第五样): 开局只填**缺省**, 绝不覆盖已有值——玩家手改优先。
    // ⚠️ 判"卡上没有"必须看空串: 取数值 对缺失返回 0, 那不是缺失信号, 是"值就是 0"。
    const 好感缺省 = String(卡?.['好感值'] ?? '').trim() === '';
    const 情欲缺省 = String(卡?.['情欲值'] ?? '').trim() === '';
    const 旧好感 = 好感缺省 && 开局?.好感值 !== undefined ? 开局.好感值 : 取数值(卡?.['好感值']);
    const 旧情欲 = 情欲缺省 && 开局?.情欲值 !== undefined ? 开局.情欲值 : 取数值(卡?.['情欲值']);
    let 名分 = 名分未落 ? (开局?.名分 ?? '无') : String(卡['名分']).trim();
    // 接受开局就关窗(§3.9 第 5 条): 即使三个数据键全被卡上已有值挡住, 标记照写——
    // 窗口该关了, 再问是重复骚扰。解析开局 返回 null(依据非法/三键全作废)则什么都不写,
    // 标记不写、窗口保持开着(下一轮 AI 还能再报)。
    // ⚠️ 已知缺口(已回报策划): 漏报那一轮代码照旧把 好感值 落成 '0', 于是下一轮再报开局时
    // "只填缺省"这条闸已经不成立——窗口是开着的, 但那 86 补不进去了(用例 [10] 第 6 条钉住该行为)。
    const 开局生效行: string[] = [];
    if (开局) {
        补丁['恋爱开局'] = '是';
        if (好感缺省 && 开局.好感值 !== undefined)
            开局生效行.push(`好感开局 ${格式数值(开局.好感值)}(${开局.依据})`);
        if (情欲缺省 && 开局.情欲值 !== undefined)
            开局生效行.push(`情欲开局 ${格式数值(开局.情欲值)}(${开局.依据})`);
        if (名分未落 && 开局.名分 !== undefined)
            开局生效行.push(`名分开局 ${开局.名分}(${开局.依据})`);
    }
    // 剧情时间: 取结束时刻的日历日; 缺失/非法 → 本轮不做时间回落, 也不更新基准日期
    const range = parseStoryTimeRange(storyTimeText);
    const 本轮日期ts = range.endTs !== null ? dateOnlyTs(range.endTs) : null;
    let 基准ts: number | null = null;
    if (本轮日期ts !== null) {
        const 基准raw = String(卡?.['恋爱基准日期'] ?? '').trim();
        const 基准parsed = 基准raw ? parseStoryTime(基准raw) : null;
        基准ts = 基准parsed !== null ? dateOnlyTs(基准parsed) : null;
    }
    // 逐条事件: 名分走独立通道, 数值按**方向分桶**(§3.5 v5)
    // 两条轴都必须分桶: 若先净额相抵再夹上限, 同轮的落事件会掩盖超上限的涨
    // (例: 情欲涨 +24 与落 −10, 净额 +14 没超 +20, 于是 +24 完全逃掉上限)
    let 好感涨变化 = 0;
    let 好感落变化 = 0; // 负数
    let 情欲涨变化 = 0;
    let 情欲落变化 = 0; // 负数
    // §3.9 第 4.5 条(空轮不落库): 判"该轴本轮有没有事件"看的是**折算命中过没有**, 不是净额——
    // +3 与 −3 相抵后净额是 0, 但事件确实发生过, 这一轮该轴就该落值(落 '0' 是正确结果)。
    let 好感有事件 = false;
    let 情欲有事件 = false;
    const 好感类型: string[] = [];
    const 情欲类型: string[] = [];
    let 名分变化: { 名分: string; 类型: string; 依据: string } | null = null;
    for (const 事件 of 事件数组) {
        if (!事件 || typeof 事件 !== 'object' || Array.isArray(事件))
            continue;
        const 轴 = String(事件['轴'] ?? '').trim();
        if (轴 === '开局')
            continue; // 开局已在上面消费掉, 不进数值/名分通道(显式分支: 防以后有人把"开局"加进事件表)
        // 「依据」必须指向正文里真实发生的事(§3.4 v7): 名分事件**硬性**(缺依据整条拒绝),
        // 数值事件**软性**(缺依据仍折算, 只提醒)——数值是渐变量, 全丢弃会让恋爱数值完全不涨。
        // 校验放在这里而不是 折算事件/应用名分事件 里: 那两个是纯映射, 校验与告警收在流水线一处。
        const 依据 = String(事件['依据'] ?? '').trim();
        if (轴 === '名分') {
            const 新名分 = 应用名分事件({ 名分 }, 事件);
            if (新名分 && 新名分 !== 名分) {
                if (!依据) {
                    console.warn(`[彼方] 恋爱名分事件缺「依据」, 已拒绝该事件(名分不变): ${规范事件类型(String(事件['类型'] ?? ''))}`);
                    continue;
                }
                名分 = 新名分;
                名分变化 = {
                    名分: 新名分,
                    类型: 规范事件类型(String(事件['类型'] ?? '')),
                    依据,
                };
            }
            continue;
        }
        const 折算 = 折算事件(事件, 倾向名);
        if (!折算)
            continue;
        if (!依据)
            console.warn(`[彼方] 恋爱数值事件缺「依据」(仍按事件折算): ${轴}·${规范事件类型(String(事件['类型'] ?? ''))}`);
        if (折算.轴 === '好感') {
            好感有事件 = true;
            if (折算.变化量 > 0)
                好感涨变化 += 折算.变化量;
            else
                好感落变化 += 折算.变化量;
            const 类型 = 规范事件类型(String(事件['类型'] ?? ''));
            if (!好感类型.includes(类型))
                好感类型.push(类型);
        }
        else if (折算.轴 === '情欲') {
            情欲有事件 = true;
            if (折算.变化量 > 0)
                情欲涨变化 += 折算.变化量;
            else
                情欲落变化 += 折算.变化量;
            const 类型 = 规范事件类型(String(事件['类型'] ?? ''));
            if (!情欲类型.includes(类型))
                情欲类型.push(类型);
        }
    }
    // 只夹涨桶(落桶不设限, 让满足回落表达充分)——夹在"两桶相抵"之前, 落掩盖不了超限的涨
    if (好感涨变化 > 0)
        好感涨变化 = Math.min(好感涨变化, 单轮上限.好感);
    if (情欲涨变化 > 0)
        情欲涨变化 = Math.min(情欲涨变化, 单轮上限.情欲);
    // 时间回落(仅情欲): 跨天数 × 速率 × 粘性(不乘敏感度, 与满足回落同一条通道); 基准缺失(首轮)不回落
    if (本轮日期ts !== null && 基准ts !== null) {
        const 跨天数 = Math.max(0, Math.round((本轮日期ts - 基准ts) / 86400000));
        const 回落 = 跨天数 * 时间回落速率 * (情感倾向表[倾向名] ?? 情感倾向表.常规).粘性;
        if (回落 !== 0) {
            情欲落变化 -= 回落;
            const 回落成因 = `时间回落${跨天数}天`;
            if (!情欲类型.includes(回落成因))
                情欲类型.push(回落成因);
        }
        // 基准日期只前进不倒退(照 生理周期日期 的既有约定): 剧情时间倒退/同刻时保留旧基准
        if (本轮日期ts >= 基准ts)
            补丁['恋爱基准日期'] = fmtStoryTime(range.endTs);
    }
    else if (本轮日期ts !== null && 基准ts === null) {
        补丁['恋爱基准日期'] = fmtStoryTime(range.endTs); // 首次落基准, 本轮不回落
    }
    // 应用变化: 两条轴都是"涨后 + 落桶"(§3.5 第 7–9 步); 好感阶段定在该值之后(地板按**结算后**阶段取)
    const 旧好感阶段 = String(卡?.['好感阶段'] ?? '').trim();
    const 涨后好感 = Math.max(0, Math.min(100, 旧好感 + 好感涨变化));
    const 新好感 = Math.max(0, Math.min(100, 涨后好感 + 好感落变化)); // 好感无地板截断
    const 新好感阶段 = 推算阶段('好感', 舍入1位(新好感), 旧好感阶段 || undefined);
    // 情欲: 涨后 → 地板 → 实际回落 = min(|落桶|, max(0, 涨后 − 地板))**只截断回落, 不抬升**
    const 涨后情欲 = Math.max(0, Math.min(100, 旧情欲 + 情欲涨变化));
    const 地板 = 情欲地板表[新好感阶段] ?? 0;
    const 实际回落 = Math.min(-情欲落变化, Math.max(0, 涨后情欲 - 地板));
    const 新情欲 = Math.max(0, Math.min(100, 涨后情欲 - 实际回落));
    // 重算阶段(每轮都算, ±2 滞回: 手改的值阶段会自动跟上, 手改的阶段在滞回区间内被尊重)
    // 但**写不写进补丁**要过「有值才写」的闸(§3.9 第 4.5 条, v10 裁决): 空轮不落库。
    // 三条闸分别判、阶段跟随值(同进同出); 计算一律照旧执行——动向的净额与地板都依赖它们。
    // 为什么按轴判而不是"本轮无事就全不写": 后者会让"手改 好感值 后阶段自动跟上"失效
    // (那一轮正好没事件时, 阶段就不重算了)——`卡上该字段非空` 那一项正好兜住它。
    // 为什么不是"缺省判据放宽成 取数值 === 0": 那会覆盖玩家手改的 0, 破"绝不覆盖"。
    const 开局好感落值 = 好感缺省 && 开局?.好感值 !== undefined;
    const 开局情欲落值 = 情欲缺省 && 开局?.情欲值 !== undefined;
    const 好感有值 = String(卡?.['好感值'] ?? '').trim() !== '' || 开局好感落值 || 好感有事件;
    const 情欲有值 = String(卡?.['情欲值'] ?? '').trim() !== '' || 开局情欲落值 || 情欲有事件;
    // 名分: **只在真的变了或本轮开局填了它时才写**(v10 裁决 2 收紧)。
    // 为什么不像好感那样带上"卡上非空"那一项: 好感有伴生字段(阶段必须跟值同进同出), 名分没有——
    // 卡上已有名分时把同一个值写回去是空转(mergeCard 遇同值等于没变), 只会把
    // "名分事件被拒 ⇒ 补丁不带 名分"这条强断言削弱成"值没被改", 是净损失。
    // 后果自查: 卡上已有名分 / 本轮回空 → 都不写, mergeCard 沿用旧值, 最终卡片一致。
    const 名分有值 = 名分变化 !== null || 开局?.名分 !== undefined;
    if (好感有值)
        补丁['好感值'] = 格式数值(新好感);
    if (情欲有值)
        补丁['情欲值'] = 格式数值(新情欲);
    if (好感有值)
        补丁['好感阶段'] = 新好感阶段;
    if (情欲有值)
        补丁['情欲阶段'] = 推算阶段('情欲', 舍入1位(新情欲), String(卡?.['情欲阶段'] ?? '').trim() || undefined);
    if (名分有值)
        补丁['名分'] = 名分;
    // 恋爱动向: 开局行排在前(它是基线), 增量行排在后(同轮既有开局又有事件时两段都在),
    // 都没有变化就不写(保留上一行)
    const 动向: string[] = [...开局生效行];
    const 好感净 = 舍入1位(新好感) - 舍入1位(旧好感);
    if (好感净 !== 0 && 好感类型.length > 0)
        动向.push(`好感${好感净 > 0 ? '+' : '−'}${格式数值(Math.abs(好感净))}(${好感类型.join('·')})`);
    const 情欲净 = 舍入1位(新情欲) - 舍入1位(旧情欲);
    if (情欲净 !== 0 && 情欲类型.length > 0)
        动向.push(`情欲${情欲净 > 0 ? '+' : '−'}${格式数值(Math.abs(情欲净))}(${情欲类型.join('·')})`);
    if (名分变化)
        动向.push(`名分→${名分变化.名分}(${名分变化.依据})`); // 依据必填, 没有兜底(§3.4 v7)
    if (动向.length > 0) {
        let 行 = 动向.join(' / ');
        if (本轮日期ts !== null) {
            const d = new Date(本轮日期ts);
            const pad = (n: number) => String(n).padStart(2, '0');
            行 += ` · ${String(d.getFullYear()).padStart(4, '0')}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
        }
        补丁['恋爱动向'] = 行;
    }
    return 补丁;
}


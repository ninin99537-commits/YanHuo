console.log('\n[11] 面板机制那三个依赖(推进中/推进文案/中断推进)确实传进去了');
{
  // 机制模块声明的依赖名, 与界面调用点传的名字对得上才算接线存在(真机上"推进"按钮切"中断"靠的就是这条线)
  const 声明 = /export interface 面板机制依赖\s*\{([\s\S]*?)\}/.exec(面板机制源)?.[1] ?? '';
  const 依赖名 = [...声明.matchAll(/^\s*([^\s:]+)\s*:/gm)].map(匹配 => 匹配[1]);
  check('机制模块声明了三个依赖', 依赖名, ['推进中', '推进文案', '中断推进']);

  const 调用处 = /使用面板机制\(\{([\s\S]*?)\}\)/.exec(vueSource)?.[1] ?? '';
  ok('界面调用了机制模块', 调用处.length > 0);
  for (const 名 of 依赖名) ok(`界面把「${名}」传进去了`, new RegExp(`(^|\\n)\\s*${名}\\s*:`).test(调用处));
  ok('推进中接的是更新 store 的 active', /推进中:\s*updatingActive\b/.test(调用处));
  ok('推进文案接的是更新 store 的 message', /推进文案:\s*updatingMessage\b/.test(调用处));
  ok('中断推进接的是 store 的取消', /中断推进:\s*\(\)\s*=>\s*updatingStore\.cancel\(\)/.test(调用处));
  ok('机制模块是从 面板机制 引进来的', vueSource.includes("import { 使用面板机制 } from './面板机制'"));
}


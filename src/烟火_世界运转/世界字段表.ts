// ---------------------------------------------------------------------------
// 字段清单的三种切法
// ---------------------------------------------------------------------------

/** 表的全部字段: 映射层把「名称」补在最前(它在数据里是键, 不在条目里), 数组层的名称字段本来就在表里 */
export function 全部字段(层: 世界层定义): 字段定义[] {
  if (层.形态 === '数组' || !层.名称键) return [...层.字段];
  return [{ 键: 层.名称键, 标签: 层.名称键 }, ...层.字段];
}

/** 内容字段: 不含名称那一条(保存条目 / 规范化 / 沿用 都用这一串) */
export function 内容字段(层: 世界层定义): 字段定义[] {
  return 层.字段.filter(字段 => 字段.键 !== 层.名称键);
}

/** 内容字段的键(给 normalizeLayer 这类按字段数组干活的函数) */
export function 内容字段键(层: 世界层定义): string[] {
  return 内容字段(层).map(字段 => 字段.键);
}

export function 字段标签(字段: 字段定义): string {
  return 字段.标签 ?? 字段.键;
}

// ---------------------------------------------------------------------------
// 界面表单: 世界编辑表单.vue 要的 { key, label, enum, multiline }
// ---------------------------------------------------------------------------

export interface 表单字段 {
  key: string;
  label: string;
  enum?: readonly string[];
  multiline?: boolean;
}

/** 一层的表单字段(= 以前界面手抄的 layerFields 那一份) */
export function 表单定义(层: 世界层定义): 表单字段[] {
  return 全部字段(层).map(字段 => ({
    key: 字段.键,
    label: 字段标签(字段),
    enum: 字段.枚举,
    multiline: 字段.多行,
  }));
}

// ---------------------------------------------------------------------------
// 取值与规范化
// ---------------------------------------------------------------------------

function 文本(值: unknown): string {
  return String(值 ?? '').trim();
}

/** 「无变化」类占位词(AI 对未变化的滚动总结字段可能填这些, 不该覆盖旧值)。
 *  事件与势力共用这一份; 判断按**原值**(不去空白)进行, 与以前一致。 */
const 占位词正则 = /^(无|没有|无变化|没有变化|无明显变化|暂无变化|依旧|照旧|维持原状|不变|同上|同前|略)[。．.!！?？…\s]*$/;

export function 占位词(值: unknown): boolean {
  return 占位词正则.test(String(值 ?? ''));
}

/** 取字段原始值: 先看本名, 再看旧快照名与 AI 别名(都是"值不为 null/undefined 就用它") */
function 取原始(字段: 字段定义, 原: Record<string, unknown>): unknown {
  if (原[字段.键] != null) return 原[字段.键];
  for (const 名 of 字段.旧名 ?? []) {
    if (原[名] != null) return 原[名];
  }
  for (const 名 of 字段.别名 ?? []) {
    if (原[名] != null) return 原[名];
  }
  return undefined;
}

/** 一个字段的最终值: 去首尾空白 + 枚举越界纠偏(保存条目 / 快照 / AI 规范化共用同一把尺) */
export function 字段值(字段: 字段定义, 值: unknown): string {
  const 文本值 = 文本(值);
  if (!字段.枚举) return 文本值;
  const 兜底 = 字段.兜底 ?? 字段.枚举[0];
  return (字段.枚举 as readonly string[]).includes(文本值) ? 文本值 : 兜底;
}

/**
 * 规范化一条(快照 / 已校验过的 AI 载荷): 缺字段补空串、旧字段名迁移、枚举纠偏, 键的顺序照表。
 * 形状由表保证, 所以调用方按自己那一层的类型收口, 例如 规范化条目<WorldMetric>(指标层, 原)。
 */
export function 规范化条目<T extends object = Record<string, string>>(
  层: 世界层定义,
  原: Record<string, unknown> | undefined,
): T {
  const 源 = 原 ?? {};
  const 条目: Record<string, string> = {};
  for (const 字段 of 层.字段) 条目[字段.键] = 字段值(字段, 取原始(字段, 源));
  return 条目 as unknown as T;
}

/**
 * AI 载荷里的一条: 字段缺失(或漏带别名里的任何一个)沿用旧值; 占位沿用 的字段填占位词时也沿用旧值。
 * 只给「名称→字段」的常驻档案用(势力清单); 事件/伏笔/节令各有自己的沿用规矩, 不在这里。
 */
export function 沿用条目<T extends Record<string, string> = Record<string, string>>(
  层: 世界层定义,
  原: Record<string, unknown>,
  旧: Record<string, unknown> | undefined,
): T {
  const 条目: Record<string, string> = {};
  for (const 字段 of 层.字段) {
    const 原始 = 取原始(字段, 原);
    const 旧值 = 文本(旧?.[字段.键]);
    const 值 = 字段.占位沿用 && 占位词(原始) ? 旧值 : 文本(原始) || 旧值;
    条目[字段.键] = 字段值(字段, 值);
  }
  return 条目 as T;
}

// ---------------------------------------------------------------------------
// 注入给主 AI 的竖线表(表头 / 数据行 / 这一条要不要进表)
// ---------------------------------------------------------------------------

/** 注入表头: 「层 | 列…」 */
export function 注入表头(层: 世界层定义): string {
  return [层.标签, ...(层.注入列 ?? [])].join(' | ');
}

/** 注入表的一行(与表头列对位): 空值填「—」(与以前一样按原值判空, 不去空白) */
export function 注入行(层: 世界层定义, 名: string, 条目: Record<string, any>): string {
  return [名, ...(层.注入列 ?? []).map(列 => (条目[列] ? String(条目[列]) : '—'))].join(' | ');
}

/** 这一条要不要进注入表: 有判据看判据(任一非空), 没判据看名字 */
export function 该注入(层: 世界层定义, 条目: Record<string, any>): boolean {
  const 判据 = 层.注入判据;
  if (!判据 || 判据.length === 0) return Boolean(条目[层.名称键]);
  return 判据.some(键 => Boolean(条目[键]));
}

// ---------------------------------------------------------------------------
// 提示词: SYSTEM_PROMPT 里那段 JSON 模板
// ---------------------------------------------------------------------------

/** JSON 模板里一个字段的示例: 枚举填兜底值, 其余填 "..." */
function JSON字段(字段: 字段定义): string {
  const 示例值 = 字段.枚举 ? (字段.兜底 ?? 字段.枚举[0]) : '...';
  return `"${字段.键}":"${示例值}"`;
}

/** JSON 模板里的一层: 映射层给「示例名 → 字段」(名字当键, 不再是条目里的字段), 数组层给一个条目对象 */
export function 提示词JSON示例(层: 世界层定义): string {
  if (层.形态 === '数组') return `"${层.名}":[{${全部字段(层).map(JSON字段).join(',')}}]`;
  const 字段 = 内容字段(层).map(JSON字段).join(',');
  return `"${层.名}":{"${层.示例名 ?? 层.名称键}":{${字段}}}`;
}

// 彼方 · 事务台账: NPC 的「未完成事项」从"每轮重写的一句话"升级为**只增不改的账**。
//
// 为什么要有这一层(真实事故): 幕后决定"给女儿买一个玩偶当生日礼物", 推了几轮进正文后
// 变成了"蛋糕"——"每轮重写的一句话"没有任何锚点, 具体名词全靠模型每轮自觉复述, 一轮记错
// 就永久错下去, 之后所有轮次都拿错的那份当"上一轮"。台账把"要做什么"在写下那一刻冻结:
// 编号由代码分配, **内容一旦入库就只由写下它的那一轮决定**, 之后任何轮次都只能改它的
// 状态与结果; 想改内容就必须作废旧条、另开一条新条(于是"玩偶变蛋糕"这件事在数据里留痕)。
//
// 对外契约(界面/提示词/合并各用一处, 类型名与函数名不许改):
//   读取台账(卡里的值)                    → 规范化成数组(旧格式字符串在这里迁移成 T1)
//   合并台账(旧台账, 本轮返回值, 剧情时间)  → 纯函数, 返回新台账(不改入参)
//   渲染台账(记录)                         → 注入给主 AI / 界面展示的可读文本
//
// 合并规则(全部要点都在这八条里, 见 合并台账 内的逐条注释):
//   1 新增(本轮没编号 / 编号是库里没有的新值)→ 由代码分配下一个编号, 不复用;
//   2 改写无效(编号已存在)→ 只接受 状态/结果, 内容/时间一律以库里为准;
//     提示词教模型"已有事务只写「编号 + 状态(+结果)」, 内容不用重抄", 所以**没有内容字段的载荷
//     必须被收下**(曾经被整条丢掉 → "AI 按编号标完成"落不了地);
//     结果只在状态给的是 已完成/已作废 时才落(进行中/没给状态都不收, 免得旧脏结果日后冒充"办成了什么");
//     状态与结果**确实变了**才算一次合并动作(什么都没变 → 按第 6 条原样不动, 不封顶);
//   3 内容重复(去掉空白标点后相同)→ **认作"匹配到那条已有事务"**(不再静默丢弃): 按第 2 条只收它的
//     状态/结果, 但**只接受收束方向**——进行中→终态、或终态→终态(视为修正); 终态→进行中一律忽略。
//     为什么只给一个方向: 指纹命中是"靠内容猜出指的是哪一条"(不是明示指名), 而 归一一条 对**缺状态**
//     的载荷默认填"进行中"——不加这道闸, `{内容:"买菜"}` 撞上一条已完成的"买菜"就会把旧账复活。
//     没有任何变化的重复载荷照旧整条不动(模型每轮重抄整份台账是幂等的), 也不顺带封顶;
//   4 封顶 8 条: 超了先淘汰最旧的 已作废/已完成, "进行中"永不淘汰;
//   5 迁移: 旧字符串 → 一条进行中(内容一字不改, 时间尽量认);
//   6 本轮什么都没返回 → 原样不动; 空数组也不删已有记录(没有删除路径, 只靠状态收束);
//   7 空意思(整句就是 无/暂无/没有/…, 见 是空意思)→ 不是事务: 旧值读成空账, 新增整条丢弃;
//   8 幽灵编号(编号查无此人且没有内容)→ 无事可做, 直接丢弃, 不重建成空内容的新事务。

export type 事务状态 = '进行中' | '已完成' | '已作废';
export type 幕后事务 = {
    编号: string;
    时间: string;
    内容: string;
    状态: 事务状态;
    结果?: string;
};

/**
 * 台账诊断(**可选出参**, 只服务于日志, 不参与任何判定): 台账里有三条路径是"静默"的,
 * 静默正是排查困难的原因, 所以让调用方能把它们汇总成一行日志。
 *
 * 为什么要调用方传进来而不是在这里 console.warn: 本函数是纯函数(用例直接跑, 不该刷屏),
 * 且日志需要 NPC 名字——名字只有调用方(mergeCard/applyUpdate)知道。调用方在合并前
 * `新建台账诊断()`, 合并后按名字打一行汇总。
 */
export type 台账诊断 = {
    /** 规则3: 因内容重复而**没有新增成新条目**的载荷条数(被认作某条已有事务) */
    重复丢弃: number;
    /** 其中命中"终态条目"的条数——偏可疑(可能是一条新承诺被当旧账吃掉了) */
    重复命中终态: number;
    /** 方向守卫拦下的"终态复活"尝试(命中条编号) */
    复活拦截: string[];
    /** 时间锚纪律的温度计: 新条目内容里仍是相对时间词、且没有绝对日期的(不拦截, 只留痕) */
    相对锚: string[];
};

/** 新建一份空的诊断(调用方在每次合并前建一份) */
export function 新建台账诊断(): 台账诊断 {
    return { 重复丢弃: 0, 重复命中终态: 0, 复活拦截: [], 相对锚: [] };
}

/** 三项合法状态(校验/归一都按它) */
const 事务状态表: 事务状态[] = ['进行中', '已完成', '已作废'];
/** 每个 NPC 最多保留的事务条数; "进行中"永不淘汰(见 封顶)。导出给提示词用: 账况标注要显示同一个数字 */
export const 台账上限 = 8;
/** 注入里"最近已办"摘要最多取几条 */
const 已办摘要条数 = 3;
/** 编号形状: T + 数字(数字部分才是"新旧"与排序的依据) */
const 编号正则 = /^T(\d+)$/;
/** 能认出来的日期: 2025-09-18 / 2025/9/18 / 2025.9.18 / 2025年9月18日 */
const 日期正则 = /(\d{4})\s*[-/.年]\s*(\d{1,2})\s*[-/.月]\s*(\d{1,2})\s*日?/;
/** 注入末尾的固定提醒: 台账里的事是"已定的事实", 主 AI 收束正文时必须照此兑现 */
const 事实提醒 = '以上是幕后已发生/已定的事实，正文收束时必须照此兑现；其中的具体物品、人名、地点不得替换或泛化。';

/** 从文本里认出**第一个**日期并补零成 YYYY-MM-DD(剧情时间给的是时间段时取开始那天); 认不出返回空串 */
function 取日期(文本: unknown): string {
    const match = String(文本 ?? '').match(日期正则);
    if (!match)
        return '';
    return `${match[1]}-${match[2].padStart(2, '0')}-${match[3].padStart(2, '0')}`;
}

/** 状态归一: 只认三个枚举值; 认不出返回空串(调用方决定是丢弃还是按"进行中"兜底) */
function 归一状态(value: unknown): 事务状态 | '' {
    const 文本 = String(value ?? '').trim();
    return 事务状态表.includes(文本 as 事务状态) ? 文本 as 事务状态 : '';
}

/** 编号数字: "T3" → 3; 认不出返回 null(空编号、乱编号都算"认不出") */
function 编号数字(编号: unknown): number | null {
    const match = String(编号 ?? '').trim().match(编号正则);
    return match ? Number(match[1]) : null;
}

/** 编号归一: 数字按 T{数字} 处理; 小写 t1 也认(模型偶尔写小写) */
function 归一编号(value: unknown): string {
    if (typeof value === 'number' && Number.isFinite(value))
        return `T${value}`;
    return String(value ?? '').trim().replace(/^t(?=\d)/i, 'T');
}

/** 去重指纹: 去掉空白与标点(只留文字与数字), 于是 "给女儿买一个玩偶。" 与 "给女儿买 一个玩偶" 是同一条 */
function 内容指纹(内容: unknown): string {
    return String(内容 ?? '').replace(/[^\p{L}\p{N}]/gu, '');
}

/**
 * 时间锚纪律的**固定小词表**(只作温度计用, 不拦截任何写入)。
 * 为什么词表永远不完备、所以不能当验收线: "洗完澡后" 这种事件锚根本不在任何时间词表里
 * (它正是台账核心事故 T6 的锚), 词表漏掉的相对锚一律查不出来——它只用来估计"纪律执行得怎么样"。
 */
const 相对时间词表 = ['明天', '今晚', '明早', '后天', '改天', '过几天', '周末', '下周', '下次'];
/** 内容里有没有**绝对日期**("10-18" / "2025-10-18" / "10月18日" 都算; 有它就不算"只有相对锚") */
const 绝对日期正则 = /\d{1,4}\s*[-/.年月]\s*\d{1,2}(\s*[-/.月]\s*\d{1,2}\s*日?)?/;

/** 这条新内容是不是"只有相对时间词、没有绝对日期"(时间锚纪律的判定; 见 相对时间词表) */
export function 缺绝对锚(内容: unknown): boolean {
    const 文本 = String(内容 ?? '');
    return 相对时间词表.some(词 => 文本.includes(词)) && !绝对日期正则.test(文本);
}

/**
 * "没有待办"的**完整**表达(白名单, 只做精确匹配, 见 是空意思)。
 * 真机事故: 旧版「未完成事项」用整句 `无` 表示"没有待办", 迁移时被当成一条真事务,
 * 变成 `T1 进行中：无` —— "进行中"永不淘汰, 这句废话于是永久挂在账上、还跟着注入给主 AI。
 */
const 空意思表 = new Set([
    '无',
    '暂无',
    '没有',
    '空',
    '-',
    '—',
    'none',
    'n/a',
    '无未完成事项',
    '暂无未完成事项',
]);

/**
 * 这句"内容"是不是"没有待办"的意思(迁移脏值 / 模型照着旧格式写回来的 `无`)。
 * 判据是**精确匹配**: 先 trim、去掉尾部的句号/顿号, 再与白名单逐字对比(英文大小写不敏感);
 * 空串与纯空白也算。
 *
 * 故意**不用**"包含 无 字"这种模糊判据: `无薪加班`、`无名指上的戒指`、`交涉无果` 都是真内容,
 * 必须原样当一条事务留着 —— 只有整句恰好就是上面那几个词才叫"没有待办"。
 */
function 是空意思(内容: unknown): boolean {
    const 文本 = String(内容 ?? '').trim().replace(/[。、]+$/u, '').trim();
    return !文本 || 空意思表.has(文本.toLowerCase());
}

/** 把一条乱七八糟的记录规范成事务; 认不出"要做什么"(既没内容又没编号, 或整句是"没有待办")
 *  → null, 整条丢掉。纯函数: 一律构造新对象, 不改入参。 */
function 归一一条(raw: unknown): 幕后事务 | null {
    // 旧格式(整句字符串): 内容一个字不改(只去首尾空白), 时间从字符串里认, 状态按"进行中"
    if (typeof raw === 'string') {
        const 内容 = raw.trim();
        if (!内容 || 是空意思(内容))
            return null;
        return { 编号: '', 时间: 取日期(raw), 内容, 状态: '进行中' };
    }
    if (!raw || typeof raw !== 'object' || Array.isArray(raw))
        return null;
    const 源 = raw as Record<string, unknown>;
    const 内容 = String(源['内容'] ?? '').trim();
    const 编号 = 归一编号(源['编号']);
    // 收下的条件: 认得出"要做什么"(有内容)**或**"改哪一条"(有合法编号)。
    // 提示词(prompts.ts)明确教模型: 已有事务只回「编号 + 状态(+结果)」, 内容不用重抄
    // (重抄的内容会被丢弃)—— 所以有编号时必须放行空内容, 它的内容在合并阶段从库里取
    // (规则2: 内容/时间一律以库里为准)。过去这里要求"必须有内容", 于是"AI 按编号标完成"
    // 这条链整条不通: 这种载荷被丢掉, 事务永远停在"进行中"。
    // 既没内容又没编号 = 认不出要做什么, 整条丢掉。
    if (!内容 && !编号)
        return null;
    const 时间原文 = String(源['时间'] ?? '').trim();
    const 事务: 幕后事务 = {
        编号,
        时间: 时间原文 ? (取日期(时间原文) || 时间原文) : '',
        内容,
        状态: 归一状态(源['状态']) || '进行中',
    };
    const 结果 = String(源['结果'] ?? '').trim();
    if (结果)
        事务.结果 = 结果;
    return 事务;
}

/** 台账里下一个可用的编号数(现有最大编号 + 1; 没有编号时从 1 起) */
function 下一个编号数(台账: 幕后事务[]): number {
    let 最大 = 0;
    for (const 事务 of 台账)
        最大 = Math.max(最大, 编号数字(事务.编号) ?? 0);
    return 最大 + 1;
}

/**
 * 规则4 封顶: 每个 NPC 最多 台账上限(8) 条。超了**先淘汰最旧的已办**(已作废/已完成),
 * "进行中"永不淘汰——哪怕全部都是进行中、超过 8 条也照留(未了结的事不能因为条数被丢掉)。
 * "最旧"按台账顺序(数组前面 = 更早写下), 不是按时间字段(时间可能是空的)。
 */
function 封顶(台账: 幕后事务[]): 幕后事务[] {
    if (台账.length <= 台账上限)
        return 台账;
    const 保留 = [...台账];
    for (let i = 0; i < 保留.length && 保留.length > 台账上限;) {
        if (保留[i].状态 === '进行中') {
            i++;
            continue;
        }
        保留.splice(i, 1);
    }
    return 保留;
}

/**
 * 把卡里的值(旧格式字符串 / 数组 / 乱七八糟)规范成台账; **永远返回数组**。
 * - 字符串 → 一条"进行中"(规则5: 内容一字不改, 时间取能认出的日期, 认不出留空);
 *   但整句恰好是"没有待办"(无/暂无/…, 见 是空意思)→ **空账 []**(不造事务);
 * - 数组/对象 → 逐条规范: 认得出的编号原样保留, 没有编号或编号重复的按最大编号递增补号;
 * - 认不出内容的条目(空串/数字/布尔等)直接丢掉 —— "有编号却没内容"的残迹也在这里丢掉
 *   (合并阶段才放行那种形状, 见循环里的注释)。
 * 纯函数: 返回全新对象, 不改入参。读取两次结果一致(界面/合并都能安全地用)。
 */
export function 读取台账(value: unknown): 幕后事务[] {
    const 原始条目: unknown[] = Array.isArray(value) ? value : [value];
    const 台账: 幕后事务[] = [];
    const 已用编号 = new Set<number>();
    // 第一遍: 逐条规范, 认得出的编号原样保留; 重复/非法编号先留空, 第二遍统一补号
    for (const 条目 of 原始条目) {
        const 事务 = 归一一条(条目);
        if (!事务)
            continue;
        // 卡上的值里"有编号却没内容"的条目是残迹(合并结果永远不会产出它: 新增必须有内容,
        // 改写只动状态/结果)—— 读取阶段照旧丢掉, 免得渲染出 `T1 进行中：` 这种幽灵行。
        // 归一一条 为合并阶段放行了这种形状(提示词教模型"只回编号+状态"), 两处口径不同是故意的:
        // 入场券(本轮载荷)要宽, 落库/展示(卡上的值)要严。
        if (!事务.内容)
            continue;
        const 数字 = 编号数字(事务.编号);
        if (数字 !== null && !已用编号.has(数字)) {
            已用编号.add(数字);
            事务.编号 = `T${数字}`;
        }
        else {
            事务.编号 = '';
        }
        台账.push(事务);
    }
    // 第二遍: 没编号的按"现有最大编号 + 1"补, 不复用已用编号
    for (const 事务 of 台账) {
        if (!事务.编号)
            事务.编号 = `T${下一个编号数(台账)}`;
    }
    return 台账;
}

/**
 * 合并本轮模型返回的事务, 返回**新台账**(纯函数, 不改入参)。规则逐条见下:
 *   1 新增: 本轮没有编号、或编号是库里没有的新值 → 视为新事务, 由代码分配下一个编号
 *     (按现有最大编号递增, 不复用; 时间取本次剧情时间的日期, 认不出才用模型给的时间);
 *   2 改写无效: 编号已存在 → **只接受它的 状态 与 结果**, 它带来的 内容/时间 一律丢弃。
 *     这是故意的: 内容里点的具体名词(玩偶/人名/地点)写下即冻结, 为了钉住它不被后续轮次
 *     换成同类物或泛化词; 要改内容只能作废旧条、另开新条。
 *     提示词就是这么教模型的("已有事务只写「编号 + 状态(+结果)」, 内容不用重抄"), 所以
 *     **没有"内容"字段的载荷在这里必须被收下**——过去 归一一条 要求必须有内容, 这种载荷
 *     被整条丢掉, 于是"AI 按编号标完成"根本落不了地(事务永远停在"进行中")。
 *     其中**结果只在状态给的是 已完成/已作废 时才落**: 状态没给或还是"进行中"就不收结果
 *     (与新增路径、台账操作.ts 的 改一条事务 同一口径)。否则模型随手写的"进行中 + 结果"会
 *     留在账上, 等这条日后真被标成已完成、那轮又没给新结果时, 已办那行按 `结果 || 内容`
 *     会把那句旧脏结果当成"办成了什么"显示给用户(错账)。
 *     状态/结果**确实变了**才算一次合并动作(规则4 才会顺带封顶); 什么都没变 → 按第 6 条原样不动。
 *   3 内容重复: 本轮带内容的载荷若与库里某条(任意状态)的内容"去掉空白与标点"后完全相同,
 *     **不新增**, 而是认作"匹配到了那一条已有事务"→ 按第 2 条只收它的 状态/结果。
 *     但只接受**收束方向**(进行中→终态、终态→终态视为修正); 终态→进行中一律忽略 —— 指纹命中
 *     是"靠内容猜出指的是哪一条", 不是明示指名, 而 归一一条 对缺状态的载荷默认填"进行中",
 *     不设这道闸, `{内容:"买菜"}` 撞上已完成的"买菜"就会把旧账复活。
 *     状态/结果确实变了才算一次合并动作(否则纯重抄会顺带封顶, 让旧账凭白老化)。
 *   4 封顶: 见 封顶;
 *   5 迁移: 旧值(字符串)在读取阶段就变成一条 T1 进行中, 内容一字不改;
 *   6 本轮什么都没返回(undefined/null/空数组/认不出任何条目)→ 台账**原样不动**(连封顶也不做:
 *     "不删已有记录"优先); 反正删除路径不存在——事务只能靠状态收束, 靠封顶淘汰旧已办。
 *   7 空意思: 本轮**新增**的事务, 内容恰好是"没有待办"(无/暂无/…, 见 是空意思)一律丢弃、不入账
 *     (模型有时照着旧格式把 `无` 当一条写回来); 丢弃后若本轮再无别的变化, 按第 6 条原样不动。
 *     已有事务只按第 2 条收 状态/结果, 内容写什么都不影响它。
 *   8 幽灵编号: 编号查无此人(被封顶淘汰/模型写错)**且**没有内容 → 无事可做, 直接丢弃:
 *     既不能改谁的状态, 也没有内容可以新开一条; **不**重建成空内容的新事务(那会造出
 *     `T1 进行中：` 这种幽灵行)。带内容的"新编号"仍按第 1 条入账(重新分配编号)。
 */
export function 合并台账(旧台账: 幕后事务[], 本轮: unknown, 剧情时间: string, 诊断?: 台账诊断): 幕后事务[] {
    // 库先规范化(旧卡可能是旧格式字符串/脏数组); 纯函数: 归一一条 全部构造新对象
    const 库 = 读取台账(旧台账);
    const 结果 = [...库];
    const 本轮条目: unknown[] = Array.isArray(本轮) ? 本轮 : [本轮];
    let 收到记录 = false;
    for (const 条目 of 本轮条目) {
        const 候选 = 归一一条(条目);
        if (!候选)
            continue;
        const 候选编号 = 编号数字(候选.编号);
        // 规则2: 编号已存在 → 只收 状态/结果; 内容/时间丢弃, 以库里的为准(故意, 见函数注释)
        const 命中 = 候选编号 === null ? undefined : 结果.find(事务 => 事务.编号 === 候选.编号);
        if (命中) {
            const 新状态 = 归一状态(候选.状态);
            // 结果只对"完成/作废"有意义: 状态没给、或给的还是"进行中", 都不落结果
            // (与下面新增路径同一口径; 台账操作.ts 的 改一条事务 也是这个口径)。
            // 为什么必须收口: 否则模型随手写的"进行中 + 结果"会留在账上 —— 等这条以后真被标成
            // 已完成、而那一轮没给新结果时, 已办那行按 `结果 || 内容` 渲染, 会把那句旧脏结果
            // 当成"办成了什么"摆到用户面前(错账), 而不是这条事务真正的内容。
            const 新结果 = 新状态 && 新状态 !== '进行中' ? 候选.结果 : '';
            let 改了 = false;
            if (新状态 && 新状态 !== 命中.状态) {
                命中.状态 = 新状态;
                改了 = true;
                // 状态改回「进行中」= **重开**这条(编号指名与面板同权, 见 台账操作.ts 的 改一条事务)。
                // 重开时把旧结果一并清掉: 结果只对"完成/作废"有意义, 留着它, 等这条日后被重新标成
                // 已完成而那轮没给新结果时, 已办那行按 `结果 || 内容` 渲染, 会把上一轮的旧结果
                // 当成"办成了什么"摆给用户(与上面那段注释同一个错账, 只是晚了一轮才发作)。
                if (新状态 === '进行中' && 命中.结果 !== undefined)
                    delete 命中.结果;
            }
            if (新结果 && 新结果 !== 命中.结果) {
                命中.结果 = 新结果;
                改了 = true;
            }
            // 只有**确实改了**才算一次合并动作(规则4 才会顺带封顶); 什么都没变 → 按规则6 原样不动。
            // 否则"本轮只回了一条毫无变化的事务"也会顺带封顶, 让旧账凭白老化(淘汰最旧的已办)。
            收到记录 = 收到记录 || 改了;
            continue;
        }
        // 规则1 之前的两道闸(都在 收到记录 之前: 丢弃后若本轮再无别的变化, 按规则6 原样不动)——
        //   ① 空意思: 模型照着旧格式把 `无`/`暂无` 当一条写回来 → 它不是真事务;
        //   ② 没内容: 编号查无此人、又没有内容可开新条(模型引用了已被封顶淘汰/写错的编号)
        //      → 无事可做: 既不能改谁的状态, 也没有内容可以新开一条。**绝不**把它重建成
        //      "空内容的新事务"(那会造出 `T1 进行中：` 这种幽灵行)。
        // 注意: "编号 + 状态(+结果)"这种没有内容的载荷, 只要编号在库里, 上面的 命中 已经收下了。
        if (!候选.内容 || 是空意思(候选.内容))
            continue;
        // 规则3: 内容与库里某条相同(去空白标点)→ **不新增**, 但认作"匹配到了那一已有事务",
        // 按规则2 只收它的 状态/结果 —— 模型"重抄内容 + 改了状态"这种手滑因此能落地(它还带出
        // 今天那个更坏的后果: 过去这里直接 continue, 而 `收到记录` 已在上面置真, 于是"整份重抄"
        // 会顺带封顶、静默淘汰最旧终态)。现在 收到记录 挪到"确定要新建"之后, 纯重抄不再封顶。
        const 指纹 = 内容指纹(候选.内容);
        // 在 **结果** 里找(不是 库): 结果 含"本轮前面几条刚刚新入账的条目", 同一轮里重复写两遍同一件事
        // 因此仍然只入账一条(旧实现扫的就是 结果, 保持幂等)
        const 同内容 = 指纹 ? 结果.find(事务 => 内容指纹(事务.内容) === 指纹) : undefined;
        if (同内容) {
            const 新状态 = 归一状态(候选.状态);
            const 新结果 = 新状态 && 新状态 !== '进行中' ? 候选.结果 : '';
            if (诊断) {
                诊断.重复丢弃++;
                if (同内容.状态 !== '进行中')
                    诊断.重复命中终态++;
            }
            // 方向守卫: 指纹命中只是"靠内容猜出指的是哪一条"→ 只接受**收束方向**。
            // 进行中→终态、终态→终态(视为修正)放行; 终态→进行中(含缺状态时的默认"进行中")忽略。
            // 要重开一条终态事务, 走"编号指名"(规则2, 与面板按钮同权)或"作废旧条 + 另开新条"。
            if (!新状态 || 新状态 === '进行中' || 新状态 === 同内容.状态) {
                if (新状态 === '进行中' && 同内容.状态 !== '进行中' && 诊断)
                    诊断.复活拦截.push(同内容.编号);
                continue;
            }
            同内容.状态 = 新状态;
            if (新结果 && 新结果 !== 同内容.结果)
                同内容.结果 = 新结果;
            收到记录 = true;
            continue;
        }
        收到记录 = true;
        // 时间锚纪律的温度计(只留痕, 不拦写入): 新条目仍用相对时间词且没有绝对日期
        if (诊断 && 缺绝对锚(候选.内容))
            诊断.相对锚.push(候选.内容);
        // 规则1: 新事务由代码分配编号(库里没有的编号也算新事务, 重新分配); 时间以本次剧情时间为准
        const 新事务: 幕后事务 = {
            编号: `T${下一个编号数(结果)}`,
            时间: 取日期(剧情时间) || 候选.时间,
            内容: 候选.内容,
            状态: 候选.状态,
        };
        // 结果只对"完成/作废"有意义(进行中写结果属于噪声, 不落库)
        if (候选.状态 !== '进行中' && 候选.结果)
            新事务.结果 = 候选.结果;
        结果.push(新事务);
    }
    // 规则6: 本轮一条可识别的记录都没有(undefined/null/空数组/乱七八糟)→ 原样不动, 不删已有记录
    if (!收到记录)
        return 库;
    // 规则4: 真正发生合并动作时才顺带封顶(超额的旧"已办"在这里收敛)
    return 封顶(结果);
}

/**
 * 本轮**未回票**的「进行中」编号 —— 表态率与注入降级标记的唯一判据。
 *
 * = 卡上全部进行中编号 − 本轮载荷里**命中库中编号**的集合。三条口径:
 * - "命中"**含改了和没改**: 模型回 `{编号, 状态:'进行中'}` 是"我确认它还在", 算表态
 *   (合并侧同样是 no-op, 但账面上它被过问了);
 * - **幽灵编号不计票**(库里没有的编号), 免得一个写错的编号掩盖真正的漏票;
 * - 只按**旧台账**(本轮合并前)算: 这一轮谁被过问, 与合并之后的结果无关。
 *
 * 为什么需要它: 合并规则 6 让"没被提到的条目原样继续", 这在数据上是对的, 但**看不见**——
 * 系统能看见"没投票", 看不见"假投票"(每条都回继续却没真看); 前者能数, 就把它数出来。
 */
export function 未回票编号(旧台账: 幕后事务[], 本轮: unknown): string[] {
    const 库 = 读取台账(旧台账);
    const 库编号 = new Set(库.map(事务 => 事务.编号));
    const 本轮条目: unknown[] = Array.isArray(本轮) ? 本轮 : [本轮];
    const 已表态 = new Set<string>();
    for (const 条目 of 本轮条目) {
        const 候选 = 归一一条(条目);
        if (!候选 || !库编号.has(候选.编号))
            continue;
        已表态.add(候选.编号);
    }
    return 库
        .filter(事务 => 事务.状态 === '进行中' && !已表态.has(事务.编号))
        .map(事务 => 事务.编号);
}

/** "最近已办"的排序: 时间倒序(空时间排最后); 同一天按编号倒序(后写下的在前) */
function 按时间倒序(a: 幕后事务, b: 幕后事务): number {
    const 甲 = 取日期(a.时间) || a.时间;
    const 乙 = 取日期(b.时间) || b.时间;
    if (甲 !== 乙) {
        if (!甲)
            return 1;
        if (!乙)
            return -1;
        return 甲 < 乙 ? 1 : -1;
    }
    return (编号数字(b.编号) ?? 0) - (编号数字(a.编号) ?? 0);
}

/**
 * 注入给主 AI / 界面显示的可读文本:
 *   ① 所有「进行中」按编号顺序一行一条: `T1 进行中（2025-09-18 起）：给女儿买一个玩偶当生日礼物`;
 *   ② 最近 3 条已办(已完成/已作废, 按时间倒序)压成一行: `已办：T0 买了玩偶（2025-09-18）`;
 *   ③ 最后一句固定提醒(具体物品/人名/地点不得替换或泛化)。
 * 台账为空(含空数组/脏值)时返回空串 —— 调用方按"空则整行不出现"处理。
 *
 * `未回票` = 本轮没被模型过问的进行中编号(`未回票编号()` 算出来), 命中时给那一行加
 * 「本轮未表态，待确认」——只降**力**不降**命**: 该条仍在账上、仍会注入, 只是不再被主 AI
 * 当"必须兑现的铁律"。它是**逐轮临时**的标记(调用方临时传参, 不落库), 所以面板与切聊天后
 * 重写世界书都不会带上它——语义正确: 它描述的只是"这一轮"。
 */
export function 渲染台账(记录: 幕后事务[], 未回票: readonly string[] = []): string {
    const 台账 = 读取台账(记录);
    const 未回票集 = new Set(未回票);
    const 进行中 = 台账
        .filter(事务 => 事务.状态 === '进行中')
        .sort((a, b) => (编号数字(a.编号) ?? 0) - (编号数字(b.编号) ?? 0));
    const 已办 = 台账
        .filter(事务 => 事务.状态 !== '进行中')
        .sort(按时间倒序)
        .slice(0, 已办摘要条数);
    const 行: string[] = 进行中.map(事务 => {
        const 括注 = [
            事务.时间 ? `${事务.时间} 起` : '',
            未回票集.has(事务.编号) ? '本轮未表态，待确认' : '',
        ].filter(Boolean).join('；');
        return `${事务.编号} ${事务.状态}${括注 ? `（${括注}）` : ''}：${事务.内容}`;
    });
    if (已办.length > 0) {
        const 摘要 = 已办
            .map(事务 => `${事务.编号} ${事务.结果 || 事务.内容}${事务.时间 ? `（${事务.时间}）` : ''}`)
            .join('；');
        行.push(`已办：${摘要}`);
    }
    if (行.length === 0)
        return '';
    行.push(事实提醒);
    return 行.join('\n');
}

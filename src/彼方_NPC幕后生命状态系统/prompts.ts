/**
 * 渲染注入表: **一次表头 + 每行一个 NPC**, 列集**动态**。
 *
 * 为什么不照抄烟火的固定列集(世界字段表.ts 的 注入表头/注入行): 烟火的层是**同构**的——
 * 每层一个固定小列集, 每条档案都有全部列, 所以 "—" 几乎不出现。彼方的卡是**异构**的:
 * 19 个候选字段里每个 NPC 只占其中一部分(生理列仅非男性且生理监测开着, 恋爱列仅被标记的),
 * 固定列集会在"生理监测关掉、只标记了一个人"的聊天里产出大半张 "—" 的表, 比旧写法还费 token。
 * 所以只保留"本次注入的 NPC 里至少有一个非空"的列, 无值的格子才填 "—"(与烟火同款占位)。
 *
 * 兜底: 一个字段都没有时(理论上不该出现), 退回旧的 "- 名字 | 状态未知" 单行写法。
 */
function 渲染注入表(npcEntries: [string, Record<string, any>][], 未回票?: Record<string, string[]>): string {
    const 行 = npcEntries.map(([名, 卡]) => ({
        名: 注入取值(名),
        值: 注入表列.map(列 => 列.取(卡 ?? {}, 名, 未回票)),
    }));
    const 保留 = 注入表列.map((_, i) => i).filter(i => 行.some(r => r.值[i]));
    if (保留.length === 0)
        return 行.map(r => `- ${r.名} | 状态未知`).join('\n');
    const 表头 = ['名字', ...保留.map(i => 注入表列[i].列)].join(' | ');
    const 数据行 = 行.map(r => [r.名, ...保留.map(i => r.值[i] || '—')].join(' | '));
    return [表头, ...数据行].join('\n');
}

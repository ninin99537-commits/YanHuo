/** 跨日事实行的措辞(四态: 首次推进 / 跨了 k 日 / 未跨日 / 不可判定)。
 *  **只有"真跨了"那一态才提"大跳"**——另三态若也提, 请求体就成了"给你大跳额度, 但你没跨日"的自相矛盾。 */
function 跨日事实行(跨日: TickInput['跨日']): string {
  if (跨日 === '首次')
    return '首次推进(没有上轮世界时间, 本轮不计跨日)——先建立 世界.时间, 新增按【运转密度】里的"每轮新增上限"计。';
  if (!跨日)
    return '无法判定(上次世界时间的日期解析不出来, 本插件不按世界日计时)——按上面那份时间约束办事, 新增按【运转密度】里的"每轮新增上限"计。';
  if (跨日.最多 <= 0)
    return '未跨日——世界.时间的日期必须沿用上次日期; 新增按【运转密度】里的"每轮新增上限"计。';
  const 跨了 = 跨日.最少 === 跨日.最多 ? `${跨日.最少}` : `${跨日.最少}~${跨日.最多}`;
  return `跨 ${跨了} 世界日——正文已明确写出跳跃, 【运转密度】里的大跳额度生效。`;
}


// 共用 · 楼层快照内核
// ---------------------------------------------------------------------------
// ── 这个模块解决什么 ──
//
//  三个插件（彼方 / 烟火 / 剧情导演）都在做同一件事：
//  把「当前状态」整体写进某个楼层的**楼层变量**，再用聊天变量里的一份轻量索引
//  （`快照楼层: number[]`）记住"哪几层存过快照"。读的时候从最新往旧扫，找第一份有效的。
//
//  这套「索引 + 有效性判定 + 裁剪 + 清理」在三处各写了一遍。
//  **每一处补丁都只补到一处** —— 这是今天最贵的一类重复。
//
// ── 接口只有四件事 ──
//
//   取最新有效的一份(存储, 末层) -> 载荷 | null
//   取最近 K 份(存储, K)          -> 载荷[]
//   写一份并登记(存储, 载荷, 锚层) -> { ok } | { ok:false, 原因 }
//   清空(存储)                    -> void
//
// ── 载荷形状与"什么算有效"由调用方给策略 ──
//
//  三家载荷不同（彼方是 NPC 名单，烟火是世界数据，导演是账本），
//  所以内核**不碰载荷内部**：只要求它有一个 `楼层` 字段（用来校验"这份快照属于这一层"）。
//  "什么算有效"（世代一致 / 清空截止 / 排除楼层 …）由调用方传 `有效?` 判定。
//
// ── 不变量（从三家实现里合并）──
//
//  | # | 不变量 | 谁守过 |
//  |---|---|---|
//  | 1 | 索引里只留"楼层存在且快照键匹配"的层 | 三家都有 |
//  | 2 | 聊天未就绪（末层 <0 / 抛错）→ **一个字节不写** | 烟火有、导演有、彼方 11-20 补 |
//  | 3 | 层号 ≤ 末层却读不到 = 平台异常 → 不清 | 只有彼方有 |
//  | 4 | 层号 > 末层 = 真被截短 → 删这条 | 三家都有 |
//  | 5 | 登记失败 = 这次快照白写 → 返回失败 | 导演有，**彼方缺**（丢 saveMeta 返回值） |
//  | 6 | 裁剪到 K 份，保留最近的 K | 三家都有 |
//  | 7 | 删楼后编号重排的认领 | 彼方有（**搬进内核但默认不启用**） |
//
// ── 关于 #7「认领」：为什么做成"带开关的能力"而不是"统一启用" ──
//
//  验收的裁定（2026-11-20，需求方 #433 采纳）：
//
//  > 算统一，**条件是**：① 认领只有一份实现，开关只决定"调不调用"
//  > ② 开关语义写死在接口上、每家接入时**显式声明**，不许隐式默认
//  > ③ 理由写进内核注释
//  >
//  > **统一的对象是"代码"，不是"行为"。**
//
//  理由展开：强制统一启用会让内核替导演/烟火引入它们**从来没有过**的新行为 ——
//  那才是真正的第二个漂移点（用户会在两个插件里看到莫名其妙的状态"被认领"）。
//
//  所以本内核**只提供** `取最近K份` 这个能力（"从新到旧取出多份"），
//  **不实现认领本身** —— 认领要不要做、认领哪一份、认领后怎么改写，都是彼方自己的事，
//  留在 `彼方/快照.ts` 里。导演/烟火**不调用**它，行为与现在完全一致。
//
// ── 刻意**不做**的事 ──
//
//  · **不碰载荷内部**：内核不知道彼方的 NPC 长什么样，也不知道烟火的世代是什么。
//  · **不改调用方的策略**：认领（#7）只给彼方用，烟火/导演不启用 —— 它们的行为不许变。
//  · **不做迁移**：三家各自的老结构迁移留在各自模块里（那是它们自己的历史）。

import { klona } from 'klona';

/** 一份快照至少要有 `楼层` —— 用来校验"这份快照属于这一层"。其余字段内核不看。 */
export type 快照载荷 = { 楼层: number } & Record<string, any>;

/** 聊天变量里那份轻量索引（三家同名同形，这就是能共用的原因） */
export type 快照索引 = {
    /** 存过快照的楼层号（升序由内核维护，调用方不用自己排） */
    快照楼层: number[];
} & Record<string, any>;

/**
 * 楼层快照的"存储"抽象 —— 内核只通过这个接口碰平台。
 *
 * 三家各自的 host 形状不同（彼方 `host.vars` / 烟火 `useHost().vars` / 导演 `useHost().vars`），
 * 所以这里只要求**最小的那几件事**，调用方用一行适配器接上。
 */
export type 快照存储 = {
    /** 读聊天变量里那份索引（读不到返回 null，内核会当成空索引） */
    读索引: () => 快照索引 | null;
    /** 写索引；返回是否写成功 —— **这是不变量 5 的落点** */
    写索引: (索引: 快照索引) => boolean;
    /**
     * **这一楼还在不在**（`chat.messages(楼层)` 有没有内容）。
     *
     * ⚠ 这与"楼层变量里有没有快照"是**两件事**：
     *   · 消息不在 → 楼层被删了（或聊天没就绪）→ 不变量 3/4 判它
     *   · 消息在、但变量里没快照 → **正常**（重 roll 产生的新 swipe 页）→ 继续往前找
     *   把两者混成一个"读不到"，会把正常情况误判成平台异常。
     */
    楼层还在: (楼层: number) => boolean;
    /** 读某楼层的快照本体（读不到返回 null = 这一层没存过东西，**正常**） */
    读楼层: (楼层: number) => 快照载荷 | null;
    /** 写某楼层的快照本体（整体赋值，避免深合并残留） */
    写楼层: (楼层: number, 载荷: 快照载荷) => void;
    /** 删某楼层的快照本体（楼层可能已不存在，实现方要自己吞掉这种错） */
    删楼层: (楼层: number) => void;
    /** 当前聊天末层；**抛错或 < 0 表示聊天还没就绪**（不变量 2 的判据） */
    末层: () => number;
};

/** 读的策略：调用方告诉内核"什么算有效" */
export type 读取策略 = {
    /**
     * 这份快照算不算有效（除"楼层存在 + 楼层号匹配"之外的额外条件）。
     *
     * 例：烟火要校验世代一致、导演要排除某些楼层、彼方要跳过清空层之前的。
     * **不传 = 只要楼层号对得上就算有效。**
     */
    有效?: (载荷: 快照载荷, 楼层: number) => boolean;
    /** 跳过这一层（不算"已删"，只是不选它）—— 如彼方的 excludeFloor */
    跳过?: (楼层: number) => boolean;
    /** 裁剪上限（不传 = 不裁剪） */
    保留份数?: number;
};

/** 读取结果：数据 + 这次判出来的"该从索引里删掉哪些层" */
export type 读取结果 = {
    /** 找到的那份（null = 一份有效的都没有） */
    载荷: 快照载荷 | null;
    /** 它来自哪一层（-1 = 没有） */
    楼层: number;
    /** 这次判成"楼层真的被删了"的层（调用方决定要不要真删，内核已按不变量 2/3 保守处理） */
    已删楼层: number[];
    /** 聊天还没就绪（调用方据此"先按空展示，等就绪再读"） */
    未就绪: boolean;
    /**
     * **平台状态可疑**：出现了"楼层号在末层之内、却读不到消息"的层。
     *
     * 这说明平台/接口在抽风 —— 此刻**任何写盘都不安全**（包括认领）。
     * 调用方拿到 true 时应该**什么都不做**，等下次再判。
     */
    平台状态可疑: boolean;
    /**
     * **楼层号对不上的候选**（删楼后编号重排）。
     *
     * 内核自己**不认领**（那是彼方特有的行为，见文件头的裁定），
     * 但把"哪些楼层上有快照、只是里面记的楼层号是旧的"交出来 ——
     * 调用方据此自己决定认不认领、认哪一份。
     *
     * 导演/烟火不看这个字段，行为与现在完全一致。
     */
    编号对不上: Array<{ 楼层: number; 载荷: 快照载荷 }>;
};

/**
 * 读索引（容错：读不到 / 形状怪 → 空索引）。
 *
 * 三家原实现都做这件事，但细节不同（烟火会 filter 非数字、彼方也是、导演也是）。
 * 统一在这里做：**只认有限数字**，其余丢掉。
 */
function 归一索引(原始: 快照索引 | null | undefined): 快照索引 {
    const 楼层们 = Array.isArray(原始?.快照楼层)
        ? 原始!.快照楼层.filter((x): x is number => typeof x === 'number' && Number.isFinite(x))
        : [];
    return { ...(原始 ?? {}), 快照楼层: 楼层们 } as 快照索引;
}

/**
 * 取最新有效的一份。
 *
 * ── 三条护栏（不变量 2 / 3 / 4）──
 *
 *  ① **聊天未就绪**（`末层()` 抛错或 < 0）且索引非空
 *     → 直接返回"未就绪"，**一个字节都不写**。
 *     为什么：那一刻每一层都读不到，若按"读不到 = 已删"处理会把索引整个清空，
 *     用户看到的是"打开聊天，数据没了"。**丢的是全部状态，而且不报错。**
 *
 *  ② **楼层号 ≤ 末层却读不到** → 判成"平台异常"，**不清这条索引**。
 *     为什么：那个位置应该有消息，却读不到 —— 自相矛盾，只能是接口临时抽风。
 *     判错一次就是永久丢失，而"多留一次"只是下次再判一遍。**代价不对称。**
 *
 *  ③ **楼层号 > 末层** → 聊天被截短了（`/cut`、删尾），那些楼层真的没了 → **该删**。
 */
export function 取最新有效(存储: 快照存储, 策略: 读取策略 = {}): 读取结果 {
    const 索引 = 归一索引(存储.读索引());
    const 楼层们 = [...索引.快照楼层].sort((a, b) => a - b);

    const 末层 = (() => {
        try {
            return 存储.末层();
        }
        catch {
            return -1;
        }
    })();

    // ── 护栏①：聊天未就绪 → 一个字节都不写 ──
    //
    //  ⚠ **判据是 `<= 0`，不是 `< 0`**（2026-11-20 硬化，需求方 #443）。
    //
    //  `< 0` 会漏掉 `lastMessageId() === 0` 这一档：`0 >= 0` 成立 → 走正常路径
    //  → 索引里所有 `> 0` 的楼层被判成"超出末层 = 真被截短" → **全删光**。
    //  那正是导演原来那个洞的成因之一（它只看 `lastId < 0`）。
    //
    //  ── 为什么 0 也该当"未就绪" ──
    //  "聊天只有第 0 层、却索引着 1/2/3 层"在真实场景里只有两种可能：
    //    · **平台异常**（返回了假末层，聊天还没真正加载完）
    //    · **聊天真的重开了** —— 那时聊天变量是新作用域，索引本该是**空的**
    //  两种都不该删。第一种删了就丢数据；第二种索引非空本身就说明不是这种情况。
    //
    //  ── `清空层` 不为 0 的情况单独想过 ──
    //  如果聊天真被清空过、只剩第 0 层：清空时 `清空层` 被写成当时的末层，
    //  且索引被重置成空。所以"清空层非 0 + 索引非空 + 末层 0"这个组合
    //  在正常路径上不会出现 —— 出现了就还是平台异常，同样不该删。
    //
    //  代价：多留一次索引，下次再判。判错一次是永久丢失。**代价不对称。**
    if (楼层们.length > 0 && !(末层 > 0)) {
        return { 载荷: null, 楼层: -1, 已删楼层: [], 未就绪: true, 平台状态可疑: false, 编号对不上: [] };
    }

    const 已删楼层: number[] = [];
    /** 出现过"楼层在范围内却读不到" —— 本次一律不清索引（不变量 3） */
    let 平台状态可疑 = false;
    /** 楼层号对不上的候选（删楼重排）—— 内核不认领，交回调用方 */
    const 编号对不上: Array<{ 楼层: number; 载荷: 快照载荷 }> = [];

    for (let i = 楼层们.length - 1; i >= 0; i--) {
        const 楼层 = 楼层们[i];
        if (策略.跳过?.(楼层))
            continue;

        // ── 护栏③：超出末层 = 真的被删了 ──
        if (楼层 > 末层) {
            已删楼层.push(楼层);
            continue;
        }

        // ── 护栏②：楼层号在末层之内、但**消息**读不到 ──
        //
        //  那个位置**应该有消息**，却读不到 → 自相矛盾，只能是接口临时抽风。
        //  判错一次就是永久丢失，而"多留一次"只是下次再判一遍。**代价不对称。**
        if (!存储.楼层还在(楼层)) {
            平台状态可疑 = true;
            continue;
        }

        // 消息在、但楼层变量里没快照 → **正常**（重 roll 的新 swipe 页）→ 继续往前
        const 载荷 = 存储.读楼层(楼层);
        if (!载荷 || typeof 载荷 !== 'object')
            continue;

        // 楼层号对不上（删楼后编号重排）→ 不是有效的一份，但也不算已删
        // 收集起来交给调用方（彼方据此认领；导演/烟火不看它）
        if (载荷.楼层 !== 楼层) {
            编号对不上.push({ 楼层, 载荷 });
            continue;
        }

        if (策略.有效 && !策略.有效(载荷, 楼层))
            continue;

        return {
            载荷: klona(载荷),
            楼层,
            已删楼层: 平台状态可疑 ? [] : 已删楼层,
            未就绪: false,
            平台状态可疑,
            编号对不上,
        };
    }

    // 走完了都没找到 —— 这时才处理"已删"
    //
    // ⚠ 只有在**没有出现平台异常**时才真的清。出现过的，宁可留着下次再判。
    if (平台状态可疑) {
        return { 载荷: null, 楼层: -1, 已删楼层: [], 未就绪: false, 平台状态可疑: true, 编号对不上 };
    }
    return { 载荷: null, 楼层: -1, 已删楼层, 未就绪: false, 平台状态可疑: false, 编号对不上 };
}

/**
 * 取最近 K 份（从新到旧），供"近期轨迹 / 跨轮 diff"这类需要多份的场景。
 *
 * 与 `取最新有效` 用同一套有效性判定 —— 两处不能各判一套，否则"最新那份有效但 K 份里没有它"。
 */
export function 取最近K份(存储: 快照存储, K: number, 策略: 读取策略 = {}): 快照载荷[] {
    const 索引 = 归一索引(存储.读索引());
    const 楼层们 = [...索引.快照楼层].sort((a, b) => a - b);
    const 结果: 快照载荷[] = [];

    const 末层 = (() => {
        try {
            return 存储.末层();
        }
        catch {
            return -1;
        }
    })();
    // 与 `取最新有效` 用**同一条**未就绪判据（`<= 0`，见那里的注释）——
    // 两处各判一套的话，会出现"最新那份说未就绪、K 份却说有数据"的矛盾。
    if (楼层们.length > 0 && !(末层 > 0))
        return [];

    for (let i = 楼层们.length - 1; i >= 0 && 结果.length < K; i--) {
        const 楼层 = 楼层们[i];
        if (策略.跳过?.(楼层))
            continue;
        if (楼层 > 末层)
            continue;
        if (!存储.楼层还在(楼层))
            continue;
        const 载荷 = 存储.读楼层(楼层);
        if (!载荷 || typeof 载荷 !== 'object')
            continue;
        if (载荷.楼层 !== 楼层)
            continue;
        if (策略.有效 && !策略.有效(载荷, 楼层))
            continue;
        结果.push(klona(载荷));
    }
    return 结果;
}

/** 写入结果 —— 失败时带原因，调用方要把它报给用户（不能静默） */
export type 写入结果 =
    | { ok: true; 楼层: number; 已删楼层: number[] }
    | { ok: false; 原因: string; 已删楼层: number[] };

/**
 * 写入策略。
 *
 * ⚠ **`保留份数` 不写死在这里**（需求方 #433 ③）：三家各传自己的
 * （彼方 10 / 烟火 30 / 导演 10，都可由设置覆盖）。
 * 内核只负责"超出就丢最旧的"，**丢到几份由调用方说**。
 */
export type 写入策略 = {
    /** 裁剪上限。**不传 = 不裁剪**；三家接入时必须显式传自己的值。 */
    保留份数?: number;
    /**
     * 写之前检查"锚点之后有没有更新的快照"（彼方的 `允许覆盖更新快照 = false`）。
     *
     * 返回非空字符串 = 拒绝写入，字符串就是原因。
     */
    拒绝写入?: (索引: 快照索引, 锚层: number) => string | null;
    /** 写成功后对索引的额外改动（如清空层清零） */
    写后?: (索引: 快照索引) => void;
};

/**
 * 写一份并登记。
 *
 * ── 不变量 5：**登记失败 = 这次快照白写** ──
 *
 * 楼层变量写成功了、但索引没登记成功 → 下次 `取最新有效` 从索引往前找**找不到它**
 * → 回退到更早的快照。**用户以为更新成功了，其实这轮结果被丢弃。**
 *
 * 所以 `写索引` 返回 false 时这里必须返回 `{ ok: false }`，**不许只 warn 就 return true**。
 */
export function 写一份并登记(
    存储: 快照存储,
    载荷: 快照载荷,
    锚层: number,
    策略: 写入策略 = {},
): 写入结果 {
    const 索引 = 归一索引(存储.读索引());
    const 已删楼层: number[] = [];

    // 写之前的拒绝判据（彼方：锚点之后已有更新的快照）
    const 拒绝原因 = 策略.拒绝写入?.(索引, 锚层);
    if (拒绝原因)
        return { ok: false, 原因: 拒绝原因, 已删楼层 };

    try {
        存储.写楼层(锚层, 载荷);
    }
    catch (error) {
        return { ok: false, 原因: `写入楼层快照失败: ${错误文本(error)}`, 已删楼层 };
    }

    // 同层重填时去重替换，然后按升序排（读侧靠顺序取最新）
    索引.快照楼层 = 索引.快照楼层.filter(楼层 => 楼层 !== 锚层);
    索引.快照楼层.push(锚层);
    索引.快照楼层.sort((a, b) => a - b);

    // 裁剪：超出上限就丢最旧的，并把它们的快照本体也删掉（不留孤儿）
    const 上限 = 策略.保留份数;
    if (typeof 上限 === 'number' && Number.isFinite(上限) && 上限 > 0) {
        while (索引.快照楼层.length > 上限) {
            const 被删 = 索引.快照楼层.shift();
            if (typeof 被删 !== 'number')
                break;
            已删楼层.push(被删);
            try {
                存储.删楼层(被删);
            }
            catch {
                // 楼层可能已不存在 —— 那不是错误，孤儿快照无害
            }
        }
    }

    策略.写后?.(索引);

    // ── 不变量 5 ──
    if (!存储.写索引(索引)) {
        return {
            ok: false,
            原因: `快照已写进楼层 #${锚层}, 但索引没登记成功 —— 下次读回会跳过它`,
            已删楼层,
        };
    }

    return { ok: true, 楼层: 锚层, 已删楼层 };
}

/**
 * 清空：物理删掉索引里所有快照本体 + 把索引重置成空。
 *
 * ⚠ **顺序：先重置索引，再删本体**（2026-11-19 彼方「发现8」的结论，三家通用）：
 *   · 索引重置成功 = 从读侧看数据已经清空了
 *   · 然后删本体，**删失败只是留下孤儿**（没索引指向，读侧看不见）
 *   · 反过来（先删本体、后写索引）失败时会"提示未清空，但实际已删" —— 那是永久损坏
 */
export function 清空(存储: 快照存储, 策略: { 写后?: (索引: 快照索引) => void } = {}): 写入结果 {
    const 索引 = 归一索引(存储.读索引());
    const 原楼层们 = [...索引.快照楼层];
    const 已删楼层: number[] = [];

    索引.快照楼层 = [];
    策略.写后?.(索引);

    if (!存储.写索引(索引)) {
        return {
            ok: false,
            原因: '索引没能重置 —— 一份快照都没删',
            已删楼层: [],
        };
    }

    for (const 楼层 of 原楼层们) {
        try {
            存储.删楼层(楼层);
            已删楼层.push(楼层);
        }
        catch {
            // 楼层可能已不存在；其余失败只留孤儿（索引已空，读侧看不见）
        }
    }

    return { ok: true, 楼层: -1, 已删楼层 };
}

/** 错误转文本（三家原来各写一份，措辞不同；统一成这个） */
function 错误文本(error: unknown): string {
    return error instanceof Error ? error.message : String(error);
}

// 烟火 · 故事层「主线」: 主角这条戏的长线(终点 / 幕 / 债 / 回顾)。
//
// 它从"每轮重写的一段话"升级为**只增不改的骨架 + 状态收束 + 渲染成注入文本** —— 形状与克制
// 照抄彼方的 事务台账.ts(那个模块已经上线、被一百多条用例钉住), 因为要防的是同一类真机事故:
//   "每轮重写"没有锚点 → 具体名词(对手的名字、欠下的那件东西、那句承诺)一轮记错就永久错下去,
//   之后每一轮都拿错的那份当"上一轮"; 而且模型会忍不住"顺手丰富一下", 把戏的节拍自己改写。
// 于是把"写下那一刻"冻结: 终点、幕、债.内容 写下即冻结, 之后只允许改 债.状态/结果 与 回顾(摘要);
// 要改内容就作废旧条、另开一条(于是"对手换人"这类事在数据里留痕)。
// 幕.序号(结幕时 +1)与 债.编号(D1/D2…)由代码分配, AI 不许自己填。
//
// 为什么住在烟火(刻意决定, 不再讨论): 编排那一轮与世界自转共用同一份上下文, 而主线只从
// **世界已有的**势力/事件里挑对手(烟火的"禁止世界为主角编织钩子"依然成立)——主线不属于世界,
// 但它读世界。它也不属于某个人物: 彼方只管 NPC 各自的生活。
//
// 对外契约(界面/提示词/合并各用一处, 类型名与函数名不许改):
//   读取主线(卡里/变量里的值)               → 规范成主线(永远返回可用的对象)
//   是空主线(主线)                          → 调用方据此决定整条不注入
//   合并编排(旧主线, 本轮模型返回, 剧情时间)  → 纯函数, 返回新主线(不改入参; 什么都没变 = 原样返回旧对象)
//   封顶(主线)                              → 债 超上限时淘汰最旧的 已还/作废
//   渲染主线(主线)                          → 注入给主 AI 的那段文本(空主线 = 空串)
//   主线提示词()                            → 编排那一轮的提示词草稿(见文件末尾, ⚠️ 待人工复核)
//
// 合并规则(全部要点都在这八条里, 见 合并编排 内的逐条注释):
//   1 冻结: 终点.类型/量级 只在"原本为空"时写(写下即永久冻结 —— 终点不可变, 要换走向只能换主角时归档重开); 终点.候选 一旦填上永久冻结
//     (连"再给一个候选"都不收); 幕.结束条件/期限 只补空, 唯一允许替换的时机是 结幕;
//     债.内容 一律以库里为准 —— 重抄的内容丢弃;
//   2 债命中编号(编号在库里)→ 只收 状态/结果, 内容/时间不动; 结果只在 已还/作废 时才落;
//   3 债没编号(或编号查无此人但带了内容)→ 按"内容指纹"去重后新增, 编号由代码分配 D{n}, 不复用;
//   4 空意思(无/暂无/…/空串/-, 见 是空意思)不是一条债: 新增整条丢弃; 已有条只按第 2 条收状态;
//   5 回顾是**唯一的例外**(它是摘要): 有非空值就整体替换, 空值不动;
//   6 结幕: 动作='结幕' 且给了新的幕 → 序号 = 旧序号 + 1, 结束条件/期限整体换成新的(新幕没写的留空);
//   7 幕的可改范围: 结束条件只补空(脊梁, 要换只能在结幕那一轮); 期限允许明确改期(中间节点可改期);
//   8 本轮什么都没变 → **原样返回旧对象**(引用相等), 不顺带封顶、不顺手改时间戳; 真改了才顺带封顶。


export type 债状态 = '欠着' | '已还' | '作废';
export interface 债 {
    编号: string;
    内容: string;
    状态: 债状态;
    结果?: string;
    时间?: string;
}
export interface 终点 {
    类型: string;
    量级: string;
    候选: string;
    成形: boolean;
}
export interface 幕 {
    序号: number;
    结束条件: string;
    期限: string;
}
export interface 主线 {
    终点: 终点;
    幕: 幕;
    债: 债[];
    回顾: string;
    上次编排?: { 楼层: number; 时间: string };
}

/** 三项合法债状态(校验/归一都按它) */
const 债状态表: 债状态[] = ['欠着', '已还', '作废'];
/** 债的上限: 超额先淘汰最旧的 已还/作废; "欠着"永不淘汰(全部欠着时允许超过上限) */
const 债上限 = 6;
/** 注入里"已还/作废"摘要最多取几条 */
const 已办摘要条数 = 3;
/** 编号形状: D + 数字(数字部分才是"新旧"与排序的依据) */
const 编号正则 = /^D(\d+)$/;
/** 能认出来的日期: 2025-09-18 / 2025/9/18 / 2025.9.18 / 2025年9月18日 */
const 日期正则 = /(\d{4})\s*[-/.年]\s*(\d{1,2})\s*[-/.月]\s*(\d{1,2})\s*日?/;
/** 编排动作白名单(认不出的动作按"没给动作"处理) */
const 动作表 = ['开篇', '推进', '结幕', '无事'] as const;
type 动作 = typeof 动作表[number];

/**
 * "没有内容"的**完整**表达(白名单, 只做精确匹配, 见 是空意思)。
 * 与彼方 事务台账.ts 同源: 模型会照着旧格式把整句 `无` 当一条写回来, 那不是一条债。
 */
const 空意思表 = new Set([
    '无',
    '暂无',
    '没有',
    '空',
    '-',
    '—',
    'none',
    'n/a',
    '无债',
    '暂无债',
]);

/** 注入末尾的四条规则原文(用户敲定, 一字不改 —— 用例逐条比对) */
const 规则原文 = [
    '本幕结束条件达成之前, 不许让主角解决核心冲突、不许让对手退场或失去威胁; 该由对手赢的那一场, 就让他赢。',
    '允许主角失败、受挫、受重伤, 甚至死亡。致命必须公平: 先有征兆、有可选的退路, 代价按 受伤→失去→重伤→死 逐级上升。',
    '主角若死亡: 那是事实, 记下时间地点与死因, 不得出现复活、转世、时光倒流。',
    '对手与债里的具体名词(人名、物品、地点)不得替换或泛化。',
];
/** 注入开头的作者视角框: 主 AI 读得到它, 但它写的是"戏的骨架", 不是世界里有人知道的事 */
const 作者视角框 = '这是这出戏的骨架, 不是世界动向; NPC 不可能知道它, 不得在台词或心理里引用。';
/**
 * 终点还没定下来时, 注入里用的中性占位词(名词, 不带任何指令)。
 * ⚠️ 注入是给**主 AI** 看的: "第 3 幕之前必须挑出候选"那类规矩只写在 主线提示词() 里(只发给编排者),
 * 一个字都不许漏到这里 —— 否则等于把编排者的手册递给了演戏的人。
 */
const 候选空值 = '(还没定)';

/** 是不是一个可当对象读的值(数组/null/字符串都不算) */
function 是对象(value: unknown): value is Record<string, unknown> {
    return !!value && typeof value === 'object' && !Array.isArray(value);
}

/** 文本归一: 认不出的值一律当空串(trim 掉首尾空白) */
function 文本(value: unknown): string {
    return String(value ?? '').trim();
}

/** 从文本里认出**第一个**日期并补零成 YYYY-MM-DD(剧情时间给的是时间段时取开始那天); 认不出返回空串 */
function 取日期(文本值: unknown): string {
    const match = String(文本值 ?? '').match(日期正则);
    if (!match)
        return '';
    return `${match[1]}-${match[2].padStart(2, '0')}-${match[3].padStart(2, '0')}`;
}

/** 状态归一: 只认三个枚举值; 认不出返回空串(调用方决定是丢弃还是按"欠着"兜底) */
function 归一状态(value: unknown): 债状态 | '' {
    const 文本值 = 文本(value);
    return 债状态表.includes(文本值 as 债状态) ? 文本值 as 债状态 : '';
}

/** 动作归一: 只认四个枚举值; 认不出返回空串(当"没给动作") */
function 归一动作(value: unknown): 动作 | '' {
    const 文本值 = 文本(value);
    return (动作表 as readonly string[]).includes(文本值) ? 文本值 as 动作 : '';
}

/** 编号数字: "D3" → 3; 认不出返回 null(空编号、乱编号都算"认不出") */
function 编号数字(编号: unknown): number | null {
    const match = 文本(编号).match(编号正则);
    return match ? Number(match[1]) : null;
}

/** 编号归一: 数字按 D{数字} 处理; 小写 d1 也认(模型偶尔写小写) */
function 归一编号(value: unknown): string {
    if (typeof value === 'number' && Number.isFinite(value))
        return `D${value}`;
    return 文本(value).replace(/^d(?=\d)/i, 'D');
}

/** 去重指纹: 去掉空白与标点(只留文字与数字), 于是 "把玉佩还给沈砚。" 与 "把玉佩还给沈砚" 是同一条 */
function 内容指纹(内容: unknown): string {
    return String(内容 ?? '').replace(/[^\p{L}\p{N}]/gu, '');
}

/**
 * 这句"内容"是不是"没有/暂无"的意思(模型把旧格式的 `无` 当一条写回来)。
 * 判据是**精确匹配**: 先 trim、去掉尾部的句号/顿号, 再与白名单逐字对比(英文大小写不敏感);
 * 空串与纯空白也算。故意**不用**"包含 无 字"这种模糊判据: `无薪加班`、`交涉无果` 都是真内容。
 */
function 是空意思(内容: unknown): boolean {
    const 文本值 = 文本(内容).replace(/[。、]+$/u, '').trim();
    return !文本值 || 空意思表.has(文本值.toLowerCase());
}

/** 造一笔债: 键序固定(编号/内容/状态/结果/时间), 空的可选值不写进去 —— 让 JSON 比对与界面展示都稳定 */
function 造债(编号: string, 内容: string, 状态: 债状态, 结果?: string, 时间?: string): 债 {
    const 一笔: 债 = { 编号, 内容, 状态 };
    if (结果)
        一笔.结果 = 结果;
    if (时间)
        一笔.时间 = 时间;
    return 一笔;
}

/** 终点归一: 成形由代码判定(类型/量级/候选 三者都有 = 终点成形), 不信卡里/模型写的那个布尔值 */
function 归一终点(raw: unknown): 终点 {
    const 源 = 是对象(raw) ? raw : {};
    const 类型 = 文本(源['类型']);
    const 量级 = 文本(源['量级']);
    const 候选 = 是空意思(源['候选']) ? '' : 文本(源['候选']);
    return { 类型, 量级, 候选, 成形: !!(类型 && 量级 && 候选) };
}

/** 幕归一: 序号只能由代码给(结幕时 +1); 认不出/小于 1 的一律回到第 1 幕 */
function 归一幕(raw: unknown): 幕 {
    const 源 = 是对象(raw) ? raw : {};
    const 序号 = Number(源['序号']);
    return {
        序号: Number.isInteger(序号) && 序号 >= 1 ? 序号 : 1,
        结束条件: 文本(源['结束条件']),
        期限: 文本(源['期限']),
    };
}

/** 上次编排归一: 楼层/时间都认不出就整块丢掉(它是记账, 不是内容) */
function 归一上次编排(raw: unknown): { 楼层: number; 时间: string } | null {
    if (!是对象(raw))
        return null;
    const 数字 = Number(raw['楼层']);
    const 楼层 = Number.isFinite(数字) ? Math.max(0, Math.floor(数字)) : 0;
    const 时间 = 文本(raw['时间']);
    return 楼层 > 0 || 时间 ? { 楼层, 时间 } : null;
}

/**
 * 把一条乱七八糟的债规范成形状; 认不出"欠的是什么"(没内容)又认不出"改哪一条"(没合法编号) → null。
 * 纯函数: 一律构造新对象。
 * 入场券(本轮载荷)要宽: 提示词教模型"已有债只回「编号 + 状态(+结果)」, 内容不用重抄", 所以
 * **有编号时可以没有内容**(内容在合并阶段从库里取)。整句是"没有"的意思时内容按空处理(见 是空意思)。
 */
function 归一债载荷(raw: unknown): 债 | null {
    if (!是对象(raw))
        return null;
    const 内容原文 = 文本(raw['内容']);
    const 内容 = 是空意思(内容原文) ? '' : 内容原文;
    const 编号 = 归一编号(raw['编号']);
    if (!内容 && !编号)
        return null;
    const 时间原文 = 文本(raw['时间']);
    return 造债(
        编号,
        内容,
        归一状态(raw['状态']) || '欠着',
        文本(raw['结果']),
        时间原文 ? (取日期(时间原文) || 时间原文) : '',
    );
}

/** 债表归一(读取阶段): 认得出的编号原样保留, 没有编号/编号重复的按最大编号递增补号 —— 同台账 */
function 归一债表(value: unknown): 债[] {
    const 原始条目: unknown[] = value === undefined || value === null ? [] : (Array.isArray(value) ? value : [value]);
    const 结果: 债[] = [];
    const 已用编号 = new Set<number>();
    for (const 条目 of 原始条目) {
        const 一笔 = 归一债载荷(条目);
        // 卡上的值里"有编号却没内容"的条目是残迹(合并结果永远不会产出它: 新增必须有内容,
        // 命中只动状态/结果)—— 读取阶段照旧丢掉, 免得渲染出 `D1 欠着：` 这种幽灵行。
        // 归一债载荷 为合并阶段放行了这种形状, 两处口径不同是故意的: 入场券要宽, 落库/展示要严。
        if (!一笔 || !一笔.内容)
            continue;
        const 数字 = 编号数字(一笔.编号);
        if (数字 !== null && !已用编号.has(数字)) {
            已用编号.add(数字);
            一笔.编号 = `D${数字}`;
        }
        else {
            一笔.编号 = '';
        }
        结果.push(一笔);
    }
    for (const 一笔 of 结果) {
        if (!一笔.编号)
            一笔.编号 = `D${下一个编号数(结果)}`;
    }
    return 结果;
}

/** 债表里下一个可用的编号数(现有最大编号 + 1; 没有编号时从 1 起) */
function 下一个编号数(债表: 债[]): number {
    let 最大 = 0;
    for (const 一笔 of 债表)
        最大 = Math.max(最大, 编号数字(一笔.编号) ?? 0);
    return 最大 + 1;
}

/** 两边是不是同一份内容(键序无关; 缺键与 undefined 视为相同)。只看值, 不看引用。 */
function 同值(甲: unknown, 乙: unknown): boolean {
    if (甲 === 乙)
        return true;
    if (Array.isArray(甲) && Array.isArray(乙))
        return 甲.length === 乙.length && 甲.every((项, i) => 同值(项, 乙[i]));
    if (是对象(甲) && 是对象(乙)) {
        const 键 = new Set([...Object.keys(甲), ...Object.keys(乙)]);
        for (const 名 of 键) {
            if (!同值(甲[名], 乙[名]))
                return false;
        }
        return true;
    }
    return false;
}

/**
 * "什么都没变"时交回去的那个对象: 旧值本来就是规范形状(逐字段同值, 没有多余键、没有脏条目)
 * 就把**原来那个引用**还回去 —— 引用相等也是"原样不动"的一种, 界面/注入不必为一个没变的账
 * 换新对象; 旧值是脏值/undefined 时只能给规范副本。
 */
function 原样返回(旧主线: unknown, 库: 主线): 主线 {
    return 同值(旧主线, 库) ? 旧主线 as 主线 : 库;
}

/** "最近已还/作废"的排序: 时间倒序(空时间排最后); 同一天按编号倒序(后写下的在前) —— 同台账 */
function 按时间倒序(甲: 债, 乙: 债): number {
    const 前 = 取日期(甲.时间) || 甲.时间 || '';
    const 后 = 取日期(乙.时间) || 乙.时间 || '';
    if (前 !== 后) {
        if (!前)
            return 1;
        if (!后)
            return -1;
        return 前 < 后 ? 1 : -1;
    }
    return (编号数字(乙.编号) ?? 0) - (编号数字(甲.编号) ?? 0);
}

/**
 * 把卡里/变量里的值规范成主线; **永远返回可用的对象**(认不出的条目丢弃)。
 * 纯函数: **一律构造新对象**(调用方可以安全地改返回值, 例如界面里直接编辑), 不改入参;
 * 读取两次结果一致(界面/合并/渲染都能安全地用)。
 * "合并编排 什么都没变就原样返回旧对象(引用相等)"不靠这里 —— 靠 合并编排 自己把原引用还回去。
 */
export function 读取主线(value: unknown): 主线 {
    const 源 = 是对象(value) ? value : {};
    const 终点 = 归一终点(源['终点']);
    const 幕 = 归一幕(源['幕']);
    const 债 = 归一债表(源['债']);
    const 回顾 = 文本(源['回顾']);
    const 上次编排 = 归一上次编排(源['上次编排']);
    const 规范: 主线 = { 终点, 幕, 债, 回顾 };
    if (上次编排)
        规范.上次编排 = 上次编排;
    return 规范;
}

/**
 * 主线是不是"什么都没有"(调用方据此决定整条不注入)。
 * 只看内容字段: 幕.序号 是代码给的位置标记(默认第 1 幕), 上次编排 是记账, 都不算内容。
 */
export function 是空主线(主线: 主线): boolean {
    const 库 = 读取主线(主线);
    return !库.终点.类型 && !库.终点.量级 && !库.终点.候选
        && !库.幕.结束条件 && !库.幕.期限
        && 库.债.length === 0
        && !库.回顾;
}

/**
 * 债的封顶: 最多 债上限(6) 条。超了**先淘汰最旧的 已还/作废**, "欠着"永不淘汰 ——
 * 哪怕全部都是欠着、超过 6 条也照留(没还完的事不能因为条数被丢掉)。
 * "最旧"按数组顺序(前面 = 更早写下), 不是按时间字段(时间可能是空的)。
 */
export function 封顶(主线: 主线): 主线 {
    const 库 = 读取主线(主线);
    if (库.债.length <= 债上限)
        return 库;
    const 保留 = [...库.债];
    for (let i = 0; i < 保留.length && 保留.length > 债上限;) {
        if (保留[i].状态 === '欠着') {
            i++;
            continue;
        }
        保留.splice(i, 1);
    }
    const 结果: 主线 = { 终点: 库.终点, 幕: 库.幕, 债: 保留, 回顾: 库.回顾 };
    if (库.上次编排)
        结果.上次编排 = 库.上次编排;
    return 结果;
}

/**
 * 合并本轮模型返回的编排, 返回**新主线**(纯函数, 不改入参)。规则逐条见文件头与下面的注释:
 *   ① 终点: 类型/量级 只在"原本为空"时写(写下即永久冻结, 终点不可变);
 *     候选 一旦填上就冻结 —— 再给新候选也丢弃(具体对手不许换人);
 *   ② 债命中编号 → 只收 状态/结果, 内容/时间以库里为准; 结果只在状态给的是 已还/作废 时才落
 *     (状态没给或还是"欠着"都不收, 免得旧脏结果日后冒充"还了什么");
 *     状态/结果**确实变了**才算一次合并动作(规则8 才会顺带封顶);
 *   ③ 债没编号(或编号查无此人但带了内容)→ 去重(内容指纹)后新增, 编号由代码分配;
 *   ④ 空意思/没内容的新增整条丢弃; 幽灵编号(查无此人又没内容)直接丢弃, 不重建成空内容的新债;
 *   ⑤ 回顾: 非空就整体替换, 空值不动(它是唯一的例外: 摘要允许每轮重写);
 *   ⑥ 结幕: 动作='结幕' → 序号 = 旧+1, 结束条件/期限整体换成新的(新幕没写的留空, 不沿用旧的);
 *   ⑦ 幕的可改范围: 结束条件只补空(脊梁); 期限允许**明确改期**(中间节点可改期) —— 没写就一个字都不动;
 *   ⑧ 本轮什么都没变 → 原样返回旧对象(连封顶也不做, 也不碰 上次编排 这个时间戳)。
 * 空输入(undefined/null/空对象/乱七八糟)= **原样不动** —— 上一个是同类模块真机出事的地方:
 * 提示词教的形状被代码丢掉, AI 就永远标不了完成。
 */
export function 合并编排(旧主线: 主线, 模型返回: unknown, 剧情时间: string): 主线 {
    const 库 = 读取主线(旧主线);
    if (!是对象(模型返回))
        return 原样返回(旧主线, 库);
    const 本轮 = 模型返回;
    const 动作 = 归一动作(本轮['动作']);
    // 先逐字段从库里拷一份(纯函数: 绝不改入参/库里的对象)
    const 终点 = { ...库.终点 };
    const 幕 = { ...库.幕 };
    const 债 = 库.债.map(一笔 => ({ ...一笔 }));
    let 回顾 = 库.回顾;
    let 改了 = false;

    // ① 终点
    const 本轮终点 = 是对象(本轮['终点']) ? 本轮['终点'] : null;
    if (本轮终点) {
        const 新类型 = 文本(本轮终点['类型']);
        const 新量级 = 文本(本轮终点['量级']);
        const 新候选 = 是空意思(本轮终点['候选']) ? '' : 文本(本轮终点['候选']);
        // 类型/量级: 只补空, 写下即永久冻结(用户定的"终点不可变": 要换走向只能在换主角时归档重开)
        if (新类型 && !终点.类型) {
            终点.类型 = 新类型;
            改了 = true;
        }
        if (新量级 && !终点.量级) {
            终点.量级 = 新量级;
            改了 = true;
        }
        // 候选: 空着才收; 一旦填了就冻结(不许换对手, 也不许再挑第二个)
        if (新候选 && !终点.候选) {
            终点.候选 = 新候选;
            改了 = true;
        }
        终点.成形 = !!(终点.类型 && 终点.量级 && 终点.候选);
    }

    // ⑥ 结幕 / 幕的冻结
    const 本轮幕 = 是对象(本轮['幕']) ? 本轮['幕'] : null;
    const 新结束条件 = 本轮幕 ? 文本(本轮幕['结束条件']) : '';
    const 新期限 = 本轮幕 ? 文本(本轮幕['期限']) : '';
    if (动作 === '结幕' && 本轮幕 && (新结束条件 || 新期限)) {
        // 结幕 = 进下一幕: 序号由代码 +1, 结束条件/期限整体换成新幕的。
        // 新幕**没写的字段留空**(不沿用上一幕的 —— 沿用会让主 AI 以为同一件事还要再演一次);
        // 渲染里空字段显示成 (未定), 编排下一轮会补上。
        幕.序号 = 库.幕.序号 + 1;
        幕.结束条件 = 新结束条件;
        幕.期限 = 新期限;
        改了 = true;
    }
    else {
        // 结束条件: 这幕的脊梁, 只补空(要换只能在 结幕 那一轮换下一幕的);
        // 期限: 中间节点, 允许**明确改期**(用户定的"中间节点可改期/作废")——
        //       但没写就一个字都不动, 免得每轮被重抄改写成另一个说法。
        if (新结束条件 && !幕.结束条件) {
            幕.结束条件 = 新结束条件;
            改了 = true;
        }
        if (新期限 && 新期限 !== 幕.期限) {
            幕.期限 = 新期限;
            改了 = true;
        }
    }

    // ②③④ 债
    const 本轮债: unknown[] = Array.isArray(本轮['债'])
        ? 本轮['债']
        : (是对象(本轮['债']) ? [本轮['债']] : []);
    for (const 条目 of 本轮债) {
        const 候选 = 归一债载荷(条目);
        if (!候选)
            continue;
        const 位置 = 候选.编号 ? 债.findIndex(一笔 => 一笔.编号 === 候选.编号) : -1;
        if (位置 >= 0) {
            // 只收 状态/结果; 内容/时间一律以库里为准(故意: 具体名词写下即冻结)
            const 命中 = 债[位置];
            const 载荷状态 = 归一状态(候选.状态);
            const 新状态 = 载荷状态 || 命中.状态;
            // 结果只对"已还/作废"有意义: 状态没给、或还是"欠着", 都不落结果(与新增路径同口径)
            const 新结果 = 载荷状态 && 载荷状态 !== '欠着' && 候选.结果 ? 候选.结果 : (命中.结果 ?? '');
            if (新状态 !== 命中.状态 || 新结果 !== (命中.结果 ?? '')) {
                // 重建而不是就地改键: 让结果里的键序恒定(编号/内容/状态/结果/时间),
                // 界面展示、快照与用例的 JSON 比对才稳定。
                债[位置] = 造债(命中.编号, 命中.内容, 新状态, 新结果, 命中.时间);
                改了 = true;
            }
            continue;
        }
        // 编号查无此人(被封顶淘汰/模型写错)又没有内容 → 无事可做: 既不重建成空内容的新债,
        // 也不当成一次合并动作(丢弃后若本轮再无别的变化, 按规则8 原样不动)。
        // 空意思(无/暂无/-/空串)同理 —— 它不是一条债。
        if (!候选.内容 || 是空意思(候选.内容))
            continue;
        const 指纹 = 内容指纹(候选.内容);
        if (!指纹 || 债.some(一笔 => 内容指纹(一笔.内容) === 指纹))
            continue;
        // 编号由代码分配(不复用); 时间取本次剧情时间的日期(模型载荷里的时间只作兜底)
        债.push(造债(
            `D${下一个编号数(债)}`,
            候选.内容,
            候选.状态,
            候选.状态 !== '欠着' ? 候选.结果 : '',
            取日期(剧情时间) || 候选.时间,
        ));
        改了 = true;
    }

    // ⑤ 回顾: 唯一的例外 —— 摘要允许每轮整体重写; 空值不动
    const 新回顾 = 文本(本轮['回顾']);
    if (新回顾 && !是空意思(新回顾) && 新回顾 !== 库.回顾) {
        回顾 = 新回顾;
        改了 = true;
    }

    // ⑦ 什么都没变 → **原样返回旧对象**(引用相等也算通过: 合并编排(旧, {}, t) === 旧)。
    // 不顺带封顶(不删已有记录优先于条数), 也不顺手改时间戳 —— 上次编排 全程不碰:
    // 楼层只有调用方知道, 这一层没有它的输入。
    if (!改了)
        return 原样返回(旧主线, 库);
    const 结果: 主线 = { 终点, 幕, 债, 回顾 };
    if (库.上次编排)
        结果.上次编排 = 库.上次编排;
    return 封顶(结果);
}

/**
 * 注入给主 AI 的那段文本: ①作者视角的框 ②终点(只显示已经定了的字段) ③第几幕 + 结束条件 + 期限
 * ④欠着的债逐条 + 最近 3 条已还/作废摘要 ⑤回顾 ⑥**四条**规则原文。
 * 编排者那一份规矩(第 5 条"第 3 幕之前必须挑出候选")**不进这里** —— 它只在 主线提示词() 里。
 * 空主线返回**空串** —— 调用方按"空则整条不注入"处理。
 */
export function 渲染主线(主线: 主线): string {
    const 库 = 读取主线(主线);
    if (是空主线(库))
        return '';
    const 行: string[] = [
        '【主线 · 作者视角】',
        作者视角框,
    ];
    const 终点 = 库.终点;
    // 只列已经定了的字段: 候选空着时连"候选"这一项都不出现(免得又提醒主 AI 有这么个东西)
    const 终点项 = [
        终点.类型 ? `类型: ${终点.类型}` : '',
        终点.量级 ? `量级: ${终点.量级}` : '',
        终点.候选 ? `候选: ${终点.候选}` : '',
    ].filter(一项 => 一项);
    行.push(`终点: ${终点项.length > 0 ? 终点项.join(' | ') : 候选空值}`);
    行.push(`第 ${库.幕.序号} 幕 | 结束条件: ${库.幕.结束条件 || '(未定)'} | 期限: ${库.幕.期限 || '(未定)'}`);
    const 欠着 = 库.债
        .filter(一笔 => 一笔.状态 === '欠着')
        .sort((甲, 乙) => (编号数字(甲.编号) ?? 0) - (编号数字(乙.编号) ?? 0));
    if (欠着.length > 0) {
        行.push(`欠着: ${欠着
            .map(一笔 => `${一笔.编号} ${一笔.内容}${一笔.时间 ? `（${一笔.时间} 起）` : ''}`)
            .join('；')}`);
    }
    const 已办 = 库.债
        .filter(一笔 => 一笔.状态 !== '欠着')
        .sort(按时间倒序)
        .slice(0, 已办摘要条数);
    if (已办.length > 0) {
        行.push(`已还/作废: ${已办
            .map(一笔 => `${一笔.编号} ${一笔.状态} ${一笔.结果 || 一笔.内容}${一笔.时间 ? `（${一笔.时间}）` : ''}`)
            .join('；')}`);
    }
    行.push(`回顾: ${库.回顾 || '(暂无)'}`);
    行.push('规则(不可违反):');
    规则原文.forEach((一条, i) => 行.push(`${i + 1}. ${一条}`));
    return 行.join('\n');
}


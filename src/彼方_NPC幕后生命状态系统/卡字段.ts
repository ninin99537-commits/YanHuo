/** 分组 → 字段名(详情页按这个渲染; 核心三字段单独处理, 不在这里) */
export const 字段分组表: Record<string, string[]> = { 生活: [], 内心: [], 生理: [] };
for (const 字段 of 字段表) {
    if (字段.组 !== '核心')
        字段分组表[字段.组].push(字段.名);
}

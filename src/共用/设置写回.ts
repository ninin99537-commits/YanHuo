// 设置会话 —— 2026-11-20 C8（需求方 #500 第 3 件）
// ═══════════════════════════════════════════════════════════════════════════
//
// ── 为什么要有"会话" ──
//
//  `建写回闸门` 本身是干净的（基线 + 可写回 + 只写差异），但它**没有生命周期** ——
//  谁用它，谁就得自己在模块作用域里维护一堆单例：
//
//  ```
//  写回闸门 / 闸门宿主 / persistenceBound / globalReadCache / globalReadTime / 首次落盘入口
//  ```
//
//  六件事，六个单例。后果是**同一进程里两个挂载点共享同一组单例**，互相污染：
//
//  ```
//  面板 iframe 读到 5 套预设 → 外层脚本也读到 5 套（同一个缓存）
//  面板改了模型 → 外层脚本的基线也跟着变 → 它以为自己没改 → 不写
//  ```
//
//  **而"两个窗口互相覆盖"这件事，今天根本没法测** —— 单例让它不可构造。
//
// ── 会话的形状 ──
//
//  一个挂载点 = 一个会话 = **一个闸门 + 一份读缓存**。
//
//  ```ts
//  const 会话 = 建设置会话({ 读远端, 写远端 });
//  会话.读()        // 读（带 500ms 窗口）；成功→记基线；失败→**关闸门**
//  会话.写(设置)     // 只写相对基线的差异；闸门关/无改动→不写
//  会话.首落盘(设置)  // 迁移专用：跳过差异整份写
//  会话.销毁()      // 幂等：清缓存 + 关闸门 + 停定时器
//  ```
//
// ── 三条不变量（写进实现，不靠调用方记）──
//
//  | 方法 | 不变量 |
//  |---|---|
//  | `读()` | ① 500ms 窗口内不重复摸存储；② 成功→**闸门可写**；③ **失败→闸门关闭**（返回回退值但绝不落盘） |
//  | `写(s)` | ① 闸门关→**一个字节都不写**；② 无差异→不写；③ 有差异→读远端→深合并→按路径删→写→基线推进 |
//  | `销毁()` | 幂等；销毁后 `写()` 必为 no-op |
//
//  > ③ 是**彼方今天缺的那条**：它的 `getSettings` catch 只清缓存、不关闸门 ——
//  >   于是闸门仍"可写回"，store 里的默认值可能在下一次 watch 里被当成用户改动写回，
//  >   覆盖真数据。导演那份做对了（显式关闸门），这里统一上来。
//
// ── 只新增，不改旧接口 ──
//
//  `建写回闸门` 与四个纯函数的签名**一字不动** —— 三家旧调用继续编译通过。
//  本批只把**彼方**迁到会话；导演/烟火下一批再说。

/** 会话端口：怎么读那一份、怎么把整份写回去（与 `写回端口` 同形） */
export interface 会话端口 extends 写回端口 {}

/** 会话选项 */
export interface 会话选项 {
  /**
   * 要不要找"基线里有、现在没了"的键并按路径删。
   * 默认 true（有"删掉一项预设"界面的插件需要它）。
   */
  收集删除?: boolean;
  /**
   * 读缓存的窗口（毫秒）。默认 500。
   *
   * 用途：同一个 tick 里多处调 `读()` 时不重复摸存储。
   */
  读窗口?: number;
  /**
   * 时钟（测试用）。默认 `Date.now`。
   */
  时钟?: () => number;
}

/** 设置会话 —— 一个挂载点持有一个 */
export interface 设置会话 {
  /**
   * 读设置。
   *
   * 不变量：
   *  · 500ms 窗口内不重复摸存储
   *  · 成功 → 记基线（闸门变可写）
   *  · **失败 → 关闸门**，返回 `回退值`，但**绝不落盘**
   */
  读: () => any;
  /**
   * 只把相对基线的改动写回。
   *
   * @returns 是否真的写了（闸门关着 / 没有改动 / 已销毁 → false）
   */
  写: (当前: any) => boolean;
  /**
   * 迁移专用：跳过差异，把这份直接写成远端并成为新基线。
   * 调用方必须保证"存储里本来没有这一份"。
   */
  首落盘: (当前: any) => boolean;
  /** 闸门是否可写（诊断/用例用） */
  可写回: () => boolean;
  /** 当前基线（诊断/用例用） */
  当前基线: () => any;
  /** 撤销：清读缓存 + 关闸门 + 标记已销毁（幂等） */
  销毁: () => void;
  /** 是否已销毁（诊断/用例用） */
  已销毁: () => boolean;
}

/**
 * 建一个设置会话。
 *
 * @param 端口   `{ 读, 写 }` —— 共用不认识酒馆，存取由调用方给
 * @param 回退值 读失败时返回什么（通常是 schema 的默认值）
 * @param 选项   收集删除 / 读窗口 / 时钟
 */
export function 建设置会话(端口: 会话端口, 回退值: any, 选项: 会话选项 = {}): 设置会话 {
  const 读窗口 = 选项.读窗口 ?? 500;
  const 时钟 = 选项.时钟 ?? (() => Date.now());
  const 建闸门 = () => 建写回闸门(端口, { 收集删除: 选项.收集删除 ?? true });

  // ⚠ `闸门` 是 `let` 而不是 `const` —— 读失败时要**重建一个**来表达"关闸门"。
  //
  //  为什么不用"改个布尔"：`建写回闸门` 的 `读成功过` 是闭包私有的，
  //  外部只能通过 `记录基线` 把它置 true，**没有置 false 的路径**。
  //  而设计稿要求"建写回闸门 签名一字不动"（三家旧调用继续编译），
  //  所以这里用"换一个新闸门"实现关闸 —— 新闸门默认 `读成功过 = false`。
  let 闸门 = 建闸门();

  let 缓存: any = undefined;
  let 缓存时间 = 0;
  let 有缓存 = false;
  let 已销毁 = false;

  return {
    读() {
      if (已销毁)
        return 回退值;
      const now = 时钟();
      if (有缓存 && now - 缓存时间 <= 读窗口)
        return 缓存;

      缓存时间 = now;
      try {
        const 远端 = 端口.读();
        缓存 = 远端;
        有缓存 = true;
        // 成功读到（哪怕是 undefined = 新装用户）→ 记基线，闸门可写
        闸门.记录基线(远端);
        return 远端;
      }
      catch {
        // ── 读失败 → **关闸门**（不变量③）──
        //  换一个新闸门 = 回到"从没读到过"的状态 → `可写回()` 为 false → `写()` 一个字节都不落。
        //
        //  这条是**彼方今天缺的**：它的 getSettings catch 只清缓存、不关闸门，
        //  于是闸门仍"可写回"，store 里的默认值可能在下一次 watch 里被当成用户改动写回。
        闸门 = 建闸门();
        缓存 = undefined;
        有缓存 = false;
        return 回退值;
      }
    },
    写(当前) {
      if (已销毁)
        return false;
      let 写了 = false;
      try {
        写了 = 闸门.立即写(当前);
      }
      catch {
        // ── 写的过程中读远端失败 ──
        //  `立即写` 内部会 `端口.读()`（要拿远端做深合并）。那次读失败会抛出来。
        //
        //  这里的语义：**写不成就当没写**，不向上抛 —— 否则一次存储故障会让调用方
        //  的整条 watch 链炸掉（设置面板从此不响应）。失败时基线不动，下次变化自然重试。
        写了 = false;
      }
      if (写了) {
        // 成功写回 → 清读缓存（否则窗口内的读会拿到旧值）
        缓存 = undefined;
        有缓存 = false;
        缓存时间 = 0;
      }
      return 写了;
    },
    首落盘(当前) {
      if (已销毁)
        return false;
      let 写了 = false;
      try {
        写了 = 闸门.首次落盘(当前);
      }
      catch {
        // 与 `写()` 同一条原则：存储故障不该炸掉调用方
        写了 = false;
      }
      if (写了) {
        缓存 = undefined;
        有缓存 = false;
        缓存时间 = 0;
      }
      return 写了;
    },
    可写回() {
      return !已销毁 && 闸门.可写回();
    },
    当前基线() {
      return 闸门.当前基线();
    },
    销毁() {
      已销毁 = true;
      缓存 = undefined;
      有缓存 = false;
      缓存时间 = 0;
    },
    已销毁() {
      return 已销毁;
    },
  };
}

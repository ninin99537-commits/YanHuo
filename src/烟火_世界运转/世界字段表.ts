/**
 * 「世界字段表」(候选 4): 五层常驻档案(地域/大势/伏笔/节令/指标)与势力清单的字段知识唯一来源。
 *
 * 以前同一份字段知识在八个地方各抄一遍: schema.ts 的类型、提示词里的 JSON 示例、注入表头、
 * 注入行格式、state.ts 的快照 sanitize、世界数据.ts 的 normalizeLayer 字段数组、界面的
 * layerFields、模板里的五段展示; 界面的下拉与筛选还另外手抄了六组事件枚举字面量,
 * 五层与势力的容量上限也散在 state.ts / 世界数据变更.ts 两处。
 * 漏一处的后果很具体: 界面能编辑的字段注入里没有(或反过来), 读快照时被悄悄丢掉,
 * 面板手动添到第 9 个地域会被下一轮规范化无声裁掉。
 *
 * 现在每个层只有这一份定义(名 / 标签 / 形态 / 名称键 / 容量 / 字段 / 注入列), 各处都从它生成:
 *   - 界面: 表单定义() → 世界编辑表单.vue 的字段表; 事件枚举 → 下拉与筛选;
 *   - 提示词: 提示词JSON示例() → SYSTEM_PROMPT 里那段 JSON 模板;
 *   - 注入: 注入表头() / 注入行() / 该注入() → 世界动向条目的竖线表;
 *   - 快照: 规范化条目() → loadData 的 sanitize(缺字段补空、旧名迁移、枚举纠偏);
 *   - AI 那条路: 内容字段键() 给 normalizeLayer, 沿用条目() 给势力清单;
 *   - 一道门(世界数据变更.ts): 名称键 / 容量 / 字段清单。
 *
 * 这个 module 不碰平台、不读设置、不写存储: 它只描述"世界数据长什么样"。
 */


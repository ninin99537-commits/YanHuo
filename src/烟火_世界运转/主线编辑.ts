// 烟火 · 主线的**面板编辑**(纯转换) —— 草稿 ⇄ 主线, 外加"加一条债 / 超上限"这两件界面要用的算术。
//
// 为什么另开一条通道: 数据层(主线.ts)的 合并编排 是**给 AI 的规矩**(写下即冻结: 终点、幕.结束条件、
// 债.内容 一律以库里为准, 重抄的一律丢弃), 防的是"模型一轮记错就永久错下去"。**用户纠错不该被它拦住**:
// 人在面板上改一个字就该生效。于是这里有第二条通道, 只做转换, 不做冻结判断:
//   主线草稿(主线)        → 面板 v-model 直接绑的草稿(逐字段拷一份, 绝不回写存档)
//   合并草稿(主线, 草稿)  → 把草稿收回主线(**手改不受冻结限制**), 保存前顺带 封顶
//   加一条债(主线)        → 追加一条空债(编号 = 现有最大编号 + 1, 淘汰过的号不复用)
//   超上限提示(主线)      → 超过上限时给用户一句人话(会淘汰谁、谁永不淘汰)
//
// 这个 module **只管纯转换**: 不碰 host、不读设置、不写存档与世界书 —— 落库与同步那两件事在界面上
// (悬浮球界面.vue 的 保存主线), 与世界页"手改一律走 世界数据变更.ts 那道门"同一个分工; 也不含任何
// 界面/DOM 依赖, 于是能在 node 里直调用例跑。
// 它也**不调 合并编排**: 那一条会把用户改的内容当"重抄"丢掉, 正是要绕开的东西。
//
// 三条守则(用例逐条钉住):
//   ① 编号只读: 改内容不换编号、不重排顺序; 新债按"现有最大 + 1"发号(被淘汰的号不回收);
//   ② 空的不进库: 空白行与"内容为空"的债整条丢弃; 状态认不出按「欠着」兜底; 幕.序号取整数且 ≥1;
//   ③ 保存前一律过一遍 封顶(那把尺在 主线.ts 里, 这里只调用它)。
import { 封顶, 读取主线, type 债, type 债状态, type 终点, type 幕, type 主线 } from './主线';

/**
 * 债的条数上限。与 主线.ts 里私有的 债上限 是同一个数(那边没导出, 面板要显示"N / 6"只能在这里写一份);
 * 用例把"7 条已还过一遍 封顶 剩几条"与它比对 —— 将来数据层动了上限, 这条钉子会当场红。
 */
export const 债条数上限 = 6;

/** 面板下拉里的三个状态(顺序 = 展示顺序): 与 主线.ts 的 债状态表 一字不差 */
export const 债状态表: 债状态[] = ['欠着', '已还', '作废'];

/** 草稿里的一条债: 每个字段都是表单能直接 v-model 的原始类型(状态是字符串, 合并时再归一) */
export interface 债草稿 {
  编号: string;
  内容: string;
  状态: string;
  结果: string;
}

/**
 * 面板草稿: 与 主线 同形, 但只装"人能手改"的东西。
 * 成形(由三个字段算)、债.时间(记账)不进表单 —— 前者合并时重算, 后者按编号从存档里取回来。
 */
export interface 主线草稿 {
  终点: { 类型: string; 量级: string; 候选: string };
  幕: { 序号: number; 结束条件: string; 期限: string };
  债: 债草稿[];
  回顾: string;
  /** 只读展示(「重置编排位置」清的是存档里那个锚点, 之后草稿会重拉一份) */
  上次编排: { 楼层: number; 时间: string } | null;
}

// ---------------------------------------------------------------------------
// 归一(与 主线.ts 同一把尺; 它是纯的, 这里也不引用任何平台能力)
// ---------------------------------------------------------------------------

/** 文本归一: 认不出的值一律当空串(trim 掉首尾空白) */
function 文本(值: unknown): string {
  return String(值 ?? '').trim();
}

/** 是不是一个可当对象读的值(数组/null/字符串都不算) */
function 是对象(值: unknown): 值 is Record<string, unknown> {
  return !!值 && typeof 值 === 'object' && !Array.isArray(值);
}

/** 状态归一: 只认三个枚举值, 认不出返回空串(调用方按「欠着」兜底) */
function 归一状态(值: unknown): 债状态 | '' {
  const 文本值 = 文本(值);
  return 债状态表.includes(文本值 as 债状态) ? (文本值 as 债状态) : '';
}

/** 编号归一: 只认 D{数字}(小写 d1 也认); 认不出返回空串(合并时按"新债"发号) */
function 归编号(值: unknown): string {
  const 文本值 = 文本(值).replace(/^d(?=\d)/i, 'D');
  return /^D\d+$/.test(文本值) ? 文本值 : '';
}

/** 下一个可用编号 = 现有最大编号 + 1(淘汰过的号**不复用**: 被封顶删掉的 D1 不会再发出去) */
function 下一个编号(债表: { 编号?: unknown }[]): string {
  let 最大 = 0;
  for (const 一笔 of 债表) {
    const 命中 = /^D(\d+)$/i.exec(文本(一笔?.编号));
    if (命中) 最大 = Math.max(最大, Number(命中[1]));
  }
  return `D${最大 + 1}`;
}

/** 序号归一: 取整数且 ≥1(0 / 负数 / 小数 / 认不出的一律回到第 1 幕) */
function 取序号(值: unknown): number {
  const 数 = Math.trunc(Number(值));
  return Number.isFinite(数) && 数 >= 1 ? 数 : 1;
}

/** 上次编排归一: 楼层/时间都认不出就整块丢掉(它是记账, 不是内容) —— 与 主线.ts 同口径 */
function 取上次编排(值: unknown): { 楼层: number; 时间: string } | null {
  if (!是对象(值)) return null;
  const 数 = Number(值['楼层']);
  const 楼层 = Number.isFinite(数) ? Math.max(0, Math.floor(数)) : 0;
  const 时间 = 文本(值['时间']);
  return 楼层 > 0 || 时间 ? { 楼层, 时间 } : null;
}

/** 从草稿里取一层(认不出给空对象): 草稿是外部(界面/用例)给的值, 形状不保证 */
function 取层(源: Record<string, unknown>, 键: string): Record<string, unknown> {
  const 值 = 源[键];
  return 是对象(值) ? 值 : {};
}

/** 造一笔库里的债: 键序固定(编号/内容/状态/结果/时间), 空的可选值不写进去 —— 与 主线.ts 的 造债 同款 */
function 造债(编号: string, 内容: string, 状态: 债状态, 结果: string, 时间?: string): 债 {
  const 一笔: 债 = { 编号, 内容, 状态 };
  if (结果) 一笔.结果 = 结果;
  if (时间) 一笔.时间 = 时间;
  return 一笔;
}

// ---------------------------------------------------------------------------
// 主线 → 草稿
// ---------------------------------------------------------------------------

/** 主线 → 草稿: 逐字段拷一份**可编辑的副本**(绝不把主线对象本身交给表单 v-model, 免得半路污染存档) */
export function 主线草稿(主线值: 主线): 主线草稿 {
  const 债表: unknown[] = Array.isArray(主线值?.债) ? 主线值.债 : [];
  return {
    终点: {
      类型: 文本(主线值?.终点?.类型),
      量级: 文本(主线值?.终点?.量级),
      候选: 文本(主线值?.终点?.候选),
    },
    幕: {
      序号: 取序号(主线值?.幕?.序号),
      结束条件: 文本(主线值?.幕?.结束条件),
      期限: 文本(主线值?.幕?.期限),
    },
    债: 债表.map(条目 => {
      const 一笔 = 是对象(条目) ? 条目 : {};
      return {
        编号: 归编号(一笔['编号']),
        内容: 文本(一笔['内容']),
        状态: 归一状态(一笔['状态']) || '欠着',
        结果: 文本(一笔['结果']),
      };
    }),
    回顾: 文本(主线值?.回顾),
    上次编排: 取上次编排(主线值?.上次编排),
  };
}

// ---------------------------------------------------------------------------
// 草稿 → 主线
// ---------------------------------------------------------------------------

/**
 * 把草稿收回主线(**不封顶**)。
 * 与 合并编排 有意不同的一点: **不判冻结** —— 终点/幕.结束条件/债.内容 用户改成什么就是什么
 * (那条"写下即冻结"是防 AI 的, 用户纠错不该被它拦住)。
 * 编号只读: 草稿里的编号原样保留、顺序不动(既不因为内容变了换号, 也不为了好看重排)。
 * 保存链路要的是封顶后的那一份, 走下面的 合并草稿; 这一条是给"条数/上限提示"看封顶前的样子。
 */
export function 合并草稿未封顶(主线值: 主线, 草稿: 主线草稿): 主线 {
  const 库 = 读取主线(主线值);
  const 源 = 是对象(草稿) ? (草稿 as unknown as Record<string, unknown>) : {};
  const 终点源 = 取层(源, '终点');
  const 幕源 = 取层(源, '幕');
  const 类型 = 文本(终点源['类型']);
  const 量级 = 文本(终点源['量级']);
  const 候选 = 文本(终点源['候选']);
  const 终点: 终点 = { 类型, 量级, 候选, 成形: !!(类型 && 量级 && 候选) };
  const 幕: 幕 = { 序号: 取序号(幕源['序号']), 结束条件: 文本(幕源['结束条件']), 期限: 文本(幕源['期限']) };
  // 时间按编号从存档里取回来(面板上不显示它, 也不该因为一次手改把记账丢掉)
  const 旧表 = new Map(库.债.map(一笔 => [一笔.编号, 一笔]));
  const 债源: unknown[] = Array.isArray(源['债']) ? 源['债'] : [];
  const 债: 债[] = [];
  for (const 条目 of 债源) {
    const 一笔 = 是对象(条目) ? 条目 : {};
    const 编号 = 归编号(一笔['编号']);
    const 内容 = 文本(一笔['内容']);
    // 空白行(刚点「加一条债」还没填的那一行)与"内容被清空 = 删掉这一条"是同一件事: 内容为空就不进库
    // (只填了结果、没写内容的行也落在这一条上 —— 一条没有内容的债没有意义)
    if (!内容) continue;
    债.push(造债(
      编号 || 下一个编号(债),
      内容,
      // 状态认不出按「欠着」兜底(下拉只有三个值, 认不出只可能是脏草稿)
      归一状态(一笔['状态']) || '欠着',
      // 结果照用户写的留着: 与 AI 那条路不同("欠着"不收结果), 用户把状态改回去时这里不替他删字
      文本(一笔['结果']),
      旧表.get(编号)?.时间,
    ));
  }
  const 结果: 主线 = { 终点, 幕, 债, 回顾: 文本(源['回顾']) };
  // 上次编排 不是可编辑字段: 草稿里带着就用它, 没有就沿用存档里的(于是点一次保存不会悄悄把锚点清掉)
  const 上次编排 = 取上次编排(源['上次编排']) ?? 库.上次编排;
  if (上次编排)
    结果.上次编排 = 上次编排;
  return 结果;
}

/**
 * 把草稿收回主线并 **封顶**(保存链路一律走这一条: 7 条会先淘汰最旧的「已还/作废」)。
 * 拆成两条是为了界面上的"N / 6"和上限提示 —— 封顶之后就看不出"保存会淘汰谁"了。
 */
export function 合并草稿(主线值: 主线, 草稿: 主线草稿): 主线 {
  return 封顶(合并草稿未封顶(主线值, 草稿));
}

// ---------------------------------------------------------------------------
// 加一条债
// ---------------------------------------------------------------------------

/** 空债(内容留给用户填): 库里的形状 */
function 空债(编号: string): 债 {
  return { 编号, 内容: '', 状态: '欠着' };
}

/**
 * 追加一条空债(主线级: 编号 = 现有最大编号 + 1, 淘汰过的号不复用)。
 * ⚠️ 它让**库里的债表**多一行, 而 内容 是空的 —— 读取主线 会把这种空条丢掉(那是存档/注入的严口径),
 * 所以要往"在编的草稿"里加行请用下面的 草稿加一条债, 不要在 加一条债 之后再过一次 主线草稿。
 */
export function 加一条债(主线值: 主线): 主线 {
  const 库 = 读取主线(主线值);
  const 结果: 主线 = { 终点: 库.终点, 幕: 库.幕, 债: [...库.债, 空债(下一个编号(库.债))], 回顾: 库.回顾 };
  if (库.上次编排)
    结果.上次编排 = 库.上次编排;
  return 结果;
}

/** 草稿加一条空债(面板的「加一条债」用它): 编号规则与 加一条债 共用 下一个编号(), 不各写一份 */
export function 草稿加一条债(草稿: 主线草稿): 主线草稿 {
  const 债表: 债草稿[] = Array.isArray(草稿?.债) ? 草稿.债 : [];
  return { ...草稿, 债: [...债表, { 编号: 下一个编号(债表), 内容: '', 状态: '欠着', 结果: '' }] };
}

// ---------------------------------------------------------------------------
// 超上限提示
// ---------------------------------------------------------------------------

/**
 * 债超过上限时给用户的一句话(没超 = null)。说的是**保存后会发生什么**, 两句规矩都在里面:
 * 淘汰最旧的「已还/作废」, 「欠着」的永不淘汰(全是欠着时上限拦不住, 也如实说)。
 */
export function 超上限提示(主线值: 主线): string | null {
  const 库 = 读取主线(主线值);
  if (库.债.length <= 债条数上限) return null;
  const 可淘汰 = 库.债.filter(一笔 => 一笔.状态 !== '欠着').length;
  if (可淘汰 === 0)
    return `债已有 ${库.债.length} 条, 超过上限 ${债条数上限}, 而且全是「欠着」: 「欠着」的永不淘汰, 保存后一条都不会少。`;
  const 淘汰数 = Math.min(库.债.length - 债条数上限, 可淘汰);
  return `债已有 ${库.债.length} 条, 超过上限 ${债条数上限}: 保存后会淘汰最旧的 ${淘汰数} 条「已还/作废」, 「欠着」的永不淘汰。`;
}

// 共用 · 模型往返 —— 「发请求 → 解析 → 校验 → 不合格就重试」只此一份
// ---------------------------------------------------------------------------
// 彼方、烟火与剧情导演各有一段这样的循环, 连重试节奏(接口错等 2s×次数、结构错等 0.6s)、
// 中断文案的处理, 三边都一字不差 —— 差别只有四件事:
//   - 解析: 各自切 JSON 候选/剥离思考字段的细节不同(烟火还要挑「世界推进」载荷), 各自传进来;
//   - 校验: 结构不合格时抛错, 抛什么错由各自决定;
//   - 错误分类: 彼方把"不是 JSON"也当可重试的错误, 烟火/导演当致命错误当场抛出;
//   - 文案: 名字、失败记录里的阶段名、给用户看的重试理由。
// 除了这几件, 其余全在这儿: 改一次重试策略, 三边同时生效。
//
// ⚠ 2026-11-19：`预填充` 从"三边共用"变成"两边用、一边不用" ——
//   彼方删了它（用户裁定：都自定义提示词了，自己加一段 assistant 就完了），
//   而烟火/剧情导演没有段列表，所以它们仍然用。
//   于是参数改成**可选**：不传 = 不启用。**不是删掉能力。**
//
// ⚠️ 重试**不再回喂**上一次的输出与错误原因(2026-10-09 用户决定去掉)。
//    原实现把上次输出的 JSON 片段 + 解析/校验错误原因拼成一条 user 消息, 接在"任务消息"后面,
//    好让模型看见自己错在哪、自己改 —— 那是为"模型不肯守格式"打的补丁。现在模型已经稳定守格式,
//    这个补丁只剩坏处: 每次重试都要多塞进一大段上一次的坏输出(白占上下文), 还可能被模型顺着抄一遍。
//    所以现在重试 = **原样重发同一份提示词**。
//    接口错(网络/超时/网关)的重试本来就不带任何回喂, 行为完全不变;
//    结构失败的重试仍保留 3 次上限, 是因为"输出被接口砍断"这类失败原样重推一次往往就成了
//    (2026-10-01 真机实测: 3284 字的世界 JSON 被砍断, 手动重推即成功)。
//
// 它不碰平台: 发请求 / 记日志 / 报进度 都是参数(与各自的 host 接缝接得上), 所以没有平台也能测。
//
// 2026-10-11 (v2.8.5 D1): 每次尝试各留一份账(`尝试: [{次, 原文, 错误}]`, 见 往返尝试),
//    失败那次**连同完整原文**一起留 —— 以前后一次直接盖掉前一次, 线上失败查不出模型当时到底输出了什么。
//
// 2026-11-01 (审查 P0-1, 已复现): 「解析候选」与「已通过校验的结果」不再共用 `parsed` 一个变量。
//    以前校验抛错后 `parsed` 仍是那份未通过的候选, 循环结束只判它是不是 null —— 三次都不合格
//    也会被当成成功返回(调用方拿它当 WorldData 用), 日志还写"重试后成功"。现在:
//      · 解析结果只活在每轮尝试的局部变量里; 只有 `校验()` 正常返回(且非 null/undefined)才提交;
//      · 尝尽了必抛**最后那次失败**, 成功日志只在真成功时出现;
//      · 取消(abort)在请求/解析/校验每个异步阶段之后、以及提交之前都再查一次 ——
//        请求开始前就取消则一次请求都不发; 重试等待本身可中断(不再等满 2s/600ms 才发觉用户已取消);
//      · 取消不算业务失败: 走 `中断文案` 那条既有出口, 不进 最近失败、不写红灯。
//    不变: 原样重试不回喂、三次上限、逐次完整原文、请求统计(成功/失败/中断都记)。
// ---------------------------------------------------------------------------

/** 失败发生在哪一步 */
type 错误阶段 = '请求' | '解析' | '校验';
/** 一次失败怎么处理: 接口错=等久一点直接重试; 反馈=有输出可重试(原样重发); 致命=当场抛出 */
type 错误归属 = '接口' | '反馈' | '致命';

/**
 * 一次尝试留下的账: **每一次都留一份, 失败那次也全留**。
 *
 * 以前每次尝试都写同一个 `response` 字段, 后一次直接盖掉前一次 —— 建档那轮第 1 次解析失败,
 * 3593 字原文只剩报错里嵌的前 300 字, 线上失败再也没法回放(用户已经为此发过一次火)。
 * 现在每次尝试各自一条: 有输出就留**完整原文**, 失败就把错因挂在同一条上。
 */
type 往返尝试 = { 次: number; 原文: string | null; 错误: string | null };

type 往返参数 = {
    /** 基础消息(每次尝试都原样重发这一份) */
    messages: any[];
    /**
     * 「预填充」：末位补一条 `assistant '{'` 引导模型直接从 JSON 开始。
     *
     * ── 2026-11-19：从**必填**改成**可选** ──
     *
     * 彼方删掉了这个功能（用户裁定：都自定义提示词了，自己加一段 assistant 就完了）。
     * 但**烟火与剧情导演还在用** —— 它们没有段列表，所以"自己加一段"那条替代路径对它们不成立。
     *
     * 所以这里保留能力、改成可选：**不传 = 不启用**。
     * ⚠ 不许为了"干净"把它整个删掉 —— 那等于拿彼方的理由删别人的功能。
     */
    预填充?: boolean;
    signal: AbortSignal;
    /** 真正发请求(线上是各自 api.ts 的 chatCompletion) */
    发请求: (messages: any[], options: { signal: AbortSignal }) => Promise<string>;
    /** 把原始输出解析成对象; 解析不了就抛错 */
    解析: (content: string) => any;
    /** 校验并规范化; 不合格就抛错 */
    校验: (parsed: any) => any;
    /** 错误分类(默认: 请求=接口, 解析/校验=反馈) */
    判断错误?: (error: Error, 阶段: 错误阶段) => 错误归属;
    /** 日志与提示里的名字, 如 '彼方' / '烟火' / '剧情导演' */
    名字: string;
    /** 结构失败记进日志时的阶段名, 如 '更新失败' / '推进失败' / '编排失败' */
    结构失败标签: string;
    /** 由错误信息推出"给用户看的重试理由"(三边文案不同, 各自传) */
    取重试理由: (error: Error) => string;
    /** 用户中断时的错误文案, 如 '用户已中断本次更新' / '用户已中断本次推进' */
    中断文案: string;
    /** 写日志页(线上是 debugStore.record) */
    记日志: (记录: any) => void;
    /** 报进度(线上是 updatingStore.message = 文字) */
    报进度: (文字: string) => void;
    /**
     * 最多尝试几次(默认 3)。调用方可以调小 —— 每次重试都是一次真实计费请求,
     * 而导演这一侧的请求经酒馆 generateRaw 走宿主事件, 重试还会连带触发别的插件(如记忆召回)。
     */
    最多尝试?: number;
    /** 已发生的请求统计(成功/失败/中断都会通知): 失败日志靠它才不会写成 0 次 0 秒 */
    记录请求统计?: (统计: { 请求耗时: number; 请求次数: number }) => void;
};

const 最多尝试默认 = 3;

async function 请求并校验(参数: 往返参数): Promise<{ parsed: any; 请求耗时: number; 请求次数: number }> {
    const { messages, 预填充, signal, 发请求, 解析, 校验, 名字, 结构失败标签, 中断文案, 记日志, 报进度 } = 参数;
    const 判断错误 = 参数.判断错误 ?? ((_error: Error, 阶段: 错误阶段) => (阶段 === '请求' ? '接口' : '反馈'));
    /**
     * **已通过校验**的结果 —— 这是本函数唯一允许交出去的东西。
     *
     * 2026-11-01 审查 P0-1(已复现): 以前 `parsed` 一个变量身兼两职 —— 先接解析结果, 再被
     * `校验()` 的返回值覆盖。校验抛错时它**没被清空**, 循环结束又只判 `parsed === null`,
     * 于是三次都不合格的候选照样被当成成功返回(调用方拿它当 WorldData 用), 日志还写"重试后成功"。
     * 现在: 解析出来的候选只活在每轮尝试的局部变量里; 校验正常返回(且非 null/undefined)才落到这里。
     */
    let 已通过: { 值: any } | null = null;
    let 失败: Error | null = null;
    let 请求耗时 = 0;
    let 请求次数 = 0;
    // 每一次尝试的账(见 往返尝试 的注释): 每次写日志都把当前这一摞带上, 谁也别盖谁
    const 尝试记录: 往返尝试[] = [];
    const 尝试快照 = () => 尝试记录.map(项 => ({ ...项 }));
    /** 写日志的唯一出口: 保证"每次尝试各留一份"总是跟着记录一起进面板 */
    const 记这次 = (额外: Record<string, unknown> = {}) => 记日志({ time: Date.now(), 尝试: 尝试快照(), ...额外 });
    const 这次 = () => 尝试记录[尝试记录.length - 1];
    /** 最近一次失败(用于"失败过但重试成功"的收尾: 那一轮不是失败, 别在日志上留红灯) */
    let 最近失败: string | null = null;
    /** 任何出口都把已发生的请求统计交出去(失败/中断也要), 否则失败日志会写成 0 次 0 秒 */
    const 通知统计 = () => 参数.记录请求统计?.({ 请求耗时, 请求次数 });
    const 抛出 = (error: Error): never => {
        通知统计();
        throw error;
    };
    /**
     * 取消检查: **每个异步阶段(请求 / 解析 / 校验)之后、以及提交结果之前**都要再查一次。
     * 取消是用户动作, 不是业务失败 —— 所以它走 `中断文案` 这条既有的中断出口,
     * 既不算一次结构失败(不进 最近失败、不写红灯), 也不会再多发一次请求。
     */
    const 检查中断 = (): void => {
        if (signal.aborted)
            抛出(Error(中断文案, { cause: (signal as { reason?: unknown }).reason }));
    };
    /** 可中断的重试等待: 等待期间用户取消 → 立刻抛出中断, 不用傻等 2s/600ms 再发现(更不会等到点后补发请求) */
    const 等或中断 = async (ms: number): Promise<void> => {
        检查中断();
        await new Promise<void>((resolve) => {
            const 收尾 = () => {
                clearTimeout(timer);
                signal.removeEventListener('abort', 收尾);
                resolve();
            };
            const timer = setTimeout(收尾, ms);
            signal.addEventListener('abort', 收尾, { once: true });
        });
        检查中断();
    };

    const 最多尝试 = Math.max(1, Math.min(最多尝试默认, Number(参数.最多尝试) || 最多尝试默认));
    for (let attempt = 1; attempt <= 最多尝试; attempt++) {
        // 开跑前就取消(换聊天/清空/停生成): 一次请求都不发, 直接按中断退出
        检查中断();
        // 重试 = 原样重发同一份提示词(不回喂上次输出, 也不带错误原因)
        const attemptMessages = [...messages];
        // 预填充: 末位补 '{', 引导模型直接从 JSON 开头输出(返回后要把 '{' 拼回, 见下)
        const last = attemptMessages[attemptMessages.length - 1];
        const prefill = 预填充 && attemptMessages.length > 0 && (last.role === 'user' || last.role === 'assistant') ? '{\n' : '';
        if (prefill)
            attemptMessages.push({ role: 'assistant', content: prefill });
        let content: string;

        try {
            const 开始 = Date.now();
            // 先记账再发请求: 接口报错/超时的那一次也算发生过
            请求次数 += 1;
            try {
                content = await 发请求(attemptMessages, { signal });
            }
            finally {
                请求耗时 += Date.now() - 开始;
            }
            if (prefill && String(content).trim().charAt(0) !== '{')
                content = prefill + content;
            // 有输出就先留档: 后面不管解析成不成功, 这一份原文都在
            尝试记录.push({ 次: attempt, 原文: content, 错误: null });
            记这次({ response: content });
        }
        catch (error) {
            if (signal.aborted)
                抛出(Error(中断文案, { cause: error }));
            失败 = error instanceof Error ? error : Error(String(error));
            const 归属 = 判断错误(失败, '请求');
            尝试记录.push({ 次: attempt, 原文: null, 错误: `接口调用失败: ${失败.message}` });
            if (归属 === '致命') {
                // 致命也要留账再抛: 否则调用方的 catch 只留下一句错因, 这次尝试就查不到了
                记这次();
                抛出(失败);
            }
            记这次({ error: `接口调用失败(第 ${attempt}/${最多尝试} 次): ${失败.message}` });
            最近失败 = `第 ${attempt} 次接口调用失败`;
            if (attempt < 最多尝试 && !signal.aborted) {
                报进度(`接口调用失败，正在重试（${attempt}/${最多尝试}）…`);
                console.warn(`[${名字}] 接口调用失败(第 ${attempt} 次), 正在重试…:`, 失败.message);
                await 等或中断(2000 * attempt);
            }
            continue;
        }

        // 请求这一阶段之后立刻再查一次取消: 已取消的这一份输出不进解析/校验, 更不会被提交
        检查中断();

        // 解析: 失败按 判断错误 的归属决定是重试还是当场抛出
        // (候选只放这里, 不碰 `已通过` —— 解析出来的东西还没有资格被交出去)
        let 候选: any;
        try {
            候选 = 解析(content);
        }
        catch (error) {
            失败 = error instanceof Error ? error : Error(String(error));
            const 归属 = 判断错误(失败, '解析');
            if (这次())
                这次()!.错误 = 失败.message;
            if (归属 === '致命' || 归属 === '接口') {
                记这次();
                抛出(失败);
            }
            最近失败 = `第 ${attempt} 次解析没过`;
            记这次({ error: `${结构失败标签}(第 ${attempt}/${最多尝试} 次): ${失败.message} · 输出 ${String(content ?? "").length} 字` });
            if (attempt < 最多尝试 && !signal.aborted) {
                const 理由 = 参数.取重试理由(失败);
                报进度(`正在重试（${attempt}/${最多尝试}）：${理由}`);
                console.warn(`[${名字}] ${理由}(第 ${attempt} 次)，正在重试…`);
                await 等或中断(600);
            }
            continue;
        }

        检查中断();

        // 校验: 结构不合格 → 原样重试; **只有校验正常返回, 结果才会落到 `已通过`**
        try {
            const 结果 = 校验(候选);
            // 校验的契约是"不合格就抛错"。返了 null/undefined = 既没通过也没说原因, 一律按不合格处理
            if (结果 === null || 结果 === undefined)
                throw Error('校验没有返回可用结果(返回了 null/undefined)');
            已通过 = { 值: 结果 };
        }
        catch (error) {
            失败 = error instanceof Error ? error : Error(String(error));
            const 归属 = 判断错误(失败, '校验');
            if (这次())
                这次()!.错误 = 失败.message;
            if (归属 === '致命') {
                记这次();
                抛出(失败);
            }
            最近失败 = `第 ${attempt} 次校验没过`;
            记这次({ error: `${结构失败标签}(第 ${attempt}/${最多尝试} 次): ${失败.message} · 输出 ${String(content ?? "").length} 字` });
            if (attempt < 最多尝试 && !signal.aborted) {
                const 理由 = 参数.取重试理由(失败);
                报进度(`正在重试（${attempt}/${最多尝试}）：${理由}`);
                console.warn(`[${名字}] ${理由}(第 ${attempt} 次)，正在重试…`);
                await 等或中断(600);
            }
            continue;
        }

        // 校验通过之后再查一次取消: 结果已经有了, 但用户已经取消 → 这一轮作废(不提交、不算失败)。
        // 放在 try 外面: 这里的抛出不能被上面的校验 catch 接走当成"第 N 次校验没过"。
        检查中断();
        if (已通过)
            break;
    }

    // 尝尽了: 一份**通过校验**的结果都没有 → 必须抛错, 抛最后那次失败的原因。
    // (以前的判据是"parsed 是不是 null", 校验失败后它还是那份坏候选, 于是坏输出被当成功返回)
    if (已通过) {
        // 失败过、但后来重试成功: 这一轮**不是失败**, 把红灯清掉, 只在备注里交代一声
        // (v2.8.5 D7: 恒定/残留的 error 会训练人忽略报错; 失败那次的完整原文在 尝试 里, 一个字都没丢)
        if (最近失败)
            记这次({ error: '', 备注: [`${最近失败}, 重试后成功(本轮已正常返回)`] });
        通知统计();
        return { parsed: 已通过.值, 请求耗时, 请求次数 };
    }
    return 抛出(失败 ?? Error('解析失败'));
}

export { 请求并校验 };
export type { 往返参数, 错误归属, 错误阶段, 往返尝试 };

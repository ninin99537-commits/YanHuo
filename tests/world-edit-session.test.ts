  check('保存真的发生了(有说明)', 结果.说明, '已保存事件修改, 注入内容已同步');
  check('还是那一条(id 沿用)', 结果.数据.事件.length, 1);
  check('id 没变', 结果.数据.事件[0].id, 'e1');
  check('用户改的标题写进去了', 结果.数据.事件[0].标题, '新名');
  check('推进改的描述没被旧草稿盖回去', 结果.数据.事件[0].描述, '推进后的描述');
  check('落了一次快照', 假.记.保存.length, 1);

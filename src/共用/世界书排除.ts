// 共用 · 世界书排除名单 —— 彼方 / 剧情导演 / 烟火 三家**同一套判定、同一套输入解析**
// ---------------------------------------------------------------------------
// 原来三家各写一份 isExcluded: 语义本来就一致(标题/备注包含即命中), 但各自演化; 输入那边更乱 ——
// 一家按"换行 + 半角逗号 + 全角逗号 + 顿号 + 空白"切, 一家只按逗号切, 一家按"逗号 + 顿号 + 空白"切,
// 于是同一份名单换个插件就得换个写法。现在两件事都收在这里:
//
//   解析名单(text)   —— **只认换行**: 逗号、顿号、分号统统当内容的一部分, 名字里有标点也不会被切开;
//   命中排除(条目, 名单) —— 标题/备注里**含这些字**就排除(不分大小写), 填一条 "[mvu_update]"
//                          就能挡掉 [mvu_update]1、[mvu_update]2…, 不用一条条写全名。
//
// 两个刻意的边界:
//   - **内容开头也参与匹配**: 条目名不可靠时(激活数据里可能只有 comment、没有 name)靠正文开头的标记
//     认自己写的条目, 如 "[彼方 · 幕后NPC状态]" / "[烟火 · 世界动向]" / "[剧情导演 · 编剧备忘]";
//   - **不匹配关键词(keys)**: 关键词多是角色名, 用它做排除会连带挡掉一大片人设条目 —— 要排某条, 写标题。
// 用例见 tests/worldbook-exclude.test.ts。

/**
 * 判定只需要条目上的这四个字段, 就在本地声明这四个 —— 不引用各家的完整条目类型:
 * `src/共用/` 不依赖任何一家插件, 反向 import 会让共用层绑死在彼方身上。
 *
 * `name` 与 `comment` 都要: 酒馆原生条目把显示名放在 `comment`(改名后 name 还是旧名),
 * 而主 AI 激活数据里可能只有 `name`; `key` 在两者都缺时兜底(见 条目标签)。
 * 四字段全可选: 调用方传进来的激活数据/世界书条目本来就可能缺字段。
 */
interface 排除条目形状 {
  name?: string;
  comment?: string;
  content?: string;
  key?: string | string[];
  /** 各家写入时打的归属标记（`extra.bifang` / `extra.yanhuo` / `extra.daoyan`） */
  extra?: Record<string, unknown>;
}

/**
 * 三家的世界书条目身份 —— **"别把别家的推演结论当设定读进来"**（2026-11-23）。
 *
 * ── 为什么需要 ──
 *
 *  三家都会往角色卡主世界书写一条常驻条目（彼方=NPC 状态卡、烟火=世界动向、导演=编剧备忘）。
 *  而"读世界书"走的是主 AI 的激活机制，**蓝灯常驻条目一定在里面** ——
 *  于是一家读世界书时，会读到**另外两家上一轮的输出**，把它当成世界设定。
 *  那是推演结果，不是设定；当设定用就是自我反馈。
 *
 * ── 为什么按标记认，不按名字子串 ──
 *
 *  名字会被用户改；子串匹配还会误伤（写"烟火"就排掉"烟火节的传说"）。
 *  三家写入时都打了稳定标记，条目名/正文开头只作兜底。
 *
 *  ⚠ 2026-11-23 更正：这里原来写「烟火的正文**没有**固定前缀」—— **那句是错的**。
 *    烟火的正文第一行确实是 `[烟火 · 世界动向]`（见下面的 `烟火世界动向锚`）。
 *    身份表里 `正文开头: null` 的真实含义是「**识别时不看正文开头**」（靠标记 + 条目名就够了），
 *    **不是**「正文没有前缀」。**「不用它识别」≠「它不存在」。**
 */
const 各家身份 = [
  { 家: '彼方', 正文开头: '[彼方 · 幕后NPC状态]', 条目名: '【彼方】NPC幕后生活', 标记: 'bifang' },
  { 家: '烟火', 正文开头: null, 条目名: '【烟火】世界动向', 标记: 'yanhuo' },
  { 家: '剧情导演', 正文开头: '[剧情导演 · 编剧备忘]', 条目名: '【剧情导演】编剧备忘', 标记: 'daoyan' },
] as const;

/**
 * 烟火常驻条目的**正文第一行锚** —— 全项目**只有这一处定义**。
 *
 * ⚠ 2026-11-23（需求方 #878）：收敛成共用常量。**这是最后一批代码改动的第一项。**
 *
 * ── 为什么要收敛（这不是"锦上添花"）──
 *
 *  这个锚原来在**三处各写一份字面量**：
 *
 *    ① 条件段（`prompts.ts`）的 `当` 函数：`worldbook.includes('[烟火 · 世界动向]')`
 *    ② 告警（`worldbook.ts`）的 `startsWith`
 *    ③ `worldbook.ts` 的 `放行条目正文锚` 表
 *
 *  **三处必须同值。** 而原来这条约束**只写在注释里** —— 将来改锚漏改一处，
 *  就**回到静默**：条件段不触发、或告警误报/漏报，而且**没有任何东西会红**。
 *
 *  ⇒ 那正是 `#871` 那条 P2 告警要治的**同一个根因**（两套信号不一致导致静默失效），
 *    只是还没发作。**用注释保证一致性 = 把同一个病留在原地。**
 *
 *  需求方 #878 的判断：
 *
 *  > 复查把这条降级成"锦上添花"，我不同意。
 *  > **你把一个新的一致性要求，用注释来保证 ⇒ 那正是 P2 的同一个根因，只是还没发作。**
 *
 * ── 为什么放在这里 ──
 *
 *  身份表（`各家身份`）在这里，识别函数（`是某家的条目`）也在这里。
 *  **锚是同一类东西**（"怎么认出烟火那一条"），所以放同一处。
 *
 * ── ⚠ 锚的**用途**与**口径**是两件事 ──
 *
 *  同一个常量，**两处用法不同**（有意的不对称，见 `worldbook.ts` 告警函数上方注释）：
 *
 *    | 谁 | 拿它跟什么比 | 口径 |
 *    |---|---|---|
 *    | 条件段（`prompts.ts`） | **整个组装后的世界书文本** | `includes` —— 宁松，不能漏 |
 *    | 告警（`worldbook.ts`） | **那一条自己的正文** | `startsWith` —— 宁严，不能误报 |
 *
 *  **共用常量保证的是"值相同"，不是"口径相同"。** 这两件事必须分开。
 *
 * ── 值的来源 ──
 *
 *  ✅ 核实过：`src/烟火_世界运转/公开摘要.ts` 的 `构建公开摘要` 里，
 *     `lines` 第一个元素就是 `'[烟火 · 世界动向]'` —— **正文第一行是代码写的，用户改不了**。
 *     所以它是可靠的锚（条目名用户能改，不能用）。
 */
export const 烟火世界动向锚 = '[烟火 · 世界动向]';

/** 这条条目是不是**别的插件**写的（不是本家）。`本家` 传自己那一家的名字。
 *
 *  ── ⚠ 2026-11-23（需求方 #836）：加了 `放行` 参数 ──
 *
 *  原来的语义是\"**排除所有别的插件**\"。但用户决定改用\"**彼方直接参考烟火的世界书条目**\"
 *  这个方案 —— 所以彼方侧要**放行烟火**、仍排导演。
 *
 *  ── 为什么不是\"删掉这一家\"或\"改身份表\" ──
 *
 *  ① 改 `各家身份` 表会连**识别**一起丢掉 —— 那条条目就再也认不出来了，
 *     而\"认出来\"是\"要不要排除\"的前提。将来要重新排除它就无从下手。
 *  ② 删掉调用点则把\"排彼方自己\"也一起丢了（那是防自我反馈的核心）。
 *
 *  ⇒ 所以保留**识别**，只让调用方声明\"这一家我放行\"。
 *    判断逻辑仍然**只有这一份**（单一构造点），两边共用。
 *
 *  ── ⚠ 放行名单是\"按家\"的，不是\"按条目\"的 ──
 *
 *  一旦放行烟火，**烟火的所有条目**都会进来（它目前只写一条，所以等价）。
 *  如果将来烟火写多条、而只想放行其中一条，那要改的是**条目级**的判定，
 *  不是这个函数 —— 那时再说。
 *
 *  @param entry 条目
 *  @param 本家 自己那一家的名字（`彼方` / `烟火` / `剧情导演`）
 *  @param 放行 **不排除**这些家的条目（默认空 = 排掉所有别的插件，即原行为）
 */
export function 是别的插件条目(
  entry: 排除条目形状 | null | undefined,
  本家: string,
  放行: readonly string[] = [],
): boolean {
  if (!entry)
    return false;
  const 名 = String(entry.name ?? '').trim();
  const 备注 = String(entry.comment ?? '').trim();
  const 内容 = String(entry.content ?? '').trim();
  for (const 家 of 各家身份) {
    if (家.家 === 本家)
      continue;
    // ⚠ 调用方放行了这一家 → 不当成\"别的插件\"（但**仍然认得出它**，见上方注释）
    if (放行.includes(家.家))
      continue;
    if (entry.extra?.[家.标记] === true)
      return true;
    if (名 === 家.条目名 || 备注 === 家.条目名)
      return true;
    if (家.正文开头 && 内容.startsWith(家.正文开头))
      return true;
  }
  return false;
}

/**
 * 这条条目**是不是 `家` 这一家**写的。
 *
 * ⚠ 2026-11-23（需求方 #871 / 复查 P2）：新增。
 *
 * ── 为什么需要它 ──
 *
 *  `是别的插件条目(entry, 本家, 放行)` 只能回答「它是不是**别的**插件写的」，
 *  回答不了「它是**哪一家**写的」。而放行告警需要知道：
 *  **这条被放行进来的，到底是哪一家？它的正文有没有那个锚？**
 *
 * ── 为什么加在这里，而不是在 `worldbook.ts` 里再写一份 ──
 *
 *  身份表（`各家身份`）在这里，识别规则也在这里。
 *  在别处再写一份「怎么认出烟火」= 两份实现迟早会漂
 *  （这正是本文件存在的理由，见文件头）。
 *
 *  ⇒ **识别逻辑仍然只有一份**：`是别的插件条目` 与它共用同一张表、同一套判定，
 *    只是**过滤方向不同**（一个问"是不是别家"，一个问"是不是这一家"）。
 *
 * @param entry 条目
 * @param 家 要认的那一家（`彼方` / `烟火` / `剧情导演`）
 */
export function 是某家的条目(entry: 排除条目形状 | null | undefined, 家: string): boolean {
  if (!entry)
    return false;
  const 身份 = 各家身份.find(x => x.家 === 家);
  if (!身份)
    return false;
  const 名 = String(entry.name ?? '').trim();
  const 备注 = String(entry.comment ?? '').trim();
  const 内容 = String(entry.content ?? '').trim();
  if (entry.extra?.[身份.标记] === true)
    return true;
  if (名 === 身份.条目名 || 备注 === 身份.条目名)
    return true;
  if (身份.正文开头 && 内容.startsWith(身份.正文开头))
    return true;
  return false;
}

/**
 * 把设置里那段文本切成名单: **只按换行**切, 每行 trim, 空行丢掉。
 * 逗号 `,` `，`、顿号 `、`、分号 `;` `；` 都是内容的一部分 —— 条目名里本来就可能带这些字符,
 * 以前按它们切会把一个名字切成几条, 于是"排除不生效"又找不出原因。
 */
export function 解析名单(text: string): string[] {
  return String(text ?? '')
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(Boolean);
}

/** 名单里任意一串出现在条目的标题/备注里(不分大小写), 或条目内容以它开头 → 排除 */
export function 命中排除(entry: 排除条目形状 | null | undefined, excludes: string[]): boolean {
  if (!entry || !Array.isArray(excludes) || excludes.length === 0)
    return false;
  const 名 = String(entry.name ?? '').trim().toLowerCase();
  const 备注 = String(entry.comment ?? '').trim().toLowerCase();
  const 内容 = String(entry.content ?? '').trim().toLowerCase();
  return excludes.some((item: string) => {
    const 词 = String(item ?? '').trim().toLowerCase();
    if (!词)
      return false;
    return (名 !== '' && 名.includes(词))
      || (备注 !== '' && 备注.includes(词))
      || (内容 !== '' && 内容.startsWith(词));
  });
}

/** 条目名(给人看的): 主 AI 激活数据在 comment/key, getWorldbook 在 name */
export function 条目标签(entry: 排除条目形状 | null | undefined): string {
  return (typeof entry?.comment === 'string' && entry.comment)
    || (typeof entry?.name === 'string' && entry.name)
    || (entry?.key ? (Array.isArray(entry.key) ? entry.key.join('、') : String(entry.key)) : '')
    || '(未命名条目)';
}

/**
 * 日志用的一句话: `排除条目挡掉 3 条([mvu_update]1、[mvu_update]2…)`(不带前后分隔符, 各家自己接)。
 * 一条都没挡到就返回空串, 不往日志里塞噪音 —— 但"挡到了却不吭声"同样不行:
 * 排除名单静默失效时, 用户只能看着一堆条目被发出去还以为是别的原因。
 */
export function 排除说明(挡掉: string[], 最多 = 3): string {
  if (!Array.isArray(挡掉) || 挡掉.length === 0)
    return '';
  const 举例 = 挡掉.slice(0, 最多).join('、');
  return `排除条目挡掉 ${挡掉.length} 条(${举例}${挡掉.length > 最多 ? '…' : ''})`;
}

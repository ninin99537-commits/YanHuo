console.log('\n[5] 双解析器 × 多变体: 严格 JSON 不认、JSON5 认得的写法照样收下');
{
  const json5文本 = [
    '{',
    "  世界: { 时间: '2025-11-15 21:30' },",
    '  事件: [],',
    '}',
  ].join('\n');
  check('JSON.parse 确实不认这份(无引号键 / 单引号 / 尾逗号)', (() => {
    try {
      JSON.parse(json5文本);
      return 'parse 竟然成功了';
    }
    catch (error) {
      return error instanceof Error ? error.constructor.name : String(error);
    }
  })(), 'SyntaxError');
  const 载荷 = 取载荷(json5文本);
  check('JSON5 兜住了它', 载荷.世界.时间, '2025-11-15 21:30');
  check('事件也跟着过来', 载荷.事件, []);

  // 多变体: 同一个候选要先剥思考字段、再转义裸控制字符, 才轮得到解析器
  const 双料 = [
    '{',
    '  "静默思考流程": "想',
    '一下",',
    '  "世界": { "时间": "2025-11-15 21:30", "总览": "甲',
    '乙" },',
    '  "事件": []',
    '}',
  ].join('\n');
  check('双料候选(剥思考字段 + 转义裸控制字符两层都用上)', 取载荷(双料).世界.总览, '甲\n乙');

  // 同一个根因的另一面: 思考值是单行时, 剥离会按"对象结尾 }"那条退路把整个对象切空。
  // 注释里承诺的"切坏则自动降级到原始文本" —— 现在空对象不再被当成载荷, 于是真的降级成功,
  // 结果回到原始候选(思考字段原样留在里面, 由上层校验去管)。
  const 单行思考 = '{"静默思考流程": "想一下", "世界": {"时间": "2025-11-15 21:30"}, "事件": []}';
  const 降级 = 取载荷(单行思考);
  check('切坏后降级: 数据还在', 降级.世界.时间, '2025-11-15 21:30');
  check('降级回来的就是原始候选(思考字段原样留着)', Object.keys(降级), ['静默思考流程', '世界', '事件']);
}


  check('事件冲突说清楚了', 事件结果.拒绝, '这条事件已经不在清单里了, 请重新打开再改');
  check('没有偷偷添一条事件', 事件结果.数据.事件.length, 1);

  // 势力: 与那道门同一句文案
  const 势力会话 = 打开势力会话(旧世界({ 势力: { 北境商帮: 势力({ 目标: '控盐' }) } }), '北境商帮')!;

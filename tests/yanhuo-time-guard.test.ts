console.log('\n[6] 带天数的跳跃词: "三天后 / 15天后 / 十五天后"(v2.8 补)');
{
  const 旧 = '2025年09月19日·周五·夜';
  const 三 = 建立世界时间约束('【最新回复】\n三天后，城门开了。', 旧);
  check('三天后 → 类型=正文相对跳跃', 三.类型, '正文相对跳跃');
  check('三天后 → 范围恰好 3~3 天(2025-09-22)', [三.最早日期?.月, 三.最早日期?.日, 三.最晚日期?.日], [9, 22, 22]);
  ok('三天后 → 允许 9/22', (() => { try { 校验世界时间('2025年09月22日·周一·上午', 三); return true; } catch { return false; } })());
  throws('三天后 → 9/23 仍被拒', () => 校验世界时间('2025年09月23日·周二·上午', 三));
  const 十五 = 建立世界时间约束('【最新回复】\n十五天后，他回来了。', 旧);
  check('十五天后 → 15 天(不许被读成"五天后")', [十五.最早日期?.月, 十五.最早日期?.日], [10, 4]);
  const 阿拉伯 = 建立世界时间约束('【最新回复】\n15天后，他回来了。', 旧);
  check('15天后 → 15 天', [阿拉伯.最早日期?.月, 阿拉伯.最早日期?.日], [10, 4]);
  const 十 = 建立世界时间约束('【最新回复】\n十天后，他回来了。', 旧);
  check('十天后 → 10 天', [十.最早日期?.月, 十.最早日期?.日], [9, 29]);
  // 表格里的老词一个都不许被新逻辑挤掉
  const 十几 = 建立世界时间约束('【最新回复】\n十几天后，他回来了。', 旧);
  check('"十几天后"仍是 10~19 天', [十几.最早日期?.日, 十几.最晚日期?.月, 十几.最晚日期?.日], [29, 10, 8]);
  check('"两周后"仍是 14 天', (() => { const c = 建立世界时间约束('【最新回复】\n两周后，他回来了。', 旧); return [c.最早日期?.日, c.最晚日期?.日]; })(), [3, 3]);

  // v2.8 词表整张复查(策划要求): 判据 = 卡片正文会自然写出它, 而它确实表示跨日
  const 距旧 = (日期: any) => Math.round((日期.天 - 解析日期(旧)!.天) / 86400000);
  const 复查表: [string, number, number][] = [
    ['翌日，他走了。', 1, 1],
    ['隔日，城门开了。', 1, 1],
    ['转天，他回来了。', 1, 1],
    ['第二日，他回来了。', 1, 1],
    ['数日后，他回来了。', 2, 14],
    ['十来天后，他回来了。', 10, 19],
    ['一个星期后，他回来了。', 7, 7],
    ['一星期后，他回来了。', 7, 7],
    ['一周后，他回来了。', 7, 7],
    ['半个月后，他回来了。', 15, 15],
    ['大半年后，他回来了。', 180, 270],
    ['半年后，他回来了。', 180, 184],
    ['三天之后，他回来了。', 3, 3],
    ['三日后，他回来了。', 3, 3],
    ['一个月之后，他回来了。', 28, 31],
  ];
  for (const [句, 少, 多] of 复查表) {
    const c = 建立世界时间约束(`【最新回复】\n${句}`, 旧);
    check(`词表复查「${句.slice(0, 5)}」→ ${少}~${多} 天`, [c.类型, c.最早日期 && 距旧(c.最早日期), c.最晚日期 && 距旧(c.最晚日期)], ['正文相对跳跃', 少, 多]);
  }
  // 故意不收的(注释里写了理由, 这里钉住"别哪天顺手收了")
  check('"半晌后"不算跳跃(几小时, 不跨日)', 建立世界时间约束('【最新回复】\n半晌后，他回来了。', 旧).类型, '无正文时间');
  check('"片刻之后"同理', 建立世界时间约束('【最新回复】\n片刻之后，他回来了。', 旧).类型, '无正文时间');
  check('"当天夜里"不算跳跃(0 天)', 建立世界时间约束('【最新回复】\n当天夜里，他回来了。', 旧).类型, '无正文时间');
  const 日期后缀 = 建立世界时间约束('【最新回复】\n10月14日之后，他回来了。', 旧);
  check('"10月14日之后"不是跳跃词(别读成"14 天后")', [日期后缀.类型, 日期后缀.跳跃], ['无正文时间', null]);
  const ISO后缀 = 建立世界时间约束('【最新回复】\n2026-10-14日之后，他回来了。', 旧);
  check('"2026-10-14日之后"按绝对日期认, 不是"14 天后"', [ISO后缀.类型, ISO后缀.跳跃], ['正文绝对时间', null]);
}

console.log('\n[7] 跨日事实 + 完成日志三态(v2.8 §2/§3)');
{
  const 旧 = '2025-09-19 20:00';
  check('跨了 3 日', 算跨世界日(建立世界时间约束('【最新回复】\n三天后。', 旧), 旧), { 最少: 3, 最多: 3 });
  check('没有时间线索 → 未跨日(0 日)', 算跨世界日(建立世界时间约束('【最新回复】\n场景继续。', 旧), 旧), { 最少: 0, 最多: 0 });
  check('开局(没有上轮世界时间) → 首次, 不是"不可判定"', 算跨世界日(建立世界时间约束('【最新回复】\n场景继续。', ''), ''), '首次');
  check('古代卡(旧时间解析不出来) → 无法判定, 整条降级',
    算跨世界日(建立世界时间约束('【最新回复】\n三天后。', '元和三年·三月初七'), '元和三年·三月初七'), null);
  check('日志 · 开局第一轮单列"首次推进"(不是误报成"时间不可解析")',
    描述世界日差('', '2025-11-15 21:30'), '首次推进（无上轮世界时间, 不计跨日）');
  check('日志 · 跨了 k 世界日', 描述世界日差(旧, '2025-09-22 09:00'), '跨了 3 世界日');
  check('日志 · 同一天(哪怕过了几小时) = 未跨日', 描述世界日差(旧, '2025-09-19 23:40'), '未跨日（沿用上轮日期）');
  check('日志 · 旧时间不可解析 → 第三态', 描述世界日差('元和三年·三月初七', '元和三年·三月初八'), '时间不可解析, 无法判定');
  check('日志 · 新时间不可解析 → 也是第三态(铁律: 不许落成"未推进")', 描述世界日差(旧, '元和三年·三月初八'), '时间不可解析, 无法判定');
  check('日志 · 原样沿用且不可解析 → 第三态, 附"沿用上轮日期"', 描述世界日差('元和三年·三月初七', '元和三年·三月初七'), '时间不可解析, 无法判定（沿用上轮日期）');
  check('日志 · 世界时间被写回更早日期 → 第四态, 不与"未跨日"混为一谈', 描述世界日差(旧, '2025-09-17 20:00'), '世界时间回退到更早日期（较上轮早 2 日）');
}


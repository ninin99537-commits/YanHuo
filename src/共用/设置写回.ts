// 共用 · 设置写回(2026-11-12 架构深化 ⑨)
// ---------------------------------------------------------------------------
// 一套纪律, 三家各写了一遍, 其中一家没写:
//
//   ① 全局变量优先、整份读到之后才允许写回(**没读到过就不许写** —— 否则拿内存里的默认值
//      把用户的真实设置(含接口密钥)覆盖掉。这条是 剧情导演 P1 事故的教训);
//   ② 写回**只写相对基线改动过的字段**。`insertOrAssign` / `variables[键] = 整份` 是**整键替换**,
//      会把别的窗口/别的设备刚改的字段一起冲掉;
//   ③ 深合并, 不是 `{ ...prev, ...next }` —— 那只是顶层合并, `接口` 这种子对象会被整块覆盖,
//      地址与密钥一起没;
//   ④ 删除得按路径真删(深合并表达不了删除: 面板 `delete 接口预设[名字]` 之后那份还会被合并回来)。
//
// 现状(评审实测): 烟火四样都有; 剧情导演有 ②③; **彼方只有一条整键覆盖 + 一条顶层浅合并**,
// 而且整键那条仍被两条迁移路径调用 —— 多窗口/多设备同时改设置时, 后落盘的一方赢, 另一方丢字段。
//
// 这个 module 只出两样东西: **四个纯函数**(合并/差异/删键/三方基线, 各自的用例直接打它们)
// 与**一个闸门**(基线 + 可写回 + 只写差异)。宿主怎么读怎么写由调用方给 —— 共用不认识酒馆。
import { klona } from 'klona';

/** 普通对象(非数组、非 null) —— 递归的边界判断 */
export function 是普通对象(value: unknown): value is Record<string, any> {
  return !!value && typeof value === 'object' && !Array.isArray(value);
}

/** 两份叶子是否等同(数组按整体比) */
export function 同一份(左: any, 右: any): boolean {
  try {
    return JSON.stringify(左) === JSON.stringify(右);
  } catch {
    return 左 === 右;
  }
}

/**
 * 深合并: `prev` 里**本次没提到的子字段**原样保留。
 * `{ ...prev, ...next }` 是浅合并 —— 子对象会被内存里那份(可能陈旧/残缺)整块覆盖。
 * 数组当作**一个整体字段**替换(不按元素合并: 用户删掉一项数组元素时, 按元素合并会把它加回来)。
 */
export function 深合并(prev: any, next: any): any {
  if (!是普通对象(prev) || !是普通对象(next)) return klona(next);
  const 结果: Record<string, any> = klona(prev);
  for (const [键, 值] of Object.entries(next)) {
    if (值 === undefined) continue; // undefined = 本次不涉及, 别拿它去清存储里的值
    结果[键] = 是普通对象(结果[键]) && 是普通对象(值) ? 深合并(结果[键], 值) : klona(值);
  }
  return 结果;
}

export interface 差异结果 {
  /** 有没有任何改动 */
  有: boolean;
  /** 只含改动过的叶子(可安全深合并进远端) */
  值: any;
  /** 基线里有、现在没了的键路径(深合并表达不了删除) */
  删: string[][];
}

/**
 * 相对写回基线的差异: 只收集**真正改动过的叶子字段**(递归)。
 *
 * `收集删除` 关掉时(默认)不找"删掉的键" —— 剧情导演那一份就是这么用的: 它的面板没有"删某个键"
 * 的操作, 多出一路删除只会让写回语义变宽。默认值保守, 需要的人显式打开。
 */
export function 取差异(基线: any, 当前: any, 选项: { 收集删除?: boolean } = {}, 路径: string[] = []): 差异结果 {
  if (当前 === undefined) return { 有: false, 值: undefined, 删: [] };
  if (是普通对象(基线) && 是普通对象(当前)) {
    const 差: Record<string, any> = {};
    const 删: string[][] = [];
    let 有 = false;
    for (const [键, 值] of Object.entries(当前)) {
      const 子 = 取差异(基线[键], 值, 选项, [...路径, 键]);
      if (子.有) {
        差[键] = 子.值;
        有 = true;
      }
      if (子.删.length) 删.push(...子.删);
    }
    if (选项.收集删除) {
      for (const 键 of Object.keys(基线)) {
        if (键 in 当前 || 基线[键] === undefined) continue;
        删.push([...路径, 键]);
        有 = true;
      }
    }
    return { 有, 值: 差, 删 };
  }
  return { 有: !同一份(基线, 当前), 值: klona(当前), 删: [] };
}

/** 按路径摘掉键(写存储与推进基线走同一个动作, 基线才不会留着已被删的键) */
export function 应用删除(目标: any, 删: string[][]): any {
  for (const 路径 of 删) {
    let 节点: any = 目标;
    for (let 层 = 0; 层 < 路径.length - 1; 层++) 节点 = 是普通对象(节点) ? 节点[路径[层]] : undefined;
    if (是普通对象(节点)) delete 节点[路径[路径.length - 1]];
  }
  return 目标;
}

/**
 * 三方差量: 以"默认值"为底, 判断本地那片叶子到底是不是**用户改的**。
 *   · 本地 == 默认 → 用户没动过这片: 基线取**本地**(=默认), 写回时不会去碰存储里的真值;
 *   · 本地 != 默认 → 用户确实改了: 基线取**全局**, 于是差异里只剩用户这一片。
 *
 * 只在"这个 store 从没成功读到过全局"时用一次 —— 否则"读不到时填的全默认草稿"
 * 会被当成"用户改了整份"灌进存储。
 */
export function 三方基线(默认值: any, 全局: any, 本地: any): any {
  if (是普通对象(默认值) && 是普通对象(全局) && 是普通对象(本地)) {
    const 结果: Record<string, any> = {};
    const 键集 = new Set([...Object.keys(默认值), ...Object.keys(全局), ...Object.keys(本地)]);
    for (const 键 of 键集) 结果[键] = 三方基线(默认值[键], 全局[键], 本地[键]);
    return 结果;
  }
  return 同一份(本地, 默认值) ? klona(本地) : klona(全局);
}

/** 存储端口: 怎么读那一份、怎么把整份写回去 —— 由调用方提供(共用不认识酒馆) */
export interface 写回端口 {
  /** 读存储里的那一份(键不存在 → undefined) */
  读: () => any;
  /** 把整份写回存储(同步; 失败就抛, 由调用方记日志) */
  写: (份: any) => void;
}

export interface 写回闸门 {
  /** 成功读到远端之后调用。键不存在也传 undefined —— 那是"新装用户", 同样算读到了 */
  记录基线: (远端: any) => void;
  /** 有没有成功读到过。没读到过就**不许写**(否则默认值会覆盖用户的真实设置) */
  可写回: () => boolean;
  /** 当前基线(诊断/用例用) */
  当前基线: () => any;
  /**
   * 只把相对基线的改动写回远端。
   * @returns 是否真的写了(闸门关着 / 没有改动 → false)
   */
  立即写: (当前: any) => boolean;
  /**
   * 明确的"首次落盘": 不经过差异, 把这份直接写成远端并成为新基线。
   * 只给**迁移**用(从 localStorage / 旧脚本变量搬过来) —— 那时存储里本来就没有这一份。
   */
  首次落盘: (当前: any) => boolean;
}

export interface 写回选项 {
  /**
   * 要不要找"基线里有、现在没了"的键并按路径删。
   * 默认 true(方舟/彼方那种有"删掉一项预设"的界面的插件需要它);
   * 像剧情导演那样"设置对象永远由 schema 补满、键不会消失"的插件可以关掉 ——
   * 关掉时写回语义更窄, 与它原来的行为逐字一致。
   */
  收集删除?: boolean;
}

/**
 * 建一个写回闸门。
 *
 * 三条语义写死在这里, 调用方不用再各自记一遍:
 *   · 没记录过基线 → `立即写` 返回 false 且**一个字节都不写**;
 *   · 有基线但没改动 → 也不写(避免无意义的落盘与"最后写入者赢");
 *   · 有改动 → 读远端 → 深合并(远端, 差异) → 按路径删 → 写, 然后基线推进到当前。
 */
export function 建写回闸门(端口: 写回端口, 选项: 写回选项 = {}): 写回闸门 {
  const 收集删除 = 选项.收集删除 ?? true;
  let 基线: any = undefined;
  let 读成功过 = false;
  return {
    记录基线(远端) {
      基线 = klona(远端);
      读成功过 = true;
    },
    可写回() {
      return 读成功过;
    },
    当前基线() {
      return 基线;
    },
    立即写(当前) {
      if (!读成功过) return false;
      const 差异 = 取差异(基线, 当前, { 收集删除 });
      if (!差异.有) {
        基线 = klona(当前);
        return false;
      }
      const 远端 = 端口.读();
      const 合并后 = 应用删除(深合并(远端, 差异.值), 差异.删);
      端口.写(合并后);
      基线 = klona(当前);
      return true;
    },
    首次落盘(当前) {
      const 份 = klona(当前);
      端口.写(份);
      基线 = klona(份);
      读成功过 = true;
      return true;
    },
  };
}


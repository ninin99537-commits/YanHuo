/** 事件行(竖线表数据行, 与表头列对位): 标题 | 时间 | 地点 | 描述 | 前情 | 渠道 | 势力 | 代表人物 */
function formatEventLine(event: WorldEvent): string {
  return [
    event.标题,
    event.时间 || '—',
    event.地点 || '—',
    event.描述 || '—',
    event.前情 || '—',
    event.渠道 || '—',
    event.势力 || '—',
    event.代表人物 || '—',
  ].join(' | ');
}

/** 生成注入给主 AI 的世界动向文本(世界自己的动向, 不分主角知晓区块) */
export function buildInjectionPrompt(data: WorldData, settings: Settings): string {
  const lines: string[] = ['[烟火 · 世界动向]'];
  lines.push(
    '以下是这个世界正在发生的动向——世界自己的事, 大多与主角无关。角色只能通过合理渠道(亲历/听说/告示/报道/情报)得知, 不许全知; 不要把所有动向都塞进主角的见闻里。' +
      (settings.运转.注入隐秘事件 ? '「隐秘事件」各方秘而不宣, 主角绝不可能知道, 除非你能给出正当的信息渠道(亲历/走漏/密报外流等)。' : ''),
  );
  const world = data.世界;
  const head: string[] = [];
  if (world.时间) head.push(`时间: ${world.时间}`);
  if (world.氛围) head.push(`氛围: ${world.氛围}`);
  if (world.总览) head.push(`总览: ${world.总览}`);
  if (head.length > 0) lines.push(head.join('\n'));

  // 五层与势力清单的注入表(表头/列序/判据全在 世界字段表.ts, 这里只按层生成; 候选 4)
  const 大势层 = 取层('大势');
  const trends = Object.entries(data.大势 ?? {}).filter(([, t]) => t && 该注入(大势层, t));
  if (trends.length > 0) {
    lines.push('大势(世界层面正在流动的趋势):');
    lines.push(注入表头(大势层));
    for (const [name, t] of trends) lines.push(注入行(大势层, name, t));
  }

  // 地域
  const 地域层 = 取层('地域');
  const regions = Object.entries(data.地域 ?? {}).filter(([, r]) => r && 该注入(地域层, r));
  if (regions.length > 0) {
    lines.push('地域(各地的当前局势):');
    lines.push(注入表头(地域层));
    for (const [name, r] of regions) lines.push(注入行(地域层, name, r));
  }

  // 节令(临近的公共节点, 公开知识; 受层开关控制)
  const 节令层 = 取层('节令');
  const occasions = (data.节令 ?? []).filter(o => o && 该注入(节令层, o));
  if (settings.运转.节令历法 && occasions.length > 0) {
    lines.push('节令(临近的公共节点, 公开知识, 可自然融入场景):');
    lines.push(注入表头(节令层));
    for (const o of occasions) lines.push(注入行(节令层, o.名称, o));
  }

  // 指标(慢变世界状态; 受层开关控制)
  const 指标层 = 取层('指标');
  const metrics = Object.entries(data.指标 ?? {}).filter(([, m]) => m && 该注入(指标层, m));
  if (settings.运转.世界指标 && metrics.length > 0) {
    lines.push('世界指标(慢变世界状态, 可作氛围与角色判断的背景, 不必直接报数值):');
    lines.push(注入表头(指标层));
    for (const [name, m] of metrics) lines.push(注入行(指标层, name, m));
  }

  // 势力动向(全部注入——注入是主AI唯一的世界记忆, 不设条数上限)
  const 势力层 = 取层('势力');
  const factionEntries = Object.entries(data.势力 ?? {}).filter(([, f]) => f && 该注入(势力层, f));
  if (factionEntries.length > 0) {
    lines.push('势力暗流(幕后组织的当前盘算与动向, 大多与主角无关):');
    lines.push(注入表头(势力层));
    for (const [name, f] of factionEntries) lines.push(注入行(势力层, name, f));
  }

  // 事件分公开/隐秘(最新在前, 不设条数上限)。`事件` 里本来就没有墓碑, 所以只按标题过滤即可——
  // 墓碑住在 `已了结`, 与注入主 AI 这条路完全无关
  const events = (data.事件 ?? []).filter(event => event.标题).reverse();
  const open = events.filter(event => event.隐秘 !== '隐秘');
  const secret = events.filter(event => event.隐秘 === '隐秘');
  const EVENT_TABLE_HEAD = '标题 | 时间 | 地点 | 描述 | 前情 | 渠道 | 势力 | 代表人物';
  if (open.length > 0) {
    lines.push('世界事件(公共层动态, 大多与主角无关, 可自然衔接但不要整段播报):');
    lines.push(EVENT_TABLE_HEAD);
    lines.push(...open.map(formatEventLine));
  }
  if (settings.运转.注入隐秘事件 && secret.length > 0) {
    lines.push('隐秘事件(各方秘而不宣的暗中行动, 主角绝不可能知道, 除非给出正当信息渠道):');
    lines.push(EVENT_TABLE_HEAD);
    lines.push(...secret.map(formatEventLine));
  }

  lines.push('(以上是世界动向: 它们是世界自己的事, 大多与主角无关; 角色只能通过合理渠道得知, 不要写成全员皆知, 也不要主动大段播报。)');
  return lines.join('\n');
}

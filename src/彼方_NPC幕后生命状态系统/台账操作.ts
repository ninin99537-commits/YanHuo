// 彼方 · 事务台账的「读一眼 / 改一条」——界面与数据变更共用的一层纯操作。
//
// 台账本身的规则(编号怎么分配、内容为什么冻结、怎么去重与封顶)在 事务台账.ts, 这里一条都不重复;
// 这一层只解决另外两件两边都要做、又都不属于台账规则的事:
//   1 **显示**: 卡里的值可能是旧格式字符串、也可能是数组(见 事务台账.ts 的迁移), 界面上还要把
//     「进行中」排在前面、把已办压在后面 —— 摊在 .vue 里就没法用用例钉住(界面只有构建能发现问题);
//   2 **改一条**: 玩家在面板上把某条事务改成 已完成/已作废(顺带写/改结果)。数据变更.ts 写回卡里
//     时用的就是这里的 改一条事务, 于是"状态合不合法、编号存不存在、进行中要不要留结果"只有一份口径。
//
// 全是纯函数: 不改入参、返回新对象(界面拿它渲染, 数据变更拿它写卡)。
import { 读取台账 } from './事务台账';
import type { 事务状态, 幕后事务 } from './事务台账';

/** 状态卡里承载事务台账的字段名。界面(渲染/表单)与数据变更(草稿合并/改状态)都从这里取,
 *  免得同一个字符串在几处各写一遍、改一处漏一处。 */
export const 台账字段 = '未完成事项';

/** 三个合法状态; 顺序就是界面上那排按钮的顺序(进行中 → 已完成 → 已作废) */
export const 台账状态表: 事务状态[] = ['进行中', '已完成', '已作废'];

/** 编号里的数字(T3 → 3); 认不出当 0, 只用于排序, 不影响数据 */
function 编号数字(编号: unknown): number {
    const match = String(编号 ?? '').trim().match(/^T(\d+)$/);
    return match ? Number(match[1]) : 0;
}

/**
 * 状态校验(归一): 只认三个枚举值, 认不出返回空串 —— 调用方据此决定是"拒绝改动"还是别的兜底。
 * 前后空白容忍("已完成 " 也算已完成)。
 */
export function 合法状态(value: unknown): 事务状态 | '' {
    const 文本 = String(value ?? '').trim();
    return 台账状态表.includes(文本 as 事务状态) ? 文本 as 事务状态 : '';
}

/**
 * 界面显示用的台账: 先把卡里的值(旧字符串/数组/脏值)规范成数组, 再排序 ——
 * 「进行中」在前(按编号升序 = 写下的先后), 已办(已完成/已作废)在后(按编号降序 = 最近收束的在前)。
 * **只是显示顺序**: 写回卡里时用的一定是没排过序的原数组(台账顺序才是"谁更旧"的依据, 见 事务台账.ts 的 封顶)。
 */
export function 显示台账(value: unknown): 幕后事务[] {
    const 台账 = 读取台账(value);
    const 进行中 = 台账.filter(事务 => 事务.状态 === '进行中').sort((甲, 乙) => 编号数字(甲.编号) - 编号数字(乙.编号));
    const 已办 = 台账.filter(事务 => 事务.状态 !== '进行中').sort((甲, 乙) => 编号数字(乙.编号) - 编号数字(甲.编号));
    return [...进行中, ...已办];
}

/**
 * 改一条事务的**状态与结果**(内容/时间/编号原样不动: 内容写下即冻结, 要改内容就作废旧条另开新条)。
 * - 状态不合法(不是三个枚举之一)、或台账里没有这个编号 → 返回 null("没改成", 调用方据此提示, 绝不静默);
 * - 新状态是「进行中」时**不带结果**(结果只对完成/作废有意义, 与 合并台账 同一口径);
 * - 传空串结果 = 清掉这条已有结果; 纯函数, 不改入参。
 */
export function 改一条事务(记录: unknown, 编号: string, 新状态: unknown, 结果: string): 幕后事务[] | null {
    const 状态 = 合法状态(新状态);
    if (!状态)
        return null;
    const 台账 = 读取台账(记录);
    const 目标 = String(编号 ?? '').trim();
    if (!目标 || !台账.some(事务 => 事务.编号 === 目标))
        return null;
    return 台账.map(事务 => {
        if (事务.编号 !== 目标)
            return 事务;
        const 新事务: 幕后事务 = { 编号: 事务.编号, 时间: 事务.时间, 内容: 事务.内容, 状态 };
        const 结果文本 = String(结果 ?? '').trim();
        if (状态 !== '进行中' && 结果文本)
            新事务.结果 = 结果文本;
        return 新事务;
    });
}

/** 状态 → 样式类名(在 .vue 里用 is-ongoing/is-done/is-void 区分醒目与弱化; 类名保持 ASCII, 免得选择器写中文) */
export function 状态类(状态: unknown): 'ongoing' | 'done' | 'void' {
    const 合法 = 合法状态(状态);
    if (合法 === '进行中')
        return 'ongoing';
    if (合法 === '已作废')
        return 'void';
    return 'done';
}

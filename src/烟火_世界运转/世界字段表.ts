/** 一条字段的全部知识: 数据里的键、表单标签、枚举、旧快照名与 AI 别名、是否多行 */
export interface 字段定义 {
  键: string;
  /** 表单/展示里的标签(缺省=键) */
  标签?: string;
  /** 枚举白名单: 表单下拉用它, 越界值按 兜底 纠偏 */
  枚举?: readonly string[];
  /** 枚举越界时的兜底值(缺省=枚举第一项) */
  兜底?: string;
  /** 旧快照里的旧字段名(读到就迁移过来, 如 势力范围 ← 领地) */
  旧名?: string[];
  /** AI 载荷里的别名(提示词之外模型自己换的名字, 如 头面人物 ← 首领) */
  别名?: string[];
  /** 滚动总结字段: AI 填"无变化/同上"这类占位词时沿用旧值 */
  占位沿用?: boolean;
  /** 表单里用多行输入 */
  多行?: boolean;
}

/** 五层常驻档案的层名(世界数据变更.ts 那道门收的"层") */
export type 世界条目层 = '地域' | '大势' | '伏笔' | '节令' | '指标';
/** 表里全部层名 = 五层档案 + 势力清单 */
export type 世界层名 = 世界条目层 | '势力';

export interface 世界层定义 {
  名: 世界层名;
  /** 注入表头与面板分组用的名字 */
  标签: string;
  /** 映射层是「名称→字段」, 数组层是一串条目 */
  形态: '映射' | '数组';
  /** 名字字段: 映射层是草稿里的键(势力没有这一项, 名字就是映射的键); 数组层是条目里的那个字段 */
  名称键: string;
  容量: number;
  /** 字段清单(键的顺序就是表单顺序与快照里的键顺序); 数组层含名称字段(排第一) */
  字段: 字段定义[];
  /** 注入给主 AI 的竖线表列(顺序照注入表; null = 这一层不进注入) */
  注入列: string[] | null;
  /** 注入判据: 这些字段里有一个非空, 这一条才进注入(缺省=名称非空) */
  注入判据?: string[];
  /** 提示词 JSON 示例里「名称」那个占位写法(缺省=名称键) */
  示例名?: string;
}


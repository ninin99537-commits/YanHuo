import type { Settings } from './schema';

/** 同一份策略同时交给提示词、准入校验与完整条目选择。额度始终是上限，不是产量。 */
export const 运转密度表 = {
  稀疏: { 每轮新增: 1, 大跳新增: 1, 进行中上限: 8, 重点跟进: 3, 公开摘要: 2, 提示: '先消化旧事；没有新条件时允许连续零新增。' },
  正常: { 每轮新增: 1, 大跳新增: 2, 进行中上限: 10, 重点跟进: 6, 公开摘要: 4, 提示: '先维护旧事并推进到达条件的线；当进行中事态偏少（如不足3件）且组织动向、形势、暗线或时代格局具备独立动因时，可自然展开不同领域的平行公共事态（当日已有其他领域的事件并不排斥外部世界另有一条独立线索浮现，不要求必须出现激烈冲突）。' },
  密集: { 每轮新增: 2, 大跳新增: 3, 进行中上限: 14, 重点跟进: 10, 公开摘要: 6, 提示: '世界处于活跃期：积极推动多方博弈、形势外溢与暗线兑现，在额度内充分展开公共事态。' },
} as const;
export type 运转密度 = keyof typeof 运转密度表;

export function 取运转策略(运转: Pick<Settings['运转'], '世界密度'> & Partial<Settings['运转']>) {
  const base = 运转密度表[运转.世界密度 ?? '正常'];
  return {
    ...base,
    每轮新增: 运转.每轮新增上限 ?? base.每轮新增,
    大跳新增: 运转.大跳新增上限 ?? base.大跳新增,
    重点跟进: 运转.重点跟进数 ?? base.重点跟进,
    公开摘要: 运转.公开摘要条数 ?? base.公开摘要,
    摘要目标字符: 运转.摘要目标字符 ?? 6000,
  };
}

  check('名称那一条回落到点开的名字', 会话.草稿.fields.名称, '东街');
  check('其余字段取数据仓里的值', [会话.草稿.fields.概况, 会话.草稿.fields.局势], ['集市所在', '宵禁']);
  check('基准就是数据仓里那一条', 会话.基准, 数据.地域.东街);
  ok('基准是拷贝, 不是同一个对象(改草稿不该动数据)', 会话.基准 !== 数据.地域.东街);
  check('刚打开没改过', 会话改过(会话), false);


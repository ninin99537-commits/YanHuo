let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  }
  else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

/** 假环境: 只记账, 不碰酒馆 */
function 假环境() {
  const 记 = { 保存: [] as WorldData[], 同步: [] as WorldData[] };
  return {
    记,
    环境: {
      注入世界书条目: true,
      保存: (数据: WorldData) => { 记.保存.push(数据); return true; },
      清空: () => {},
      同步世界书: (数据: WorldData) => { 记.同步.push(数据); },
    },
  };
}

function 旧世界(部分: Partial<WorldData> = {}): WorldData {
  return { ...emptyData(), ...部分 };
}

function 事件(部分: Partial<WorldEvent> & { 标题: string }): WorldEvent {
  return {
    id: '',
    描述: '描述',
    地点: '',
    时间: '2025-01-01 08:00',
    规模: '要事',
    传播: '本埠',
    渠道: '',
    势力: '',
    阶段: '进行',
    隐秘: '公开',
    代表人物: '',
    前情: '',
    演变: [],
    ...部分,
  } as WorldEvent;
}

function 势力(部分: Record<string, string> = {}) {
  return { 目标: '', 动向: '', 前情: '', 势力范围: '', 对外关系: '', 头面人物: '', ...部分 };
}

